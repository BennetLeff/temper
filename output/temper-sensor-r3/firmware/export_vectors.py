"""Export golden vectors from the Python reference for the firmware host tests.

Writes (generated, do not edit):
  firmware/test/pan_temp_estimator_vectors.h  estimator: step, ramp, h_c extremes, noise
  firmware/test/contact_check_vectors.h       D1: loss on 4 pans, food on 3, nominal on 4

Estimator vectors: open-loop runs of the sensor-r2/r3 truth plant with the C1
cartridge and a fixed power profile; the reference is estimator_study.KFNoPower
(double, numeric Jacobian) with screen.py's C1 constants, run on the quantised
readings that are written to the header.

D1 vectors: closed-loop screen.run() cases (kind loss / food / nominal_det,
identical seeds to screen.py), cut to 230-320 s, quantised, then replayed
through screen.py's own D1 code (ref.d1_replay) for the reference decisions.

Run: python export_vectors.py   (about 30 s)
"""
from __future__ import annotations

import json
import os
import sys
from multiprocessing import Pool
from pathlib import Path

import numpy as np

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import evidence_compare as EC  # noqa: E402  (reference_platform on the evidence written)
import ref  # noqa: E402
from ref import es, screen  # noqa: E402

FW_TEST = HERE.parent.parent.parent / "firmware" / "test"
WIN = (2300, 3200)          # D1 vector window, samples (230.0-319.9 s)


def est_case(spec):
    name, pan, h, profile, noise, T_hot, n = spec
    screen.apply(ref.C1)
    tr = ref.HotTruth(es.PANS[pan], h, 0.82, 7, T_hot=T_hot)
    rng = np.random.default_rng(11)
    ys, rims = [], []
    for k in range(n):
        P = profile(k * es.DT_CTRL)
        for _ in range(round(es.DT_CTRL / es.DT_SIM)):
            tr.step(P, h)
        ys.append(round(tr.Tel + noise * rng.standard_normal(), 3))
        rims.append(round(tr.sink() + es.NTC_BIAS, 3))
    kf = es.KFNoPower(es.T_AMB, screen.NOISE, h_c=ref.C1["h_nom"])
    refs = [kf.step(y, (0.0, r)) for y, r in zip(ys, rims)]
    return name, ys, rims, refs


EST_CASES = [
    ("ramp_cast_iron_h888", "cast_iron_26", 888.0, lambda t: 1200.0, 0.2, None, 1500),
    ("clad_h21946_step_down", "triply_clad_24", 21946.0, lambda t: 800.0 if t < 60 else 200.0, 0.2, None, 1200),
    ("carbon_h300_stress", "carbon_steel_28", 300.0, lambda t: 1000.0, 0.2, None, 1200),
    ("hot_pan_placed_cast_iron", "cast_iron_26", 3396.0, lambda t: 0.0, 0.2, 200.0, 600),
    ("noise_1K_carbon_h3633", "carbon_steel_28", 3633.0, lambda t: 1000.0, 1.0, None, 1200),
]


def d1_jobs():
    """screen.main()'s C1 loss / food / nominal_det jobs with their seeds."""
    c = ref.C1
    screen.apply(c)
    spread = screen.h_spread(c)
    i = 16 + 12                       # design and stress cases come first
    jobs = []
    for pan, (lo, hi) in spread.items():
        h_mid = (lo * hi) ** 0.5
        jobs.append(("loss", pan, h_mid, 500 + i, 250.0, None))
        jobs.append(("nominal", pan, h_mid, 500 + i, None, None))
        if pan != "disc_pot_water_1l5":
            jobs.append(("food", pan, h_mid, 500 + i, None, 250.0))
        i += 1
    return jobs


def d1_case(job):
    kind, pan, h, seed, loss_at, food_at = job
    c = ref.C1
    screen.apply(c)
    L, info = screen.run("C1", pan, h, 0.82, "kf_fixed", seed, c["h_nom"], loss_at, food_at, True)
    tr = screen.Truth(es.PANS[pan], h, 0.82, seed)
    a = 0.82 / (tr.C.sum() + tr.Cw)
    rise = 35.0 if tr.Cw else 50.0
    n = len(L)
    k = np.arange(n)
    ntc = es.T_AMB + rise * (1 - np.exp(-((k + 1) * es.DT_CTRL) / 300.0)) + es.NTC_BIAS
    p_applied = np.concatenate([[0.0], L[:-1, 6]])
    lo, hi = WIN
    y = np.round(L[lo:hi, 5], 3)
    th = np.round(L[lo:hi, 2], 3)
    p = np.round(p_applied[lo:hi], 1)
    nt = np.round(ntc[lo:hi], 3)
    tau_off = c["C_CAP"] / c["G_LEAK"]
    rep = ref.d1_replay(list(y), list(th), list(p), list(nt), a, tau_off)
    closed = {"suspect_at": info["suspect_at"], "detected_at": info["detected_at"], "probes": info["probes"]}
    return dict(name=f"{kind}_{pan}", kind=kind, pan=pan, h=h, a=a, tau_off=tau_off, y=y, th=th, p=p, ntc=nt,
                rep=rep, closed=closed)


def carr(name, vals, fmt):
    vals = [fmt % v for v in vals]
    rows = ["    " + ",".join(vals[i:i + 12]) + "," for i in range(0, len(vals), 12)]
    return f"static const float {name}[] = {{\n" + "\n".join(rows) + "\n};\n"


def write_est(cases):
    k = ref.c1_constants()
    h = ["/* GENERATED by output/temper-sensor-r3/firmware/export_vectors.py - do not edit.",
         " * Pan-temperature estimator golden vectors: Python double reference",
         " * (estimator_study.KFNoPower, screen.py C1 constants) on quantised readings. */",
         "#ifndef PAN_TEMP_ESTIMATOR_VECTORS_H", "#define PAN_TEMP_ESTIMATOR_VECTORS_H", "",
         "#include <stdint.h>", "",
         f"#define PTV_C_CAP {k['c_cap']!r}", f"#define PTV_C_EL {k['c_el']!r}",
         f"#define PTV_G_BOND {k['g_bond']!r}", f"#define PTV_G_LEAK {k['g_leak']!r}",
         f"#define PTV_AREA {k['area']!r}", f"#define PTV_H_NOM {k['h_nom']!r}",
         f"#define PTV_SIGMA {screen.NOISE!r}", f"#define PTV_T0 {es.T_AMB!r}", ""]
    for name, ys, rims, refs in cases:
        h.append(carr(f"ptv_{name}_y", ys, "%.3f"))
        h.append(carr(f"ptv_{name}_rim", rims, "%.3f"))
        h.append(carr(f"ptv_{name}_ref", refs, "%.5f"))
    h.append("typedef struct { const char *name; uint16_t n; const float *y; const float *rim; const float *ref; } ptv_case_t;")
    h.append("static const ptv_case_t ptv_cases[] = {")
    for name, ys, _, _ in cases:
        h.append(f'    {{ "{name}", {len(ys)}u, ptv_{name}_y, ptv_{name}_rim, ptv_{name}_ref }},')
    h.append("};")
    h.append("#define PTV_N_CASES (sizeof(ptv_cases) / sizeof(ptv_cases[0]))")
    h += ["", "#endif", ""]
    (FW_TEST / "pan_temp_estimator_vectors.h").write_text("\n".join(h))


def write_d1(cases):
    h = ["/* GENERATED by output/temper-sensor-r3/firmware/export_vectors.py - do not edit.",
         " * Contact-check (D1) golden vectors: closed-loop screen.py runs cut to",
         f" * samples {WIN[0]}-{WIN[1] - 1} ({WIN[0] / 10:.0f}-{(WIN[1] - 1) / 10:.1f} s), quantised, with the",
         " * reference decisions from screen.py's D1 code replayed on the same data.",
         " * Loss and food start at 250 s = sample 200 of the window. -1 = never. */",
         "#ifndef CONTACT_CHECK_VECTORS_H", "#define CONTACT_CHECK_VECTORS_H", "",
         "#include <stdint.h>", ""]
    for c in cases:
        n = c["name"]
        h.append(carr(f"ccv_{n}_y", c["y"], "%.3f"))
        h.append(carr(f"ccv_{n}_th", c["th"], "%.3f"))
        h.append(carr(f"ccv_{n}_p", c["p"], "%.1f"))
        h.append(carr(f"ccv_{n}_ntc", c["ntc"], "%.3f"))
    h.append("typedef struct { const char *name; int kind; float a; float tau_off; uint16_t n;\n"
             "    const float *y; const float *th; const float *p; const float *ntc;\n"
             "    int suspect_k; int lost_k; int probes; } ccv_case_t;")
    h.append("enum { CCV_LOSS = 0, CCV_FOOD = 1, CCV_NOMINAL = 2 };")
    h.append("static const ccv_case_t ccv_cases[] = {")
    kinds = {"loss": "CCV_LOSS", "food": "CCV_FOOD", "nominal": "CCV_NOMINAL"}
    for c in cases:
        r = c["rep"]
        s = -1 if r["suspect_k"] is None else r["suspect_k"]
        lo = -1 if r["lost_k"] is None else r["lost_k"]
        n = c["name"]
        h.append(f'    {{ "{n}", {kinds[c["kind"]]}, {float(c["a"])!r}f, {float(c["tau_off"])!r}f, {len(c["y"])}u, '
                 f"ccv_{n}_y, ccv_{n}_th, ccv_{n}_p, ccv_{n}_ntc, {s}, {lo}, {r['probes']} }},")
    h.append("};")
    h.append("#define CCV_N_CASES (sizeof(ccv_cases) / sizeof(ccv_cases[0]))")
    h += ["", "#endif", ""]
    (FW_TEST / "contact_check_vectors.h").write_text("\n".join(h))


def main():
    worst = ref.check_kfref()
    assert worst < 1e-9, f"KFRef differs from es.KFNoPower by {worst}"
    with Pool(min(10, os.cpu_count() or 1)) as pool:
        d1 = pool.map(d1_case, d1_jobs())
    est = [est_case(s) for s in EST_CASES]
    write_est(est)
    write_d1(d1)
    summary = {"kfref_vs_KFNoPower_max_abs_K": worst, "d1": []}
    for c in d1:
        r = c["rep"]
        summary["d1"].append({"case": c["name"], "replay_suspect_t": None if r["suspect_k"] is None else (WIN[0] + r["suspect_k"]) / 10,
                              "replay_lost_t": None if r["lost_k"] is None else (WIN[0] + r["lost_k"]) / 10,
                              "replay_probes_in_window": r["probes"], "closed_loop": c["closed"],
                              "probe_log": [(WIN[0] + k) / 10 for k, *_ in r["probe_log"]]})
    (HERE / "vectors-summary.json").write_text(json.dumps(EC.stamp(summary), indent=1) + "\n")
    print(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
