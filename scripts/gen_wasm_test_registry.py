def select_crate(name: str) -> CrateSpec:
    """Point the module-level globals at ``name``'s crate.

    Globals rather than threaded parameters because
    ``tools/wasm/gen_test_family_map.py`` imports ``ELIGIBLE``, ``SRC`` and
    ``module_path`` from this module.  They keep meaning `temper-drc-rs` unless
    something calls this, so that importer is unaffected.
    """
    global CRATE_SPEC, CRATE, SRC, ELIGIBLE, FAMILIES, FAMILY_BY_ENTRY
    spec = CRATES[name]
    CRATE_SPEC = spec
    CRATE = REPO_ROOT / "packages" / name
    SRC = CRATE / "src"
    if spec.eligible is not None:
        ELIGIBLE = list(spec.eligible)
    else:
        ELIGIBLE = [
            (d.rel, d.ident)
            for d in discover_eligible(SRC, spec.absent_features)
            if not d.excluded
        ]
    FAMILIES = spec.families
    FAMILY_BY_ENTRY = {
        (module_path(rel), ident): spec.family_of(rel) for rel, ident in ELIGIBLE
    }
    return spec


