#!/usr/bin/env python3
"""Generate (and drift-check) a crate's ``wasm32`` test registry.

Why this exists
---------------
``cargo test``'s libtest harness cannot target ``wasm32-unknown-unknown``:
there is no process model, no threads, and no ``std::process::exit``.  So the
Worker tier cannot run ``cargo test`` -- it has to call each test *function*
individually from a ``wasm32`` entry point.

The obstacle is Rust privacy, not compilation.  Unit tests live in
``#[cfg(test)] mod tests { fn ... }``: both the module and the functions are
private, so nothing outside the defining module can name them.  A registry
built anywhere *else* in the crate therefore cannot reference them.

The fix used here is deliberately the boring one: emit a ``pub const``
**inside each test module**, where the private functions are in scope, and
aggregate those consts from the crate root.  No proc macro, no ``inventory``
link-section magic (which needs ``__wasm_call_ctors`` to actually fire on
``wasm32-unknown-unknown``), no build script.  The registry is plain Rust that
``grep`` can find and a reviewer can read.

What it does to the sources
---------------------------
For every eligible test module it rewrites the gate

    #[cfg(test)]
    mod tests {

into

    #[cfg(any(test, feature = "wasm-test-registry"))]
    #[allow(dead_code, unused_imports, clippy::unwrap_used, clippy::expect_used)]
    pub(crate) mod tests {

It also rewrites ``#[test]`` to ``#[cfg_attr(test, test)]`` inside those
modules.  That second rewrite is not cosmetic: ``#[test]`` is a built-in macro
that *deletes* the function unless the crate is being compiled as a test
binary, so without it the registry would compile against functions that do not
exist.  Under a plain ``cargo test`` both rewrites collapse back to exactly
what was there before, so native behaviour is unchanged.

Which crates this covers
------------------------
One registry per crate, selected with ``--crate``.  ``temper-drc-rs`` was
first; ``temper-geometry`` followed once the same enabling work was done for
it.  The two differ only in how their eligible module list is decided:

* ``temper-drc-rs`` names its modules explicitly (``ELIGIBLE_DRC_RS``), which
  is what it has always done and what its committed registry was generated
  from.
* ``temper-geometry`` *discovers* them (:func:`discover_eligible`) and applies
  exclusion **predicates** with named reasons.  A hand-maintained list silently
  omits a newly added test module -- the drift gate only compares the registry
  against the list, so a module missing from the list is invisible to it.
  Discovery closes that hole: a new ``#[cfg(test)] mod`` in an eligible file
  makes ``--check`` fail until the registry is regenerated.

Usage
-----
    python3 scripts/gen_wasm_test_registry.py                          # write
    python3 scripts/gen_wasm_test_registry.py --check                  # CI gate
    python3 scripts/gen_wasm_test_registry.py --crate temper-geometry
    python3 scripts/gen_wasm_test_registry.py --census                 # explain

The gate has two arms, and it took a real escape to learn that one was not
enough:

1. **Drift.**  Regenerate into memory and fail if the committed registry has
   drifted from the actual ``#[test]`` functions, so a test added to a *listed*
   module cannot silently stay out of the Worker tier.
2. **Unregistered modules** (:func:`check_unregistered`).  Arm 1 iterates the
   list, so a whole module *missing* from the list is not drift to it -- it is
   invisible.  ``src/ipc.rs`` landed with the ``temper-ipc`` crate-fold on
   2026-08-09 and its eleven IPC-2221/2152 kernel tests sat outside the tier
   while ``--check`` reported green.  Arm 2 starts from the source: every
   ``#[cfg(test)]`` module holding ``#[test]`` functions must either be
   registered or carry a stated structural reason.

The gate is per-crate: run it once for each crate that has a registry.
``scripts/regen_derived.py`` does exactly that.

``--census`` prints every ``#[cfg(test)]`` module the crate has, registered or
not, with the reason for each exclusion.  Use it to check that an exclusion is
structural rather than convenient.
"""

