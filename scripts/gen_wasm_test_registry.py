def find_module_span(lines: list[str], ident: str) -> tuple[int, int, int]:
    """Locate ``mod <ident>`` and return ``(attr_start, decl_idx, body_end)``.

    ``body_end`` is the index of the closing brace line, or ``-1`` for a file
    module (``mod tests;``), whose body is a separate file.
    """
    decl = re.compile(
        rf"^\s*(?:pub(?:\([^)]*\))?\s+)?mod\s+{re.escape(ident)}\s*(\{{|;)\s*$"
    )
    for i, line in enumerate(lines):
        m = decl.match(line)
        if not m:
            continue
        # Walk backwards over the attribute block that gates this module.
        start = i
        while start > 0 and lines[start - 1].lstrip().startswith("#["):
            start -= 1
        if m.group(1) == ";":
            return start, i, -1
        depth = 0
        for j in range(i, len(lines)):
            depth += lines[j].count("{") - lines[j].count("}")
            if depth == 0:
                return start, i, j
        raise SystemExit(f"unbalanced braces for mod {ident}")
    raise SystemExit(f"could not find `mod {ident}`")


def fn_cfgs(lines: list[str], test_attr_idx: int) -> list[str]:
    """``#[cfg(...)]`` attributes attached to the test fn at ``test_attr_idx``.

    A test function can carry its own configuration gate --
    ``#[cfg(not(target_arch = "wasm32"))]`` on a test that asserts a native-host
    property, for instance.  The function then does not exist in a ``wasm32``
    build, so a registry entry naming it does not compile.  Collecting the gates
    here lets :func:`generated_block` repeat them on the entry, which keeps the
    registry exactly as configured as the functions it points at.

    Only the contiguous attribute/doc-comment block above the ``#[test]`` is
    scanned, so this cannot pick up an attribute belonging to a previous item.
    """
    cfgs = []
    i = test_attr_idx - 1
    while i >= 0:
        stripped = lines[i].strip()
        if stripped.startswith("#["):
            if stripped.startswith("#[cfg("):
                cfgs.append(stripped)
        elif not stripped.startswith("//"):
            break
        i -= 1
    return list(reversed(cfgs))


def collect_test_fns(lines: list[str]) -> list[tuple[str, list[str]]]:
    """``(fn name, its own #[cfg] attributes)`` for every test in ``lines``.

    The walk from ``#[test]`` down to its ``fn`` has to step over the
    attributes in between, and an attribute is not necessarily one line.
    ``temper-io-types``'s ``dag_expr::depth_boundary`` writes::

        #[cfg_attr(test, test)]
        #[allow(
            clippy::expect_used,
            reason = "..."
        )]
        fn rejects_the_first_frame_past_the_ceiling() {

    An earlier version scanned a fixed five-line window and stopped at the
    first line not *starting* with ``#[``, so the continuation line
    ``clippy::expect_used,`` ended the walk and the function was dropped from
    the registry — silently, because the drift arm regenerates through this
    same function and so agrees with itself.  ``--census`` counts ``#[test]``
    attributes directly and disagreed (144 vs 143), which is how it surfaced.

    Bracket depth is tracked instead, so a multi-line attribute is stepped
    over whole.  At depth 0 the walk still stops at the first line that is
    neither an attribute, a comment, nor blank, so it can never run past its
    own item into the next one.
    """
    names: list[tuple[str, list[str]]] = []
    for i, line in enumerate(lines):
        if not TEST_FN.match(line):
            continue
        depth = 0
        for j in range(i + 1, len(lines)):
            stripped = lines[j].strip()
            if depth == 0:
                m = FN_NAME.match(lines[j])
                if m:
                    names.append((m.group(1), fn_cfgs(lines, i)))
                    break
                if stripped and not stripped.startswith(("#[", "//")):
                    break
            depth = max(0, depth + lines[j].count("[") - lines[j].count("]"))
    return names


def strip_generated(lines: list[str], ident: str) -> list[str]:
    """Drop only *this* module's generated block.

    Scoped by ident because one file can hold two test modules (`board.rs`),
    and a blanket strip would delete the sibling block on the second pass.
    """
    begin, end = BEGIN.format(ident=ident), END.format(ident=ident)
    out, skipping = [], False
    for line in lines:
        if line.strip() == begin:
            skipping = True
            continue
        if line.strip() == end:
            skipping = False
            continue
        if not skipping:
            out.append(line)
    return out


def generated_block(
    indent: str, mod_path: str, ident: str, fns: list[tuple[str, list[str]]]
) -> list[str]:
    """The ``pub const`` that makes private ``#[test]`` fns reachable."""
    q = f"{mod_path}::{ident}"
    body = [
        f"{indent}{BEGIN.format(ident=ident)}",
        f"{indent}/// Every `#[test]` in this module, as a callable the `wasm32`",
        f"{indent}/// entry point can invoke by index.  Generated because these",
        f"{indent}/// functions are private to this module and unreachable from",
        f"{indent}/// anywhere a registry could otherwise live.",
        f"{indent}pub const WASM_TESTS: &[(&str, fn())] = &[",
    ]
    for fn, cfgs in fns:
        prefix = "".join(f"{cfg} " for cfg in cfgs)
        body.append(f'{indent}    {prefix}("{q}::{fn}", {fn}),')
    body += [f"{indent}];", f"{indent}{END.format(ident=ident)}"]
    return body


def render_root(entries: list[tuple[str, str, int]]) -> str:
    total = sum(n for _, _, n in entries)
    lines = [
        f"//! The `wasm32` test registry for `{CRATE_SPEC.name}`.",
        "//!",
        "//! Generated by `scripts/gen_wasm_test_registry.py`; run it after adding a",
        "//! test to any listed module, and `--check` gates drift in CI.",
        "//!",
        "//! `cargo test`'s libtest harness cannot target `wasm32-unknown-unknown`,",
        "//! so the Worker tier calls each test function individually instead of",
        "//! running a test binary.  This module is the flat, indexable list of them.",
        "//!",
        "//! Only modules that survive `--no-default-features` appear here.  Tests",
        "//! inside `#[cfg(feature = \"python\")]` modules are structurally absent",
        f"//! from a `wasm32` build and {CRATE_SPEC.census_note}.",
        "//!",
        *CRATE_SPEC.extra_notes,
        *(["//!"] if CRATE_SPEC.extra_notes else []),
        *CRATE_SPEC.sharding_note,
        "",
        "/// A single test: its fully qualified name and a nullary callable.",
        "///",
        "/// Failure is signalled by panicking, exactly as under libtest.  On",
        "/// `wasm32-unknown-unknown` a panic aborts (the target has no unwinding on",
        "/// stable), which surfaces to the host as a WebAssembly trap -- so the",
        "/// runner catches the trap rather than a `Result`.",
        "pub type WasmTest = (&'static str, fn());",
        "",
        f"/// All {total} eligible tests, in a stable order.  Each entry is",
        "/// gated on the per-family `wasm-registry-<family>` feature; enable",
        "/// all families (`wasm-test-registry`) or individual ones.",
        "pub const ALL: &[&[WasmTest]] = &[",
    ]
    for mod_path, ident, _ in entries:
        family = FAMILY_BY_ENTRY.get((mod_path, ident), "infra")
        lines.append(
            f"    #[cfg(feature = \"wasm-registry-{family}\")]"
            f" crate::{mod_path}::{ident}::WASM_TESTS,"
        )
    lines += [
        "];",
        "",
        "/// Total number of registered tests *in the currently-selected families*.",
        "pub fn count() -> usize {",
        "    ALL.iter().map(|m| m.len()).sum()",
        "}",
        "",
        "/// The test at `index` in the flattened registry.",
        "pub fn get(index: usize) -> Option<&'static WasmTest> {",
        "    let mut remaining = index;",
        "    for module in ALL {",
        "        if remaining < module.len() {",
        "            return Some(&module[remaining]);",
        "        }",
        "        remaining -= module.len();",
        "    }",
        "    None",
        "}",
        "",
    ]
    return "\n".join(lines)


def ancestor_decls(rel: str) -> list[tuple[str, str]]:
    """``(declaring file, module ident)`` for every ancestor module of ``rel``.

    `rules/drc/clearance.rs` is declared `mod clearance;` in `rules/drc/mod.rs`,
    which is `mod drc;` in `rules/mod.rs`, which is `mod rules;` in `lib.rs`.
    Each link has to be at least `pub(crate)` for the crate-root registry to
    name the test module at the end of the chain.
    """
    parts = rel[: -len(".rs")].split("/")
    if parts[-1] == "mod":
        parts.pop()
    out = []
    for i in range(len(parts) - 1, -1, -1):
        parent = "/".join(parts[:i])
        decl_file = f"{parent}/mod.rs" if parent else "lib.rs"
        out.append((decl_file, parts[i]))
    return out


def widen_mod_decl(text: str, ident: str) -> str:
    """Raise a private ``mod <ident>;`` to ``pub(crate)``; leave ``pub`` alone."""
    # `[ \t]*$` rather than `\s*$`: `\s` spans newlines, so the looser form
    # swallowed the blank line after the declaration it rewrote.
    pattern = re.compile(rf"^([ \t]*)mod\s+{re.escape(ident)}[ \t]*;[ \t]*$", re.MULTILINE)
    return pattern.sub(rf"\g<1>pub(crate) mod {ident};", text)


# `#[cfg(test)]` sitting directly above a file-module declaration
# (`#[cfg(test)]\nmod integration;`), tolerating other attributes in between.
def _mod_gate_pattern(ident: str) -> re.Pattern[str]:
    return re.compile(
        rf"^([ \t]*)"
        + re.escape(TEST_GATE)
        + r"([ \t]*\n(?:[ \t]*#\[[^\n]*\][ \t]*\n)*"
        + rf"[ \t]*(?:pub(?:\([^)]*\))?[ \t]+)?mod[ \t]+{re.escape(ident)}[ \t]*;)",
        re.MULTILINE,
    )


def widen_mod_gate(text: str, ident: str) -> str:
    """Widen a ``#[cfg(test)]`` on the *declaration* of file module ``ident``.

    Visibility is only half of what a registry entry needs: the declaration
    itself can be test-gated, and then the whole file is absent from the
    ordinary build the registry compiles into.  ``temper-rust-router-core``'s
    ``combinator/mod.rs`` does exactly that with ``#[cfg(test)] mod
    integration;`` -- its 8 round-trip tests live in a file that only exists
    under ``cargo test``.

    Widening the gate to the same ``GATE`` the test modules get keeps
    ``cargo test`` identical (``any(test, ...)`` is still ``test``) and makes
    the file present whenever ``wasm-registry`` is on.  Idempotent: ``GATE`` is
    not ``#[cfg(test)]``, so a second pass matches nothing.
    """
    return _mod_gate_pattern(ident).sub(rf"\g<1>{GATE}\g<2>", text)


def rewrite_module(text: str, rel: str, ident: str) -> tuple[str, str | None, list[str]]:
    """Gate + expose ``mod <ident>`` and append its generated registry block.

    Returns the new text for ``rel``, the new text for a file module's body
    file (or ``None`` for an inline module), and the test function names.
    """
    lines = strip_generated(text.splitlines(), ident)
    attr_start, decl_idx, body_end = find_module_span(lines, ident)
    indent = lines[decl_idx][: len(lines[decl_idx]) - len(lines[decl_idx].lstrip())]

    # Rewrite the gate, keeping any hand-written attributes other than the
    # `cfg(test)` being replaced and the allow re-added below.
    kept = [
        ln
        for ln in lines[attr_start:decl_idx]
        if "cfg(test)" not in ln
        and "wasm-test-registry" not in ln
        and "wasm-registry" not in ln
        and "clippy::unwrap_used" not in ln
        and "clippy::expect_used" not in ln
    ]
    header = [f"{indent}{GATE}", f"{indent}{ALLOW}"] + kept
    decl = lines[decl_idx]
    if not decl.lstrip().startswith(("pub ", "pub(")):
        decl = f"{indent}pub(crate) {decl.lstrip()}"

    if body_end == -1:
        # File module: the body lives in `<stem>/<ident>.rs`.
        body_path = submodule_path(SRC, rel, ident)
        body_lines = strip_generated(body_path.read_text().splitlines(), ident)
        hidden = nested_gated_mask(body_lines)
        body_lines = [
            ln if nested else keep_test_fn(ln)
            for ln, nested in zip(body_lines, hidden)
        ]
        fns = collect_test_fns(own_lines(body_lines))
        block = generated_block("", module_path(rel), ident, fns)
        while body_lines and not body_lines[-1].strip():
            body_lines.pop()
        body_text = "\n".join(body_lines + [""] + block) + "\n"
        new_lines = lines[:attr_start] + header + [decl] + lines[decl_idx + 1 :]
        return "\n".join(new_lines) + "\n", body_text, fns

    body = lines[decl_idx + 1 : body_end]
    hidden = nested_gated_mask(body)
    # A nested test-gated submodule keeps its `#[test]` attributes verbatim:
    # it is not compiled into the registry build, and rewriting inside a
    # `proptest!` invocation would change what that macro sees.
    body = [ln if nested else keep_test_fn(ln) for ln, nested in zip(body, hidden)]
    while body and not body[-1].strip():
        body.pop()  # keep regeneration idempotent
    fns = collect_test_fns(own_lines(body))
    block = generated_block(indent + "    ", module_path(rel), ident, fns)
    new_lines = (
        lines[:attr_start]
        + header
        + [decl]
        + body
        + [""]
        + block
        + lines[body_end:]
    )
    return "\n".join(new_lines) + "\n", None, fns


def check_unregistered() -> list[Discovered]:
    """Test modules that could register but do not.  The gate's second arm.

    The first arm compares the committed registry against ``ELIGIBLE`` and so
    can only see a test added to a module already on the list.  A module that
    is *absent* from the list is not drift to it -- it is invisible.  That is
    not hypothetical: ``src/ipc.rs`` landed with the ``temper-ipc`` crate-fold
    on 2026-08-09, and its eleven IPC-2221/2152 kernel tests sat outside the
    tier for a day while ``--check`` reported green.

    So this arm starts from the source instead of from the list: every
    ``#[cfg(test)]`` module holding ``#[test]`` functions must either be
    registered or carry a *stated* structural reason for not being
    (:func:`discover_eligible`'s predicates).  Silent absence is no longer a
    representable state.
    """
    listed = set(ELIGIBLE)
    return [
        d
        for d in discover_eligible(SRC, CRATE_SPEC.absent_features)
        if not d.excluded and d.tests and (d.rel, d.ident) not in listed
    ]


def print_census() -> None:
    """Every ``#[cfg(test)]`` module, registered or not, with its reason.

    For a crate that names its modules explicitly, membership of ``ELIGIBLE``
    is what decides "registered" -- and a module the predicates call eligible
    but the list omits is called out, because that is the hole a hand-kept list
    has and the drift gate cannot see.
    """
    found = discover_eligible(SRC, CRATE_SPEC.absent_features)
    listed = set(ELIGIBLE)
    for d in found:
        if CRATE_SPEC.eligible is not None and not d.excluded:
            if (d.rel, d.ident) not in listed:
                d.excluded = "not-in-explicit-list"
    kept = [d for d in found if not d.excluded]
    dropped = [d for d in found if d.excluded]
    print(f"{CRATE_SPEC.name} census: {len(found)} `#[cfg(test)]` modules")
    print(f"  registered: {len(kept)} modules, {sum(d.tests for d in kept)} tests")
    for d in kept:
        print(f"    {d.rel}::{d.ident}  {d.tests}")
    print(f"  excluded:   {len(dropped)} modules, {sum(d.tests for d in dropped)} tests")
    for d in dropped:
        print(f"    {d.rel}::{d.ident}  {d.tests}  [{d.excluded}]")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail on drift instead of writing")
    ap.add_argument(
        "--crate",
        default="temper-drc-rs",
        choices=sorted(CRATES),
        help="which crate's registry to generate (default: temper-drc-rs)",
    )
    ap.add_argument(
        "--census",
        action="store_true",
        help="list every `#[cfg(test)]` module and why any is excluded, then exit",
    )
    args = ap.parse_args()
    select_crate(args.crate)

    if args.census:
        print_census()
        return 0

    pending: dict[Path, str] = {}
    entries: list[tuple[str, str, int]] = []

    for rel, ident in ELIGIBLE:
        path = SRC / rel
        # Read through `pending` so a file holding two test modules (board.rs)
        # accumulates both edits instead of the second discarding the first.
        text = pending.get(path) or path.read_text()
        new_text, body_text, fns = rewrite_module(text, rel, ident)
        pending[path] = new_text
        if body_text is not None:
            pending[submodule_path(SRC, rel, ident)] = body_text
        entries.append((module_path(rel), ident, len(fns)))

        for decl_file, mod_ident in ancestor_decls(rel):
            decl_path = SRC / decl_file
            decl_text = pending.get(decl_path) or decl_path.read_text()
            pending[decl_path] = widen_mod_gate(
                widen_mod_decl(decl_text, mod_ident), mod_ident
            )

    # Test-support modules: same gate widening and visibility raise, no entries.
    # Done after the loop so a crate that both registers a module in a file and
    # names a support module in it accumulates both edits through `pending`.
    for decl_file, mod_ident in CRATE_SPEC.test_support:
        decl_path = SRC / decl_file
        decl_text = pending.get(decl_path) or decl_path.read_text()
        pending[decl_path] = widen_mod_gate(
            widen_mod_decl(decl_text, mod_ident), mod_ident
        )

    pending[SRC / "wasm_test_registry.rs"] = render_root(entries)

    drifted = []
    for path, text in pending.items():
        current = path.read_text() if path.exists() else None
        if current == text:
            continue
        drifted.append(path.relative_to(REPO_ROOT))
        if not args.check:
            path.write_text(text)

    total = sum(n for _, _, n in entries)
    suffix = "" if args.crate == "temper-drc-rs" else f" [{args.crate}]"

    # Second gate arm: a module that could register but is not on the list.
    # Checked in write mode too -- regenerating cannot invent a list entry, so
    # this needs a human either way.
    unregistered = check_unregistered()
    if unregistered:
        print(
            f"{len(unregistered)} test module(s) hold `#[test]` functions, are"
            " not registered, and have no stated reason not to be:"
        )
        for d in unregistered:
            print(f"  {d.rel}::{d.ident}  ({d.tests} tests)")
        print(
            "Add each to ELIGIBLE in this script (and regenerate), or -- if it"
            " genuinely cannot compile into a non-test build -- give"
            " discover_eligible() a predicate that names the reason."
        )
        return 1

    if args.check:
        if drifted:
            print(
                "wasm test registry is stale; run scripts/gen_wasm_test_registry.py"
                f" --crate {args.crate}"
            )
            for p in drifted:
                print(f"  {p}")
            return 1
        print(
            f"wasm test registry up to date: {total} tests across"
            f" {len(entries)} modules{suffix}"
        )
        return 0

    print(f"wrote registry: {total} tests across {len(entries)} modules{suffix}")
    for p in drifted:
        print(f"  updated {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
