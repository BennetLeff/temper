TEST_FN = re.compile(r"^(\s*)#\[(?:test|cfg_attr\(test, test\))\]\s*$")

# A *use* of the `proptest` dev-dependency: the `proptest!` macro or a
# `proptest::` path.  Deliberately not a bare substring search -- a module that
# merely says the word in a comment ("--- proptest: structural properties ---",
# or a note explaining why a nested module is gated) does not depend on the
# crate, and excluding it on that basis would drop real tests from the tier for
# a spelling.
PROPTEST_USE = re.compile(r"(?:^|[^A-Za-z0-9_])proptest\s*(?:!|::)")
FN_NAME = re.compile(r"^\s*(?:pub\s+)?fn\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(")


def keep_test_fn(line: str) -> str:
    """``#[test]`` -> ``#[cfg_attr(test, test)]``, preserving indentation."""
    m = TEST_FN.match(line)
    return f"{m.group(1)}{TEST_ATTR}" if m else line


def module_path(rel: str) -> str:
    """``types/vent.rs`` -> ``types::vent``; ``rules/mod.rs`` -> ``rules``."""
    p = rel[: -len(".rs")]
    if p.endswith("/mod"):
        p = p[: -len("/mod")]
    return p.replace("/", "::")


MOD_DECL = re.compile(
    r"^\s*(?:pub(?:\([^)]*\))?\s+)?mod\s+([A-Za-z_][A-Za-z0-9_]*)\s*(\{|;)\s*$"
)


def attr_block(lines: list[str], decl_idx: int) -> list[str]:
    """The ``#[...]`` lines immediately above ``decl_idx``.

    Immediately above is the operative word: this mirrors
    :func:`find_module_span`, which stops at the first non-attribute line.  A
    comment between an attribute and the ``mod`` therefore ends the block for
    both, so classification and rewriting always agree on what gates a module.
    """
    start = decl_idx
    while start > 0 and lines[start - 1].lstrip().startswith("#["):
        start -= 1
    return [ln.strip() for ln in lines[start:decl_idx]]


def is_test_gate(attr: str) -> bool:
    """Does ``attr`` gate a module on the test configuration?

    Both spellings count: the hand-written ``#[cfg(test)]`` and the ``GATE``
    this script rewrites it into.  Recognising the rewritten form is what makes
    regeneration idempotent -- otherwise the second run would see no test
    modules at all and emit an empty registry.
    """
    return attr.strip() in (TEST_GATE, GATE)


def looks_test_gated(lines: list[str], decl_idx: int) -> bool:
    """Is there a test gate above ``decl_idx``, comments notwithstanding?

    Deliberately more permissive than :func:`attr_block`: it scans back over
    comments and blank lines too, so a test module whose gate the rewriter
    *cannot* reach is still seen by discovery and reported rather than dropped.
    """
    i = decl_idx - 1
    while i >= 0 and (
        lines[i].lstrip().startswith(("#[", "//")) or not lines[i].strip()
    ):
        if is_test_gate(lines[i]):
            return True
        i -= 1
    return False


def nested_gated_mask(body: list[str]) -> list[bool]:
    """Which lines of ``body`` belong to a *nested* test-gated submodule.

    A test module can hold another test module::

        #[cfg(test)]
        mod tests {
            #[test] fn a() {}

            #[cfg(test)]
            mod proptests { proptest! { #[test] fn p(..) {} } }
        }

    The inner module is its own census entry (:func:`discover_eligible` finds
    it in the same sweep, because it carries its own gate), so its tests are
    *not* the outer module's.  Without this mask the outer module would both
    inherit the inner one's ``proptest`` exclusion and emit registry entries
    naming functions that are not in its scope -- neither of which compiles or
    counts correctly.

    Only submodules carrying their own gate are masked.  An ungated helper
    ``mod`` inside a test module is not a separate entry, so it stays part of
    its parent exactly as before -- which is why this cannot change what
    ``temper-drc-rs`` or ``temper-geometry`` already generate.

    Caveat, shared with :func:`attr_block`: an attribute is recognised only
    when it is written on ONE line.  Splitting ``#[allow(a, b, c)]`` across
    lines hides the gate from the scan, and the nested module's tests get
    attributed to its parent -- which does not compile (the parent cannot name
    them), so the failure is loud rather than silent, but keep such attributes
    on one line.
    """
    mask = [False] * len(body)
    i = 0
    while i < len(body):
        m = MOD_DECL.match(body[i])
        if m and m.group(2) == "{" and any(
            is_test_gate(a) for a in attr_block(body, i)
        ):
            depth = 0
            end = len(body) - 1
            for j in range(i, len(body)):
                depth += body[j].count("{") - body[j].count("}")
                mask[j] = True
                if depth == 0:
                    end = j
                    break
            i = end + 1
        else:
            i += 1
    return mask


def own_lines(body: list[str]) -> list[str]:
    """``body`` with every nested test-gated submodule removed."""
    return [ln for ln, hidden in zip(body, nested_gated_mask(body)) if not hidden]


def module_body(lines: list[str], decl_idx: int) -> list[str]:
    """The brace-balanced body of the inline module declared at ``decl_idx``."""
    depth = 0
    for j in range(decl_idx, len(lines)):
        depth += lines[j].count("{") - lines[j].count("}")
        if depth == 0:
            return lines[decl_idx : j + 1]
    raise SystemExit(f"unbalanced braces at line {decl_idx + 1}")


def submodule_path(src: Path, rel: str, ident: str) -> Path:
    """Where the body of a file module ``mod <ident>;`` declared in ``rel`` lives.

    Rust resolves this against the *directory* the declaring file owns, and a
    "mod-rs" file (``lib.rs``, ``foo/mod.rs``) owns the directory it sits in
    while a plain ``foo.rs`` owns ``foo/``.  Getting that wrong is silent: the
    body file simply is not found, the module is censused as having no tests,
    and real tests drop off the tier without a word.  That is exactly what
    happened to ``temper-rust-router-core``'s ``combinator/mod.rs``, whose
    ``#[cfg(test)] mod integration;`` body is ``combinator/integration.rs``,
    not ``combinator/mod/integration.rs``.
    """
    stem = rel[: -len(".rs")]
    if stem in ("lib", "main"):
        parent = ""
    elif stem.endswith("/mod"):
        parent = stem[: -len("/mod")]
    else:
        parent = stem
    return src / parent / f"{ident}.rs"


def feature_gated_modules(src: Path, features: tuple[str, ...]) -> dict[str, str]:
    """Top-level module idents gated on a feature absent from the wasm32 build.

    ``{ident: feature}``.  Their whole file is absent from a
    ``--no-default-features`` build, so every test inside is structurally
    unreachable on ``wasm32`` -- not skipped, not failing: not compiled.

    ``python`` is the usual one (pyo3 does not cross-compile to
    ``wasm32-unknown-unknown``), but it is not the only one: the
    ``temper-rust-router-core`` modules behind ``sat`` need ``rustsat-cadical``,
    a C++ solver that has no ``wasm32-unknown-unknown`` build either.  Which
    features are absent is therefore per-crate (``CrateSpec.absent_features``)
    rather than the single hard-coded ``python`` this used to assume.
    """
    lines = (src / "lib.rs").read_text().splitlines()
    gated: dict[str, str] = {}
    for i, line in enumerate(lines):
        m = MOD_DECL.match(line)
        if not m:
            continue
        attrs = attr_block(lines, i)
        for feature in features:
            if any(f'feature = "{feature}"' in a for a in attrs):
                gated[m.group(1)] = feature
                break
    return gated


@dataclass
class Discovered:
    """One ``#[cfg(test)]`` module found by the census."""

    rel: str
    ident: str
    tests: int
    excluded: str | None  # None = eligible; otherwise the reason


def discover_eligible(
    src: Path, absent_features: tuple[str, ...] = ("python",)
) -> list[Discovered]:
    """Every ``#[cfg(test)]`` module under ``src``, each with its verdict.

    Exclusions are *predicates with reasons*, never a hand-kept deny-list, so
    a module that becomes eligible (say, its ``python`` gate is lifted) is
    picked up automatically instead of staying silently out of the tier.
    """
    gated = feature_gated_modules(src, absent_features)
    out: list[Discovered] = []
    for path in sorted(src.rglob("*.rs")):
        rel = str(path.relative_to(src))
        lines = path.read_text().splitlines()
        for i, line in enumerate(lines):
            m = MOD_DECL.match(line)
            if not m or not looks_test_gated(lines, i):
                continue
            ident, inline = m.group(1), m.group(2) == "{"
            if inline:
                body = module_body(lines, i)
            else:
                # File module (`mod tests;`): the body is a separate file.
                body_path = submodule_path(src, rel, ident)
                body = body_path.read_text().splitlines() if body_path.exists() else []
            # A nested test-gated submodule is its own entry in this same
            # sweep, so its tests (and its dev-dependency imports) belong to
            # it, not to the module lexically containing it.
            body = own_lines(body)
            tests = sum(1 for ln in body if TEST_FN.match(ln))
            attrs = attr_block(lines, i)

            reason: str | None = None
            own_gate = next(
                (f for f in absent_features if any(f'feature = "{f}"' in a for a in attrs)),
                None,
            )
            file_gate = gated.get(rel[: -len(".rs")])
            if own_gate or file_gate:
                # The module does not exist in a wasm32 build at all.
                reason = f"{own_gate or file_gate}-gated"
            elif any(PROPTEST_USE.search(ln.split("//")[0]) for ln in body):
                # `proptest` is a dev-dependency: present under `cargo test`,
                # absent from the ordinary (non-test) build the registry is
                # compiled into.  Same exclusion `temper-drc-rs` makes by
                # leaving its own `proptests` modules out of ELIGIBLE_DRC_RS.
                reason = "proptest-dev-dependency"
            elif not any(is_test_gate(a) for a in attrs):
                # `looks_test_gated` saw a gate the rewriter cannot reach --
                # a comment sits between `#[cfg(test)]` and `mod`.  Report it
                # rather than dropping the module on the floor.
                reason = "gate-not-adjacent-to-mod"
            elif tests == 0:
                reason = "no-test-functions"

            out.append(Discovered(rel, ident, tests, reason))
    return out


@dataclass
class CrateSpec:
    """Everything the generator needs to know about one crate."""

    name: str
    # Explicit module list, or None to discover them.
    eligible: list[tuple[str, str]] | None
    families: list[str]
    family_of: object  # Callable[[str], str]
    # Cargo features whose modules cannot exist in the `--no-default-features`
    # wasm32 build.  `python` always qualifies (pyo3 does not cross-compile);
    # a crate whose non-default surface needs a native-only dependency adds it
    # here so those modules are excluded *with a stated reason* rather than
    # registered into a build that cannot compile them.
    absent_features: tuple[str, ...] = ("python",)
    # Tail of the "tests inside python-gated modules are absent" sentence.
    census_note: str = "are censused in the Phase 0 report instead"
    # The sharding section of the registry's module docstring.
    sharding_note: list[str] = field(
        default_factory=lambda: [
            "//! ## Per-family sharding (Phase 1 U8)",
            "//!",
            "//! Each module entry in `ALL` is gated on a `wasm-registry-<family>`",
            "//! feature.  Building with only e.g. `--features wasm-registry-drc`",
            "//! includes only the DRC family's modules; with LTO, unreferenced test",
            "//! functions from other families are dead-stripped, producing a smaller",
            "//! `.wasm` module per Worker function.",
        ]
    )
    # Crate-specific paragraphs inserted before the sharding section.
    extra_notes: list[str] = field(default_factory=list)
    # `(declaring file, module ident)` for *test-support* modules: `#[cfg(test)]`
    # modules that hold no `#[test]` of their own but whose helpers registered
    # test modules call (`temper-quality-oracle`'s `tests_common`, shared by
    # `oracle::tests` and `thresholds::tests`).  They get the same gate widening
    # and visibility raise a registered module gets, and nothing else -- they
    # contribute no registry entries, so the census still calls them
    # `no-test-functions`.  Omitting one that is needed does not fail silently:
    # the `wasm-registry` build cannot resolve `crate::tests_common` and stops.
    test_support: list[tuple[str, str]] = field(default_factory=list)


