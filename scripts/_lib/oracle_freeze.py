"""Shared machinery for the FREEZE oracle-retirement generator (U4 of
``docs/plans/2026-08-11-003-feat-migration-pipeline-wire-and-retire-plan.md``).

Background
----------
The migration pipeline pins a verbatim pre-migration Python implementation
as a "differential oracle" for every migrated kernel (``docs/migration-
pipeline.md`` stage 3), and — before this plan — had no mechanism to ever
retire one. Result: 153+ ``_py_oracle.py`` files, 50,141+ LOC, that can
never run on the wasm32 tier (they need CPython) and grow with every
migration.

FREEZE is the plan's default disposition for a retirable oracle: run the
oracle once over a *declared* input corpus, bake the (input, output) pairs
into a Rust ``const`` array as a golden-vector regression test, delete the
Python oracle, and keep the differential — now comparing the Rust kernel
against the frozen vectors instead of a live CPython call. The regression
signal survives; the CPython dependency does not; the resulting test is
wasm32-tier-executable because it is plain Rust data + an ``assert_eq``
loop, no ``pyo3``, no ``proptest`` (a dev-dependency absent from the
tier's non-test build).

Q2 — the reason this module exists, not just a one-off script
---------------------------------------------------------------
A frozen corpus cannot find a bug in an input region it never sampled. This
repo has hit exactly that failure four times (see ``docs/evidence/
2026-08-11-native-only-is-an-upper-bound.md`` §7): ``temper-geometry``'s
keepout property, ``temper-thermal``'s overlap-area property, ``temper-
quality-oracle``'s IPC-2221 bracket property, and ``temper-io-types``'s 7
special-value gaps under uniform sampling. FREEZE reproduces this failure
class at scale unless the corpus generator both **measures** the fraction
of non-trivial/boundary cases it drew and **refuses** to emit a corpus
that does not clear a declared minimum for each such fraction. That is
what :func:`run_freeze` does: it is not optional plumbing, it is the gate
that makes FREEZE safe to apply repeatedly. Every :class:`FreezeSpec` must
declare at least one :class:`NonVacuityCheck`; a spec with an empty list is
rejected before it runs (see ``run_freeze``'s validation), mirroring the
precedent in ``packages/temper-geometry/src/creepage_check.rs`` /
``via_clearance.rs`` (PR #1007) and ``packages/temper-quality-oracle/src/
property_campaigns.rs`` (Kernel 5, IPC-2221 bracket), which measure hit
rates like "42/50 bracket-straddling" and assert a minimum before trusting
the campaign.

Design notes
------------
* One spec module per oracle, under ``scripts/oracle_freeze_specs/``,
  each exporting a module-level ``SPEC: FreezeSpec``. This mirrors this
  repo's existing generator convention (``scripts/gen_wasm_test_registry.py``
  hand-lists eligible modules per crate; there is no single mechanical rule
  that derives a Rust golden-vector block from an arbitrary Python function
  signature, so the per-oracle glue — how to call it, how to render its
  inputs/outputs as Rust literals, what "non-trivial" means for its domain —
  is inherent complexity, not accidental).
* Corpus generation is deterministic: either an explicit hand-curated list
  (reusing the oracle's own pre-existing differential test cases where they
  already form a good corpus) or a seeded :class:`SplitMix64` draw (the same
  PRNG and constants as ``packages/temper-orchestration/src/
  wasm_campaign_prng.rs`` / ``packages/temper-drc-rs/src/rules/drc/
  property_campaigns.rs``, reimplemented here in Python so a spec's corpus
  is reproducible without a Rust build).
* Floats are rendered as ``f64::from_bits(0x...)`` — bit-exact, including
  NaN/Infinity payloads, matching this repo's existing bit-exactness
  convention (``float.hex()`` comparisons in the differential suites this
  tool replaces) without depending on Rust's lack of stable hex-float
  literal syntax.
* Generated Rust is spliced into an EXISTING file between a pair of marker
  comments (``splice_generated_block``), the same idempotent-rewrite shape
  ``scripts/gen_wasm_test_registry.py`` already uses for its own
  ``BEGIN/END generated by`` blocks — chosen deliberately so a frozen
  corpus can live inside a kernel's own ``#[cfg(test)] mod tests`` (where
  the wasm-registry generator can already see it) rather than requiring a
  new crate module and a new ``mod`` declaration in ``lib.rs`` for every
  retired oracle.
"""

from __future__ import annotations

import struct
import sys
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
