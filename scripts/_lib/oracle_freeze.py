# Driver
# --------------------------------------------------------------------------


class FreezeRefused(Exception):
    """Raised when a corpus fails a non-vacuity check — the generator
    refuses to emit it (Q2)."""


def run_freeze(spec: FreezeSpec, *, write: bool, check: bool = False) -> str:
    """Generate a spec's frozen corpus, enforce non-vacuity, and (unless
    ``check``) splice the result into its Rust target file.

    Returns a human-readable report. Raises :class:`FreezeRefused` if any
    non-vacuity check fails — this is a hard refusal, not a warning: Q2
    exists precisely so a bad corpus cannot silently ship.
    """
    if not spec.non_vacuity:
        raise ValueError(
            f"spec {spec.name!r} declares zero NonVacuityCheck entries — a FreezeSpec "
            f"MUST measure and assert non-triviality (Q2); refusing to run an "
            f"unguarded corpus generator."
        )

    cases = spec.gen_cases()
    if not cases:
        raise ValueError(f"spec {spec.name!r} generated zero cases")

    results: list[tuple[FreezeCase, Any]] = [(c, spec.run_oracle(c.input)) for c in cases]

    report_lines = [
        f"=== FREEZE {spec.name} ===",
        spec.description,
        f"oracle: {spec.oracle_provenance}",
        f"kernel: {spec.kernel_provenance}",
        f"corpus size: {len(results)}",
        "non-vacuity:",
    ]
    all_ok = True
    for nvc in spec.non_vacuity:
        ok, hits, n = nvc.evaluate(results)
        all_ok = all_ok and ok
        status = "PASS" if ok else "FAIL"
        target = f">={nvc.min_count}" if nvc.min_count else f">={nvc.min_fraction:.0%}"
        report_lines.append(f"  [{status}] {nvc.tag}: {hits}/{n} ({target}) -- {nvc.description}")

    report = "\n".join(report_lines)

    if not all_ok:
        raise FreezeRefused(
            f"{report}\n\nREFUSED: at least one non-vacuity check failed minimum -- "
            f"this corpus would be trivially satisfiable (Q2). Widen/rebias gen_cases(), "
            f"do not lower the threshold to make the check pass."
        )

    body = spec.render_rust(results)
    target_path = REPO_ROOT / spec.rust_target_file
    original = target_path.read_text(encoding="utf-8")
    new_text = splice_generated_block(original, spec.marker(), body, spec.insert_before_marker)

    if check:
        if new_text != original:
            raise FreezeRefused(
                f"{spec.rust_target_file} is out of date for spec {spec.name!r} -- "
                f"run `python3 scripts/gen_oracle_freeze.py --spec {spec.name}` and commit the result."
            )
        return report + "\n\nCHECK OK: generated block up to date."

    if write and new_text != original:
        target_path.write_text(new_text, encoding="utf-8")
        report += f"\n\nWROTE {spec.rust_target_file}"
    else:
        report += "\n\n(no write requested or no change)"

    return report
