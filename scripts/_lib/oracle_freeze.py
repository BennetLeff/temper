REPO_ROOT = find_repo_root()


# --------------------------------------------------------------------------
# Deterministic PRNG — Python mirror of wasm_campaign_prng.rs's SplitMix64.
# --------------------------------------------------------------------------


class SplitMix64:
    """Same constants and update rule as this repo's Rust mirror campaigns
    (``packages/temper-orchestration/src/wasm_campaign_prng.rs``). Not
    required to be bit-identical to any Rust draw for FREEZE to be correct
    (the corpus is baked into Rust as data, not regenerated there) — reused
    only so this tool's determinism story matches the rest of the tier
    rather than introducing a fourth PRNG convention.
    """

    __slots__ = ("state",)
    _MASK = 0xFFFFFFFFFFFFFFFF

    def __init__(self, seed: int) -> None:
        self.state = seed & self._MASK

    def next_u64(self) -> int:
        self.state = (self.state + 0x9E3779B97F4A7C15) & self._MASK
        z = self.state
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & self._MASK
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & self._MASK
        return z ^ (z >> 31)

    def next_f64(self) -> float:
        return (self.next_u64() >> 11) * (1.0 / (1 << 53))

    def range(self, lo: float, hi: float) -> float:
        return lo + self.next_f64() * (hi - lo)

    def range_i64(self, lo: int, hi: int) -> int:
        assert hi > lo
        return lo + (self.next_u64() % (hi - lo))

    def index(self, n: int) -> int:
        assert n > 0
        return self.next_u64() % n

    def boolean(self) -> bool:
        return self.next_u64() & 1 == 0


def rust_f64_literal(x: float) -> str:
    """Bit-exact ``f64::from_bits(0x...)`` rendering, including NaN/Infinity.

    Deliberately not a decimal literal: Rust has no stable hex-float syntax,
    and a decimal round-trip (``repr(x)`` -> Rust parses it back) is not
    guaranteed bit-exact for every double, only for "shortest repr" doubles
    Python happens to print losslessly. Bits are exact by construction.
    """
    bits = struct.unpack(">Q", struct.pack(">d", x))[0]
    return f"f64::from_bits(0x{bits:016X}_u64)"


