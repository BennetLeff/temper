# Spec model
# --------------------------------------------------------------------------


@dataclass(frozen=True)
class FreezeCase:
    """One corpus case: an opaque, spec-defined input plus the tags used
    for non-vacuity measurement. ``input`` is never interpreted by this
    module — only by the spec's own ``run_oracle``/``render_case``.
    """

    input: Any
    tags: frozenset[str]


@dataclass(frozen=True)
class NonVacuityCheck:
    """One generation-time coverage guard: at least ``min_fraction`` of the
    corpus must carry ``tag``, or the corpus is refused (Q2 — see this
    module's docstring). ``min_count`` is an alternative absolute-count form
    for tags that should appear at all (e.g. "every shape code exercised at
    least once") rather than at some percentage.
    """

    tag: str
    description: str
    min_fraction: float = 0.0
    min_count: int = 0

    def evaluate(self, cases_with_output: list[tuple[FreezeCase, Any]]) -> tuple[bool, int, int]:
        n = len(cases_with_output)
        hits = sum(1 for case, _ in cases_with_output if self.tag in case.tags)
        if self.min_count:
            ok = hits >= self.min_count
        else:
            ok = n > 0 and hits * 100 >= n * int(round(self.min_fraction * 100))
        return ok, hits, n


@dataclass(frozen=True)
class FreezeSpec:
    """Everything needed to freeze one oracle. See module docstring."""

    name: str
    description: str
    oracle_provenance: str  # human-readable: file + pinned commit, informational
    kernel_provenance: str  # human-readable: which .rs fn this compares against
    gen_cases: Callable[[], list[FreezeCase]]
    run_oracle: Callable[[Any], Any]  # FreezeCase.input -> raw oracle output
    non_vacuity: list[NonVacuityCheck]
    render_rust: Callable[[list[tuple[FreezeCase, Any]]], str]  # -> full generated block body
    rust_target_file: str  # repo-relative path to splice into
    insert_before_marker: str  # exact line already present in rust_target_file
    marker_name: str = ""  # defaults to `name` if unset
    extra_context: dict[str, Any] = field(default_factory=dict)

    def marker(self) -> str:
        return self.marker_name or self.name


# --------------------------------------------------------------------------
# Marker splice (same idempotent-rewrite shape as gen_wasm_test_registry.py)
# --------------------------------------------------------------------------


def _markers(marker_name: str) -> tuple[str, str]:
    begin = f"// --- BEGIN generated by scripts/gen_oracle_freeze.py: {marker_name} ---"
    end = f"// --- END generated by scripts/gen_oracle_freeze.py: {marker_name} ---"
    return begin, end


def splice_generated_block(
    text: str, marker_name: str, body: str, insert_before_marker: str
) -> str:
    """Insert or replace the ``marker_name`` generated block in ``text``.

    If the markers are already present, the content between them is
    replaced in place (idempotent regeneration — matches ``gen_wasm_test_
    registry.py``'s own rewrite behaviour). If absent, the block is
    inserted immediately before the first line equal to
    ``insert_before_marker`` (stripped comparison), so a frozen corpus can
    land inside an existing ``mod tests { ... }`` block, ahead of that
    module's own wasm-registry ``BEGIN/END`` markers, without hand-editing.
    """
    begin, end = _markers(marker_name)
    lines = text.splitlines(keepends=True)
    block = f"{begin}\n{body}\n{end}\n"

    begin_idx = None
    end_idx = None
    for i, line in enumerate(lines):
        if line.strip() == begin:
            begin_idx = i
        elif line.strip() == end and begin_idx is not None:
            end_idx = i
            break

    if begin_idx is not None and end_idx is not None:
        return "".join(lines[:begin_idx]) + block + "".join(lines[end_idx + 1 :])

    insert_idx = None
    for i, line in enumerate(lines):
        if line.strip() == insert_before_marker.strip():
            insert_idx = i
            break
    if insert_idx is None:
        raise ValueError(
            f"insert_before_marker {insert_before_marker!r} not found in target file "
            f"and no existing {begin!r}/{end!r} block to replace"
        )
    return "".join(lines[:insert_idx]) + block + "\n" + "".join(lines[insert_idx:])


