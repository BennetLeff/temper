"""
Board-to-Elmer mesh converter — generates an Elmer mesh definition directory
and ``.sif`` solver-input file from the temper board geometry.

Produces TEXT artifacts (geometry definition + .sif) without invoking Elmer.
``ElmerGrid`` would consume the geometry file to produce an actual mesh;
the ``.sif`` is passed to ``ElmerSolver`` by the ``ElmerRunner``.

The temper board is parameterised once (semi-automated per the scope boundary):
- 4-layer stackup with inner copper planes (dominant in-plane heat spreader)
- 3-D extrusion: board outline polygon x stackup thickness
- Copper-plane regions as separate material bodies
- Device footprints as volumetric heat sources (TO-247)
- Dirichlet BC on the heatsink edge, adiabatic edges elsewhere
- Convective enclosure BCs per the ``heat_removal`` model

Requirements: R2 (board-to-Elmer geometry conversion).
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from temper_placer.core.board import Board
    from temper_placer.physics.thermal_fdm import ThermalFDMConfig
    from temper_placer.physics.tj_cross_check import DeviceThermalConfig


# ---------------------------------------------------------------------------
# Temper-board material properties (semi-automated, parameterised once)
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class ElmerMaterial:
    """An Elmer material with its heat-equation properties."""

    name: str
    material_id: int
    k_inplane: float  # W/(m*K)
    k_through: float   # W/(m*K)
    density: float = 1900.0  # kg/m**3
    heat_capacity: float = 1150.0  # J/(kg*K)
    because: str = ""


TEMPER_MATERIALS: dict[str, ElmerMaterial] = {
    "fr4": ElmerMaterial(
        name="FR4",
        material_id=1,
        k_inplane=0.3,
        k_through=0.3,
        because="standard FR4 datasheet values; k=0.3 W/(m*K) through-plane",
    ),
    "copper": ElmerMaterial(
        name="Copper",
        material_id=2,
        k_inplane=385.0,
        k_through=385.0,
        density=8960.0,
        heat_capacity=385.0,
        because="pure copper; k=385 W/(m*K) per standard thermal handbooks",
    ),
}


