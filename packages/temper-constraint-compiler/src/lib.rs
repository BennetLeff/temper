// NOT gated on `python`. The wasm32 tier builds with --no-default-features,
// so an added `python` gate here would silently exclude the registry and the
// runner would fail to compile against it. `wasm-registry` is implied by every
// per-family feature and by `wasm-test-registry`, so any wasm build compiles
// this module.
// Generated by
// `scripts/gen_wasm_test_registry.py --crate temper-constraint-compiler`.
#[cfg(feature = "wasm-registry")]
pub mod wasm_test_registry;

#[cfg(feature = "python")]
use pyo3::prelude::*;
#[cfg(feature = "python")]
use pyo3::types::{PyDict, PyList};

#[cfg(feature = "python")]
#[pyfunction]
#[allow(clippy::too_many_arguments)]
fn compile_pcl_constraints(
    py: Python<'_>,
    pcl_dicts: &Bound<'_, PyList>,
    net_class_dicts: &Bound<'_, PyList>,
    component_map: &Bound<'_, PyDict>,
    zone_map: &Bound<'_, PyDict>,
    skeletons: &Bound<'_, PyList>,
    channel_widths: &Bound<'_, PyDict>,
    existing_vars: &Bound<'_, PyList>,
    existing_cons: &Bound<'_, PyList>,
    net_names: Vec<String>,
) -> PyResult<Py<PyDict>> {
    pyo3_bridge::run_full_pipeline(
        py,
        pcl_dicts,
        net_class_dicts,
        component_map,
        zone_map,
        skeletons,
        channel_widths,
        existing_vars,
        existing_cons,
        net_names,
    )
}

#[cfg(feature = "python")]
#[pymodule]
fn temper_constraint_compiler(m: &Bound<'_, PyModule>) -> PyResult<()> {
    m.add_function(wrap_pyfunction!(compile_pcl_constraints, m)?)?;
    crate::constraints::py::register(m)?;
    crate::pcl_contracts::register(m)?;
    Ok(())
}
