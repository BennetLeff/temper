#!/usr/bin/env python3
"""Write native-21/BRINGUP-PROBES.md from the board-only plan, so the probe map can't drift from it.

    python3 native-21/layout/probe_map21.py   (after plan_board_only21.py and verification/d5_audit.py)

Reads layout/board_only21.json (test pads, fiducials, holes) and verification/d5-audit.json (each
fixing's distance from HOT copper, measured on the built board).
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
bo = json.loads((HERE / "board_only21.json").read_text())
audit = json.loads((HERE.parent / "verification" / "d5-audit.json").read_text())
hot = {h["ref"]: h["hot_mm"] for h in audit["npth_to_hot"] if h["ref"].startswith("H")}


def xy(p):
    return f"{p[0]:.1f}, {p[1]:.1f}"


refs = {tuple(t["at"]): t["ref"] for t in bo["test_points"] if "ref_at" not in t}
out = ["# Native-21 bring-up probe map", "",
       "Board-only test pads (TestPoint_Pad_D1.0mm: bare 1 mm copper, no part, not in BOM/CPL), each",
       "paired with a ground-reference pad on its own domain for a short probe ground (D-8: ≤ 10 mm loop).",
       "Chosen by `layout/plan_board_only21.py` from the routed copper; added on every build by",
       "`layout/board_only21.py`. Pads sit on an existing via or track of their net (no routing change).",
       "Bottom-side pads are probed with the board on standoffs; their designators are on F.Fab.",
       "Generated by `layout/probe_map21.py`: edit the plan, not this file.", "",
       "**Safety:** HOT domains float at bus / switch-node potential. Probe them only with rated",
       "differential or isolated probes (D-8 equipment table), never a grounded scope ground.", "",
       "| Signal pad | Net | Side | At (mm) | Ground pad | Ground net | Purpose |",
       "| --- | --- | --- | --- | --- | --- | --- |"]
for t in bo["test_points"]:
    if "ref_at" in t:
        out.append(f"| {t['ref']} | {t['net']} | {t['side']} | {xy(t['at'])} | {refs[tuple(t['ref_at'])]} | "
                   f"{t['ref_net']} | {t['purpose']} |")
out += ["", "## Probed elsewhere (no legal test-pad spot)", "", "| Net | Probe at |", "| --- | --- |"]
out += [f"| {m['net']} | {m['probe']} |" for m in bo["missing_test_points"]]
out += ["", "FET gate/drain/source (VGS, VDS): at the TO-247 package leads with rigid insulated adapters, per",
        "D-8 (`validation-results/01-switching-parasitics/round17/delegation/out-D8/README.md`).", "",
        "## Fiducials and fixings", "",
        "Fiducials: " + ", ".join(f"{f['ref']} ({f['at'][0]}, {f['at'][1]})" for f in bo["fiducials"])
        + " (1 mm copper, 3 mm mask opening, F side).", "",
        "| Hole | At (mm) | HOT copper from the hole wall | Hardware |", "| --- | --- | --- | --- |"]
# The enclosure build (temper-manufacturing R24+) parses this table: "| H<n> | x, y | ... |" rows,
# columns in this order. Changing the format breaks it loudly; tell the enclosure owner first.
for h in bo["mounting_holes"]:
    d = f"{hot[h['ref']]} mm" if h["ref"] in hot else "—"
    if h["kind"] == "metal":
        hw = "M3 metal allowed: chassis/PE, ≥ 8 mm from HOT (D5)"
    else:
        hw = ("**M3 nylon only** (UL94 V-0): screw, washer and standoff. Washer face copper-free on both "
              "outer layers (review M4)")
        if h["ref"] in hot and hot[h["ref"]] < 8.0:
            hw += "; **nylon standoff ≥ 10 mm**, which carries the HOT→chassis 8.0 mm surface path"
    out.append(f"| {h['ref']} | {h['at'][0]}, {h['at'][1]} | {d} | {hw} |")
out += ["", "**Nylon fixings are an insulation part, not hardware choice** (closure review M4):",
        "- the whole chain at every nylon hole is insulating: nylon screw, nylon washer, and a nylon standoff;",
        "- the standoff is male-female, or female-female with a nylon screw at the chassis too;",
        "- no metal screw, nut or insert within 10 mm of the board at these holes.",
        "",
        "At the holes marked ≥ 10 mm, one metal screw would sit a millimetre or two of laminate from HOT copper",
        "while bonded to PE. At the SELV holes, it would add a second SELV–PE bond beyond R38.",
        "",
        "Positions are frozen at the stage-8 plan, which the enclosure adopted (R22 bosses).",
        "`layout/plan_board_only21.py` keeps them while they stay legal and says so when one has to move.", ""]
(HERE.parent / "BRINGUP-PROBES.md").write_text("\n".join(out))
print(f"BRINGUP-PROBES.md: {sum('ref_at' in t for t in bo['test_points'])} signal pads, "
      f"{len(bo['mounting_holes'])} holes")
