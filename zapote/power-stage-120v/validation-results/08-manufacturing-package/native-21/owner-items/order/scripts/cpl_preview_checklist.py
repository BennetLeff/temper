#!/usr/bin/env python3
"""Write owner-items/order/CPL-PREVIEW-CHECKLIST.md from cpl-rotation-audit/audit.csv and fab/bom-jlcpcb.csv.

    python3 -I owner-items/order/scripts/cpl_preview_checklist.py [--check]

--check exits 1 if the committed Markdown differs from what the audit and the BOM give now.
"""
import sys as _s; _s.dont_write_bytecode = True
import argparse
import csv
from pathlib import Path

PKG = Path(__file__).resolve().parents[2].parent          # .../native-21
OUT = PKG / "owner-items/order/CPL-PREVIEW-CHECKLIST.md"


def what_to_check(r):
    reason = r["reason"]
    if r["designator"].startswith(("C126", "C127", "C128", "C129")) or r["footprint"].startswith("CP_Elec"):
        return "polarity: the negative stripe against the KiCad pad 1 (+) side in JLC's 3D preview"
    if reason.startswith("CONFLICT"):
        return ("both rotations: EasyEDA fit rot %s against the DB rule rot %s; pick the one whose pin 1 lands on pad 1 "
                "and whose body matches the silk" % (r["easyeda_rot"], r["db_rot"]))
    if reason.startswith("only the JLC rotation DB"):
        return "the DB rotation %s against pin 1 (no EasyEDA footprint to cross-check)" % r["proposed_jlc_rot"]
    if reason.startswith("EasyEDA footprint fit needs"):
        return "the EasyEDA offset %s deg (no DB rule): pin 1 on pad 1" % r["easyeda_offset"]
    if "pad layouts do not match" in reason:
        return "that JLC's footprint for this LCSC number matches our pads at all (best fit rms %s mm)" % r["fit_rms_mm"]
    return "position, rotation and pin 1 against JLC's own footprint for this LCSC number (none offline)"


def build():
    bom = {}
    for x in csv.DictReader(open(PKG / "fab/bom-jlcpcb.csv")):
        for d in x["Designator"].replace(" ", "").split(","):
            bom[d] = x["Manufacturer Part Number"]
    rows = [x for x in csv.DictReader(open(PKG / "cpl-rotation-audit/audit.csv")) if x["class"] == "NEEDS-PREVIEW"]
    L = ["# CPL preview checklist: the NEEDS-PREVIEW parts (prepared, NOT ordered)", "",
         "Generated by `owner-items/order/scripts/cpl_preview_checklist.py` from `cpl-rotation-audit/audit.csv` and",
         "`fab/bom-jlcpcb.csv` (s52). The audit classes the 372 CPL rows of `fab/cpl-jlcpcb.csv` as OK 300, CORRECTED 32,",
         "NEEDS-PREVIEW %d, excluded 17 (consigned or hand-assembled, so JLC does not place them). The NEEDS-PREVIEW rows" % len(rows),
         "are not changed in the CPL. In JLC's CPL preview, confirm each one below before confirming the order.", "",
         "Note: `cpl-rotation-audit/README.md` still carries the stage-45 counts (284 / 32 / 31); `audit.csv` is the s52 result.", "",
         "| # | Refdes | MPN | LCSC | Footprint | KiCad rot | CPL rot | What to check | Audit reason |",
         "| ---: | --- | --- | --- | --- | ---: | ---: | --- | --- |"]
    for i, r in enumerate(rows, 1):
        L.append("| %d | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            i, r["designator"], bom.get(r["designator"], "?"), r["lcsc"], r["footprint"], r["kicad_rot"],
            r["proposed_jlc_rot"], what_to_check(r), r["reason"].replace("|", "/")))
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = build()
    if a.check:
        sys_exit = 0 if OUT.exists() and OUT.read_text() == text else 1
        print("CPL-PREVIEW-CHECKLIST.md", "matches" if sys_exit == 0 else "DIFFERS")
        raise SystemExit(sys_exit)
    OUT.write_text(text)
    print("wrote", OUT, text.count("\n| ") - 1, "rows")
