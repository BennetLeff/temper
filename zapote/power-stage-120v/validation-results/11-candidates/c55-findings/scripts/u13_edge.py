#!/usr/bin/env python3
"""S30 at stage 55: the R134 / C167 node through U47 (SN74LVC1G17 Schmitt buffer) into U13.A (SN74LVC1G332).

    python3 -I validation-results/11-candidates/c55-findings/scripts/u13_edge.py

Datasheet values (local copies; sha256 prefixes as in the datasheet ledger):
  SN74LVC1G17  TI SCES351Y (Oct 2025, c76fa723fac45024): Recommended Operating Conditions p.5 carry no input-transition
               limit (Schmitt input; 8.1 p.11 "where the input is slow or noisy"); p.6 at VCC 3 V: VT+ 1.48-1.92 V,
               VT- 0.89-1.20 V, hysteresis 0.51-0.83 V; VOH >= 2.3 V at IOH -24 mA, VOL <= 0.55 V at IOL 24 mA;
               p.7 Table 5-4 tpd <= 6.5 ns (3.3 V +- 0.3 V, -40..125 C, CL 30 / 50 pF).
  SN74LVC1G332 TI SCES489E (Dec 2013, 5ecad3180cb93664): p.3 dt/dv <= 10 ns/V at 3.3 V +- 0.3 V, VIL 0.8 / VIH 2.0 V
               (2.7-3.6 V); p.4 Ci 3.5 pF typical.
Board: R134 1 k 1 % (0603WAF1001T5E), C167 100 pF 5 % C0G (CL10C101JB8NNNC), v3v3 3.135-3.465 V (pin_absmax_registry).

1. U13.A edge (stage 55). Across U13's 0.8-2.0 V input band U47's output sits between its VOL and VOH test points, where a
   CMOS stage sources / sinks at least the tabulated 24 mA (the device current only rises as the output moves away
   from the test point). Into C_load <= 20 pF (U13 Ci 3.5 pF typical, a 4 mm 0.25 mm trace < 1 pF, about 5x margin
   on the typical) the slope is >= 24 mA / 20 pF, i.e. <= 0.83 ns/V.
2. U47.A edge. No transition limit applies to the Schmitt input; the RC edge is reported for the record.
3. Trip delay (rising RC edge from 0 V to the final level Vf): stage 54 switched U13.A anywhere up to VIH 2.0 V, stage 55
   switches U47 at VT+ <= 1.92 V plus tpd <= 6.5 ns. Slow corner: tau max 1.01 k x 105 pF, Vf 3.135 V.
4. CMTI glitch rejection (a full-swing upset of width w from U9 at the fast corner: tau min 0.99 k x 95 pF, Vf 3.465 V):
   stage 54 rejected only what stays under U13's lowest possible switching point (VIL 0.8 V); stage 55 what stays under
   VT+ min 1.48 V.
Writes results/u13-edge.json and results/u13-edge.md.
"""
import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "results"
I_DRIVE = 24e-3          # A, SCES351Y p.6 at VCC 3 V
C_LOAD = 20e-12          # F, bound (Ci 3.5 pF typical, SCES489E p.4)
VIL, VIH = 0.8, 2.0      # SCES489E p.3
VTP_MIN, VTP_MAX = 1.48, 1.92   # SCES351Y p.6 (3 V row)
TPD_MAX = 6.5e-9         # SCES351Y p.7 Table 5-4
DTDV_LIMIT = 10.0        # ns/V, SCES489E p.3
TAU_MAX = 1010 * 105e-12
TAU_MIN = 990 * 95e-12
V_LO, V_HI = 3.135, 3.465


def t_cross(tau, vf, v):
    return tau * math.log(vf / (vf - v))


def main():
    slope = C_LOAD / I_DRIVE * 1e9          # ns/V
    # RC edge at U47.A (stage 55) / at U13.A (stage 54): slope (Vf - V) / tau at the band edges, slow corner
    rc_at = lambda v, vf: TAU_MAX * 1e9 / (vf - v)
    res = {
        "u13a_edge_ns_per_V_bound": round(slope, 3),
        "u13a_limit_ns_per_V": DTDV_LIMIT,
        "u13a_ratio": round(slope / DTDV_LIMIT, 4),
        "u47a_rc_edge_ns_per_V": {"at VT- min 0.89 V falling": round(TAU_MAX * 1e9 / 0.89, 1),
                                   "at VT+ max 1.92 V rising": round(rc_at(VTP_MAX, V_LO), 1)},
        "trip_delay_ns": {"s54 (U13.A at VIH 2.0 V)": round(t_cross(TAU_MAX, V_LO, VIH) * 1e9, 1),
                          "s55 (U47 at VT+ 1.92 V + tpd)": round((t_cross(TAU_MAX, V_LO, VTP_MAX) + TPD_MAX) * 1e9, 1)},
        "glitch_rejected_below_ns": {"s54 (U13.A could switch at VIL 0.8 V)": round(t_cross(TAU_MIN, V_HI, VIL) * 1e9, 1),
                                     "s55 (U47 VT+ min 1.48 V)": round(t_cross(TAU_MIN, V_HI, VTP_MIN) * 1e9, 1)},
    }
    OUT.mkdir(exist_ok=True)
    (OUT / "u13-edge.json").write_text(json.dumps(res, indent=1) + "\n")
    t, g = res["trip_delay_ns"], res["glitch_rejected_below_ns"]
    lines = ["# u13-edge.md (generated by scripts/u13_edge.py; do not edit)", "",
             f"U13.A edge at stage 55 (driven by U47): <= {slope:.2f} ns/V (24 mA into <= 20 pF) against {DTDV_LIMIT:.0f} ns/V: "
             f"ratio {slope / DTDV_LIMIT:.3f}.",
             f"U47.A (Schmitt, no transition limit) sees the RC edge: {res['u47a_rc_edge_ns_per_V']['at VT+ max 1.92 V rising']} ns/V "
             f"at VT+ max rising, {res['u47a_rc_edge_ns_per_V']['at VT- min 0.89 V falling']} ns/V at VT- min falling.",
             f"Trip delay through the RC, slow corner: s54 {t['s54 (U13.A at VIH 2.0 V)']} ns, s55 "
             f"{t['s55 (U47 at VT+ 1.92 V + tpd)']} ns.",
             f"Full-swing glitch rejected if shorter than: s54 {g['s54 (U13.A could switch at VIL 0.8 V)']} ns, s55 "
             f"{g['s55 (U47 VT+ min 1.48 V)']} ns (fast corner)."]
    (OUT / "u13-edge.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
