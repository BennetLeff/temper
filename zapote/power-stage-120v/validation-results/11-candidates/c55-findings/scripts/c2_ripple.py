#!/usr/bin/env python3
"""S31: C2 (KEMET R463N410050N1K, X2 1 uF P22.5) ripple current against the attributed 1 uF rating and a bounded Th.

    python3 -I validation-results/11-candidates/c55-findings/scripts/r46_irms_digitize.py   (first)
    python3 -I validation-results/11-candidates/c55-findings/scripts/c2_ripple.py

Inputs (all committed):
  - stress: c54-ledger-desk/results/cx_current.json, the worst release (pan_18.375A) and 28 A (pan_28A) C2 line-cycle
    RMS over every variant (inlet module or not, L1 stray 8 / 18 uH, DC-link ESR 2.55 / 20 mOhm);
  - rating at Th <= 70 C: results/r46-irms.json, the 1 uF trace of the p.8 22.5 mm graph, its minimum over 35-90 kHz;
  - derating: KEMET p.6, Irms(Th) = Irms(70) x sqrt(dTlim(Th) / 20 K), dTlim 20 K to 70 C falling linearly to 0 at
    110 C, i.e. Irms(Th) = Irms(70) x sqrt((110 - Th) / 40) above 70 C;
  - Th: KEMET p.6 defines Th as the hotter of the ambient around the capacitor and its hottest contact point (tracks).
    Two bases per case: the B3 L1 body row of margins.json ('L1: B82726 climatic', the hottest body beside C1 / C2; the
    air around C2 cannot be hotter than the surface heating it), which bounds the ambient, and the B3 C2 pad-copper
    probe of the case's run file (the contact point) with the bay air (`bay_c`).
Writes results/c2-ripple.json and results/c2-ripple.md.
"""
import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
UNIT = HERE.parents[3]
LANE = HERE.parent
CX = UNIT / "validation-results/11-candidates/c54-ledger-desk/results/cx_current.json"
B3 = UNIT / "validation-results/04-board-current-thermal/round5-native21/b3-ratings"
CASES = {"release": ("c17.5_h10", "pan_18.375A"), "c28": ("c28_h10", "pan_28A")}


def irms_at(i70, th):
    return i70 if th <= 70.0 else i70 * math.sqrt(max(0.0, 110.0 - th) / 40.0)


def th_max(i70, i):
    return 110.0 - 40.0 * (i / i70) ** 2 if i > 0 else 110.0


def main():
    cx = json.loads(CX.read_text())["worst"]
    dig = json.loads((LANE / "results/r46-irms.json").read_text())
    i70 = dig["one_uF_A_min_35_90kHz"]
    margins = json.loads((B3 / "margins.json").read_text())
    out = {"i70_A": i70, "i70_source": "results/r46-irms.json (1 uF trace, min 35-90 kHz)",
           "board_sha256": margins["board_sha256"]["c17.5_h10"], "cases": {}}
    for name, (case, ck) in CASES.items():
        i = max(cx[f"x2 {ck} board alone"]["irms_line_cycle_A"], cx[f"x2 {ck} with module"]["irms_line_cycle_A"])
        l1 = [r for r in margins["cases"][case] if " ".join(r["item"].split()[:3]) == "L1: B82726 climatic"]
        assert len(l1) == 1, case
        run = json.loads((B3 / f"runs/{case}_p0p25.json").read_text())
        assert run["board_sha256"] == margins["board_sha256"][case], (case, run["board_sha256"])
        pad = run["probes"]["C2"]["pad_max_cell_c"]
        local = max(pad, run["bay_c"])
        tm = th_max(i70, i)
        out["cases"][name] = {
            "b3_case": case, "stress_A": round(i, 4),
            "th_max_C": round(tm, 1),
            "l1_body_C": l1[0]["est_c"], "c2_pad_C": round(pad, 1), "bay_C": run["bay_c"], "local_th_C": round(local, 1),
            "limit_at_l1_body_A": round(irms_at(i70, l1[0]["est_c"]), 3),
            "ratio_at_l1_body": round(i / irms_at(i70, l1[0]["est_c"]), 4),
            "limit_at_local_A": round(irms_at(i70, local), 3),
            "ratio_at_local": round(i / irms_at(i70, local), 4),
        }
    (LANE / "results/c2-ripple.json").write_text(json.dumps(out, indent=1) + "\n")
    rows = ["# c2-ripple.md (generated by scripts/c2_ripple.py; do not edit)", "",
            f"C2 R463N410050N1K, 1 uF P22.5: Irms(Th <= 70 C) = {i70:.2f} A (1 uF trace, results/r46-irms.md), "
            f"x sqrt((110 - Th) / 40) above 70 C (KEMET p.6). Board {out["board_sha256"][:12]}.", "",
            "| Case | C2 stress (A, line-cycle RMS) | Th max for it (C) | L1 body (C) | limit / ratio at L1 body | "
            "C2 pad / bay (C) | limit / ratio at max(pad, bay) |", "|---|---|---|---|---|---|---|"]
    for name, r in out["cases"].items():
        rows.append(f"| {name} ({r['b3_case']}) | {r['stress_A']:.3f} | {r['th_max_C']:.1f} | {r['l1_body_C']:.1f} | "
                    f"{r['limit_at_l1_body_A']:.3f} A / {r['ratio_at_l1_body']:.3f} | {r['c2_pad_C']:.1f} / {r['bay_C']:.1f} | "
                    f"{r['limit_at_local_A']:.3f} A / {r['ratio_at_local']:.3f} |")
    rel = out["cases"]["release"]
    c28 = out["cases"]["c28"]
    rows += ["", f"release: {rel['stress_A']:.3f} A needs Th <= {rel['th_max_C']:.1f} C; the L1-body bound is "
                 f"{rel['l1_body_C']:.1f} C, so it holds at the bound ({rel['ratio_at_l1_body']:.3f} of the derated rating).",
             f"c28: {c28['stress_A']:.3f} A needs Th <= {c28['th_max_C']:.1f} C; above the L1-body bound "
             f"({c28['l1_body_C']:.1f} C, ratio {c28['ratio_at_l1_body']:.3f}), inside it at the C2 pad / bay basis "
             f"(ratio {c28['ratio_at_local']:.3f})."]
    (LANE / "results/c2-ripple.md").write_text("\n".join(rows) + "\n")
    print("\n".join(rows))


if __name__ == "__main__":
    main()
