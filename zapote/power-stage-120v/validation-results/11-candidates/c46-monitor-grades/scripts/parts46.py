#!/usr/bin/env python3
"""Stage 46 part choice from the cached JLC public records (scripts/jlc-raw, read 2026-10-15 by scripts/jlc.py; untrusted,
named fields only). Offline.

    python3 -I scripts/parts46.py   -> results/parts-s46.md

Need: 3 per board x 500 boards = 1,500 for the monitor ICs; 1 x 500 = 500 for U5.
"""
import sys as _s; _s.dont_write_bytecode = True
import sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.argv = [sys.argv[0], "--offline"]
sys.path.insert(0, str(HERE))
import jlc  # noqa: E402

ROWS = [  # role, refs, need, searched MPN, chosen?
    ("monitor reference (was TL431BIDBZR C41283)", "U17/U19/U21", 1500, "TL431BQDBZR", "C190245"),
    ("monitor comparator (was LM339BIDR C22416291)", "U29/U30/U31", 1500, "LM2901BIDR", "C22427890"),
    ("REF25 (as built LM4040A25IDBZR)", "U5", 500, "LM4040A25IDBZR", "C9421"),
    ("REF25 125 C grade, 0.5 %", "U5", 500, "LM4040C25QDBZR", "C2872469"),
    ("REF25 125 C grade, 1 %", "U5", 500, "LM4040D25QDBZR", "C2156615"),
    ("REF25 125 C, LM4040-N C grade", "U5", 500, "LM4040CEM3-2.5", "C701885"),
    ("REF25 125 C, LM4040-N Q1 C grade", "U5", 500, "LM4040QCEM3-2.5", "C1880333"),
    ("REF25 125 C, LM4050-N Q1 A grade", "U5", 500, "LM4050QAEM3-2.5", "C2157745"),
]


def main():
    L = ["# Stage 46 parts at JLC (generated by scripts/parts46.py from scripts/jlc-raw; do not edit)\n",
         "| Role | Refs | Need | Searched | LCSC | JLC MPN / brand | Library | Stock | Stock >= need | $ at need | Fetched (UTC) |",
         "|---|---|---:|---|---|---|---|---:|---|---:|---|"]
    for role, refs, need, mpn, code in ROWS:
        hit = next((h for h in jlc.search(mpn) if h[0] == code), None)
        det = jlc.detail(code) if hit else {}
        stock = hit[2] if hit else 0
        L.append(f"| {role} | {refs} | {need:,} | {mpn} | {code} | {hit[3] if hit else '-'} / {hit[4] if hit else '-'} | "
                 f"{hit[1] if hit else '-'} | {stock:,} | {'yes' if stock >= need else '**no**'} | "
                 f"{jlc.price_at(det, need) if det else '-'} | {jlc.fetched(code) or '-'} |")
    out = HERE.parent / "results/parts-s46.md"
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
