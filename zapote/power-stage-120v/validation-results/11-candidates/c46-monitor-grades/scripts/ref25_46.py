#!/usr/bin/env python3
"""Stage 46, U5 (LM4040A25IDBZR, REF25): what its 125 C grades would do to the bands it sets, and whether JLC stocks them.

    python3 -I scripts/ref25_46.py   -> results/ref25-s46.json, results/ref25-s46.md

REF25 consumers (elec/src/power_stage_120v.ato u_ref): the shunt-OCP threshold (R34 12.6 k / R35 11.7 k, and R32 / R33 10 k
on the Kelvin node) and the bus OVP threshold (R36 10 k / R37 140 k). Method = the committed one: task-02 round-3
thresholds.py exact_corners (imported unchanged) with stage 17's R5 CSS2H tuple and the stage-15 divider, as
round5-native21/stage17-r5/ocp_band17.py. exact_corners takes REF25 at 2.5 V +- 20 mV (A25I +-19 mV full range plus the
1 mV load allowance); a grade with a wider full-range tolerance T is evaluated by mapping those two corners to
2.5 V +- (T + 1 mV) - every output is monotonic in REF25, so the vertices still bound it.
Grades (TI SLOS456Q, Apr 2026): A25I 6.8 p.9: +-19 mV over -40..85 C; C25Q 6.10 p.11: +-38 mV over -40..125 C; D25Q 6.10 p.11:
+-63 mV over -40..125 C (no A or B grade is specified over -40..125 C; 6.3 p.5 TA ranges).
Control: the A25I mapping (scale 1) reproduces ocp_band17.json's 69.89-116.44 A.
Acceptance (committed): OCP low corner after the s45 Kelvin shift (-2.123 A, kelvin/budget-native21s45.json) >= the 64.17 A
floor (kelvin_budget.FLOOR); OVP upper corner must not rise (simplify-2026-10-15 ovp_band.py rule: the bus maximum that the
D3 / C5 C6 / ALT-BIAS ledger rows use).
"""
import sys as _s; _s.dont_write_bytecode = True
import importlib.util, json
from pathlib import Path

HERE = Path(__file__).resolve().parent
PS = HERE.parents[3]
VR = PS / "validation-results"
OUT = HERE.parent / "results"
spec = importlib.util.spec_from_file_location("thr", VR / "02-protection-timing/round3/thresholds.py")
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)
RT = (0.001, 25e-6)
m.PARTS.update({"R34": (12.6e3, *RT), "R35": (11.7e3, *RT)})
m.PARTS["R5"] = m.SHUNT_CSS2H
ORIG = m.thresholds
KELVIN = json.loads((VR / "02-protection-timing/kelvin/budget-native21s45.json").read_text())
SHIFT = KELVIN["trip_shift_A"] if "trip_shift_A" in KELVIN else None
FLOOR = 64.17
JLC = {  # JLC part API 2026-10-15 (runs-native21/s46/dl/jlc-raw; read-only), stock against 1 per board x 500
    "LM4040A25IDBZR": ("C9421", 4775), "LM4040C25QDBZR": ("C2872469", 133), "LM4040D25QDBZR": ("C2156615", 0),
    "LM4040CEM3-2.5/NOPB": ("C701885", 104), "LM4040QCEM3-2.5/NOPB": ("C1880333", 95), "LM4050QAEM3-2.5/NOPB": ("C2157745", 43)}
GRADES = [("LM4040A25IDBZR", 0.019, (-10.0, 85.0), "SLOS456Q 6.8 p.9: +-19 mV, -40..85 C (as built)"),
          ("LM4040C25QDBZR", 0.038, (-10.0, 85.0), "SLOS456Q 6.10 p.11: +-38 mV over -40..125 C; network at the committed -10/85 C"),
          ("LM4040C25QDBZR", 0.038, (-10.0, 105.0), "same, network corner at 105 C (U5 pad 104.5 C at c28 @ 55)"),
          ("LM4040D25QDBZR", 0.063, (-10.0, 85.0), "SLOS456Q 6.10 p.11: +-63 mV over -40..125 C")]


def band(tol, temps):
    scale = (tol + 0.001) / 0.020
    m.thresholds = lambda p, ref, vos, **kw: ORIG(p, 2.5 + (ref - 2.5) * scale, vos, **kw)
    try:
        r = [m.exact_corners(t, 50.0) for t in temps]
    finally:
        m.thresholds = ORIG
    return {k: [round(min(x[k]["min"] for x in r), 2), round(max(x[k]["max"] for x in r), 2)] for k in ("shunt_a", "ovp_v")}


def main():
    ctrl = band(0.019, (-10.0, 85.0))
    assert ctrl["shunt_a"] == [69.89, 116.44], ctrl
    base_ovp_hi = ctrl["ovp_v"][1]
    rows = []
    for mpn, tol, temps, note in GRADES:
        b = band(tol, temps)
        lo_after = round(b["shunt_a"][0] + SHIFT, 2)
        code, stock = JLC[mpn]
        rows.append({"mpn": mpn, "lcsc": code, "jlc_stock": stock, "stock_ok_500": stock >= 500, "tolerance_V": tol,
                     "network_temps_C": list(temps), "note": note, "ocp_band_before_kelvin_A": b["shunt_a"],
                     "ocp_low_after_kelvin_A": lo_after, "ocp_floor_margin_A": round(lo_after - FLOOR, 2),
                     "ovp_band_V": b["ovp_v"], "ovp_upper_rise_V": round(b["ovp_v"][1] - base_ovp_hi, 2)})
    out = {"control": "A25I mapping reproduces ocp_band17.json 69.89-116.44 A", "kelvin_shift_A": SHIFT, "floor_A": FLOOR,
           "rows": rows, "other_ti_125C_shunts_jlc": {k: v for k, v in JLC.items() if k not in [g[0] for g in GRADES]}}
    OUT.mkdir(exist_ok=True)
    (OUT / "ref25-s46.json").write_text(json.dumps(out, indent=1) + "\n")
    L = ["# U5 REF25 grades (generated by scripts/ref25_46.py; do not edit)\n", f"Control: {out['control']}. Kelvin shift "
         f"{SHIFT} A (s45 budget), floor {FLOOR} A.\n",
         "| MPN | LCSC / JLC stock (need 500) | REF25 tol | network T | OCP band before Kelvin (A) | OCP low after Kelvin, margin to floor | OVP band (V) | OVP upper rise |",
         "|---|---|---:|---|---|---|---|---:|"]
    for r in rows:
        L.append(f"| {r['mpn']} | {r['lcsc']} / {r['jlc_stock']:,} | +-{r['tolerance_V'] * 1e3:g} mV | {r['network_temps_C']} | "
                 f"{r['ocp_band_before_kelvin_A']} | {r['ocp_low_after_kelvin_A']} ({r['ocp_floor_margin_A']:+.2f}) | "
                 f"{r['ovp_band_V']} | {r['ovp_upper_rise_V']:+.2f} |")
    L.append("\nOther TI 2.5 V shunt references rated -40..125 C in SOT-23-3 at JLC (2026-10-15): " +
             ", ".join(f"{k} {v[0]} ({v[1]})" for k, v in out["other_ti_125C_shunts_jlc"].items()) + ".")
    (OUT / "ref25-s46.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
