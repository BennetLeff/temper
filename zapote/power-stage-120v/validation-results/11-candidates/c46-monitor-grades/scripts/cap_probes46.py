#!/usr/bin/env python3
"""Pad-copper estimates of the FET-row C0G caps from the s46 B3 run files (hot copper), for the datasheet ledger.

    python3 -I scripts/cap_probes46.py   -> results/cap-probes-s46.json, results/cap-probes-s46.md

The run files (b3-ratings/runs/<case>_p0p25.json / _p0p5.json, gitignored, written by the chain's run_basis.py) carry
"probes": the pad-copper maximum of every footprint (body_runs probes=True, the S16 monitor-probe mechanism). This applies
the B3 gate's own estimator (b3_ratings_gate.est: Q(0.25) + 3 |Q(0.25) - Q(0.5)| + (bay - 50)) to the snubber caps
C12 / C13 / C19 / C20 (CC1206JKNPOCBN102) and the Cgs caps C55 / C56 / C62 / C63 (GRM1885C1H472JA01D). Before stage 46
the ledger bounded both by the FET-row laminate copper (no row of their own). The pad temperature is the cap's local
temperature proxy (no self-heat added: C0G at the edge-current RMS bound is a few mW). Asserts the run files are the
board margins.json was solved on.
"""
import sys as _s; _s.dont_write_bytecode = True
import json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PS = HERE.parents[3]
RAT = PS / "validation-results/04-board-current-thermal/round5-native21/b3-ratings"
sys.path.insert(0, str(RAT))
import b3_ratings_gate as gate  # noqa: E402

GROUPS = {"CC1206JKNPOCBN102": ["C12", "C13", "C19", "C20"], "GRM1885C1H472JA01D": ["C55", "C56", "C62", "C63"]}


def main():
    m = json.loads((RAT / "margins.json").read_text())
    out = {"board_sha256": None, "estimator": "b3_ratings_gate.est (no self-heat)", "cases": {}}
    for c, v in m["basis"]["cases"].items():
        a = json.loads((RAT / f"runs/{c}_p0p25.json").read_text())
        b = json.loads((RAT / f"runs/{c}_p0p5.json").read_text())
        assert a["board_sha256"] == b["board_sha256"] == m["board_sha256"][c], c
        assert a["copper_temp_model"]["model"] == "hot-iterated", c
        out["board_sha256"] = a["board_sha256"]
        out["cases"][c] = {"bay_c": v["bay_c"], "role": v["role"], "pads_c": {}}
        for mpn, refs in GROUPS.items():
            for r in refs:
                out["cases"][c]["pads_c"][r] = round(gate.est(a["probes"][r]["pad_max_cell_c"], b["probes"][r]["pad_max_cell_c"],
                                                             v["bay_c"]), 1)
    (HERE.parent / "results/cap-probes-s46.json").write_text(json.dumps(out, indent=1) + "\n")
    L = ["# FET-row C0G cap pad estimates, s46 hot-copper BASIS (generated by scripts/cap_probes46.py; do not edit)\n",
         f"Board {out['board_sha256']}; estimator {out['estimator']}.\n", "| MPN | case | bay C | worst ref | worst pad C | all |",
         "|---|---|---:|---|---:|---|"]
    for mpn, refs in GROUPS.items():
        for c, v in out["cases"].items():
            p = {r: v["pads_c"][r] for r in refs}
            w = max(p, key=p.get)
            L.append(f"| {mpn} | {c} | {v['bay_c']:g} | {w} | {p[w]} | {p} |")
    (HERE.parent / "results/cap-probes-s46.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
