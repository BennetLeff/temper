#!/usr/bin/env python3
"""Stage 51: clearances of the dual-pitch bank's pad-2 holes on the built board.

    python3 -I validation-results/11-candidates/c51-bank-source/stage51/scripts/hole_clearance51.py \
        native-21/verification/native21s51-all-copper.json.gz   -> stage51/results/hole-clearance-s51.json / .md

For every bank pad (C21 / C22 / C23 / C151 / C152, pad 1 at x 163.0, pad 2 at x 185.5 and the new x 190.5 hole), from the
all-copper export (tools/export_power_copper.py, FlashLayer-aware pad shells):
  * same layer: edge-to-edge distance to the nearest copper of any other net, per copper layer (DRC checks the netclass
    rule; this is the number behind it);
  * plan view, any layer: edge-to-edge distance to the nearest SELV copper (rules21.SELV; the barrier / D5 HOT-SELV rule
    is 8.0 mm, s50's D5 minimum 8.047 mm) and to the nearest PE copper (D5 HOT-PE, s50 minimum 8.507 mm), and to the
    nearest In1 v3v3 plane copper in particular.
"""
import sys as _s; _s.dont_write_bytecode = True
import gzip
import json
from pathlib import Path

from shapely.geometry import LineString, Point, Polygon
from shapely.ops import unary_union

HERE = Path(__file__).resolve().parent
PS = HERE.parents[4]
_s.path.insert(0, str(PS / "native-21/layout"))
import rules21  # noqa: E402

BANK = ("C21", "C22", "C23", "C151", "C152")
PE = {"pe"}


def geom(p):
    k = p["kind"]
    if k in ("zone", "pad"):
        g = Polygon(p["shell"], p.get("holes") or [])
        return g if g.is_valid else g.buffer(0)
    if k == "track":
        return LineString([p["start"], p["end"]]).buffer(p["width_mm"] / 2, cap_style=1)
    if k == "via":
        return Point(p["centre"]).buffer(p["diameter_mm"] / 2)
    raise KeyError(k)


def main():
    src = Path(_s.argv[1])
    d = json.load(gzip.open(src))
    prims = [(p, geom(p)) for p in d["primitives"]]
    pads = [(p, g) for p, g in prims if p["kind"] == "pad" and p["ref"].split(".")[0] in BANK]
    selv = unary_union([g for p, g in prims if p["net"] in rules21.SELV])
    pe = unary_union([g for p, g in prims if p["net"] in PE])
    v3 = unary_union([g for p, g in prims if p["net"] == "v3v3" and p["layer"] == "In1.Cu" and p["kind"] == "zone"])
    rows = []
    for p, g in pads:
        other = [(q, h) for q, h in prims if q["layer"] == p["layer"] and q["net"] != p["net"]]
        near = min(other, key=lambda qh: g.distance(qh[1]))
        rows.append({"pad": p["ref"], "net": p["net"], "layer": p["layer"], "centre": p["centre"],
                     "same_layer_other_net_mm": round(g.distance(near[1]), 3), "nearest_other_net": near[0]["net"],
                     "nearest_other_kind": near[0]["kind"], "plan_selv_mm": round(g.distance(selv), 3),
                     "plan_pe_mm": round(g.distance(pe), 3), "plan_in1_v3v3_plane_mm": round(g.distance(v3), 3)})
    by = {}
    for r in rows:
        k = (r["pad"], tuple(r["centre"]))
        b = by.setdefault(k, {"pad": r["pad"], "net": r["net"], "centre": r["centre"], "layers": {},
                              "plan_selv_mm": r["plan_selv_mm"], "plan_pe_mm": r["plan_pe_mm"],
                              "plan_in1_v3v3_plane_mm": r["plan_in1_v3v3_plane_mm"]})
        b["layers"][r["layer"]] = {"other_net_mm": r["same_layer_other_net_mm"], "net": r["nearest_other_net"],
                                   "kind": r["nearest_other_kind"]}
        for f in ("plan_selv_mm", "plan_pe_mm", "plan_in1_v3v3_plane_mm"):
            b[f] = min(b[f], r[f])
    holes = sorted(by.values(), key=lambda b: (b["centre"][0], b["centre"][1]))
    new = [b for b in holes if abs(b["centre"][0] - 190.5) < 0.01]
    out = {"board_sha256": d["board_sha256"], "source": str(src), "pads": holes,
           "new_holes_x190p5": None if not new else {"count": len(new),
                                "min_same_layer_other_net_mm": min(min(v["other_net_mm"] for v in b["layers"].values()) for b in new),
                                "min_plan_selv_mm": min(b["plan_selv_mm"] for b in new),
                                "min_plan_pe_mm": min(b["plan_pe_mm"] for b in new),
                                "min_plan_in1_v3v3_plane_mm": min(b["plan_in1_v3v3_plane_mm"] for b in new)},
           "all_bank_pads": {"min_plan_selv_mm": min(b["plan_selv_mm"] for b in holes),
                             "min_plan_pe_mm": min(b["plan_pe_mm"] for b in holes)}}
    o = HERE.parent / "results"
    o.mkdir(exist_ok=True)
    (o / "hole-clearance-s51.json").write_text(json.dumps(out, indent=1) + "\n")
    L = ["# Bank pad clearances, stage 51 (generated by stage51/scripts/hole_clearance51.py; do not edit)\n",
         f"Board {d['board_sha256'][:8]}. Edge-to-edge mm. Same layer: nearest other-net copper on that layer (worst layer "
         "shown). Plan view: nearest SELV / PE copper on any layer, and the In1 v3v3 plane.\n",
         "| Pad | Net | Centre | Same layer, worst (layer, net) | Plan SELV | Plan PE | Plan In1 v3v3 |", "|---|---|---|---|---:|---:|---:|"]
    for b in holes:
        ly, w = min(b["layers"].items(), key=lambda kv: kv[1]["other_net_mm"])
        L.append(f"| {b['pad']} | {b['net']} | {b['centre']} | {w['other_net_mm']} ({ly}, {w['net']} {w['kind']}) | "
                 f"{b['plan_selv_mm']} | {b['plan_pe_mm']} | {b['plan_in1_v3v3_plane_mm']} |")
    L += ["", f"New x 190.5 holes: {out['new_holes_x190p5']}", f"All bank pads: {out['all_bank_pads']}"]
    (o / "hole-clearance-s51.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[-2:]))


if __name__ == "__main__":
    main()
