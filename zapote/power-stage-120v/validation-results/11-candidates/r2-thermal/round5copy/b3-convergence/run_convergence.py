#!/usr/bin/env python3
"""Compute stage of the B3 convergence study (stage 19b). Writes runs/<name>.json (one per solve).

    python3 run_convergence.py [--stage controls|global|windows|all] [--workers 3] [--fresh]
    python3 report_convergence.py        # analysis, controls assertion, results.json, plots

Inputs (gitignored, regenerated by ../run_cases.py or copied from ps-integrate): ../outputs/*-heat.npz for the 14 A4
cases of the stage-19b board; native-21/verification/native21s19b-all-copper.json.gz; inputs/part-bodies.json
(extract_bodies.py from native-21/section.kicad_pcb). <= 4 worker processes (default 3).
"""
from __future__ import annotations

import argparse
import json
import math
import sys
import time
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import body_runs as br  # noqa: E402
import thermal_body as tb  # noqa: E402

RUNS = HERE / "runs"
CACHE = HERE / "cache"                       # gitignored: fine masks and rise fields
PITCHES = (1.0, 0.5, 0.25)
FINE = 0.125
GLOBAL_OPS = [("c28", 25), ("nominal", 25)]            # the mesh-sensitivity cases named in the task
VERDICT_OPS = [("c28", 25), ("c28", 10), ("der14", 10)]  # 28 A h25, 28 A h10 (no derate), stall-derated 14 A ceiling h10
CONFIGS = {"legacy": ("binary", "point"), "binary+network": ("binary", "network"),
           "fraction+point": ("fraction", "point"), "main": ("fraction", "network")}
SENS = {"all_pins": {"all_pins": True}, "r_pad_x0.5": {"r_scale": 0.5}, "r_pad_x2": {"r_scale": 2.0},
        "h_body_x0.5": {"h_body_factor": 0.5}, "gap_path": {"gap": True}, "air_all": {"air_all": True}}

_BRD = None


def board():
    global _BRD
    if _BRD is None:
        _BRD = tb.Board(br.rs.GEOM, CACHE)
        _BRD.fine()
    return _BRD


def rise_path(name):
    return CACHE / f"rise_{name}.npz"


def do_task(t):
    """Run one task dict; returns (name, seconds). Skips if the result file exists (unless t['fresh'])."""
    out = RUNS / f"{t['name']}.json"
    if out.exists() and not t.get("fresh"):
        return t["name"], 0.0
    brd = board()
    copper, source = CONFIGS[t["config"]]
    bc = None
    ref_rise = None
    window = None
    if t.get("window"):
        window = tuple(t["window"])
        z = np.load(rise_path(t["bc_from"]))
        g = z["rise"]
        pg = float(z["pitch"]) if "pitch" in z.files else 0.25
        wg = z["window"] if "window" in z.files else np.array([0, 0, 0, 0])
        origin = (brd.xmin + int(wg[0]) * pg, brd.ymin + int(wg[2]) * pg)
        bc = br.bc_from_global(g, pg, origin, brd, t["pitch"], *window)
        ref_rise = g
    t0 = time.time()
    res, rise = br.run_case(brd, t["op"], t["h"], t["pitch"], copper, source, t.get("sens") or {}, window, bc,
                            t.get("use_a4", True), t.get("use_parts", True), label=t["name"], return_rise=True)
    res["task"] = {k: v for k, v in t.items() if k != "fresh"}
    if t.get("save_rise"):
        CACHE.mkdir(exist_ok=True)
        np.savez_compressed(rise_path(t["name"]), rise=rise.astype(np.float64), pitch=t["pitch"],
                            window=np.array(window if window else [0, 0, 0, 0]))
    if ref_rise is not None and abs(t["pitch"] - 0.25) < 1e-9 and abs(pg - 0.25) < 1e-9 and int(wg[1]) == 0:
        i0, i1, j0, j1 = window
        sub = ref_rise[:, i0 + 1:i1 - 1, j0 + 1:j1 - 1]
        mine = rise[:, 1:-1, 1:-1]
        res["control_vs_global_max_abs_k"] = float(np.abs(sub - mine).max())
    RUNS.mkdir(exist_ok=True)
    out.write_text(json.dumps(res, indent=1) + "\n")
    return t["name"], time.time() - t0


def tname(op, h, pitch, config, extra=""):
    return f"{op}_h{h}_p{str(pitch).replace('.', 'p')}_{config.replace('+', '-')}{extra}"


def global_tasks(fresh):
    tasks = []
    for op, h in GLOBAL_OPS:
        for cfg in CONFIGS:
            for p in PITCHES:
                tasks.append(dict(name=tname(op, h, p, cfg), op=op, h=h, pitch=p, config=cfg, fresh=fresh,
                                  save_rise=(cfg == "main" and p == 0.25)))
    for op, h in VERDICT_OPS:
        if (op, h) in GLOBAL_OPS:
            continue
        for p in PITCHES:
            tasks.append(dict(name=tname(op, h, p, "main"), op=op, h=h, pitch=p, config="main", fresh=fresh,
                              save_rise=(p == 0.25)))
    # decomposition (c28 h25): copper heat only / part heat only, legacy vs main model
    for p in PITCHES:
        for cfg in ("legacy", "main"):
            tasks.append(dict(name=tname("c28", 25, p, cfg, "_a4only"), op="c28", h=25, pitch=p, config=cfg,
                              use_parts=False, fresh=fresh))
            tasks.append(dict(name=tname("c28", 25, p, cfg, "_partsonly"), op="c28", h=25, pitch=p, config=cfg,
                              use_a4=False, fresh=fresh))
    # package-network sensitivities (0.5 mm, c28 h25)
    for sname, sens in SENS.items():
        tasks.append(dict(name=tname("c28", 25, 0.5, "main", f"_sens-{sname}"), op="c28", h=25, pitch=0.5,
                          config="main", sens=sens, fresh=fresh))
    return tasks


def make_windows(brd, max_area=6000.0, pad_m=12.0):
    """Merged refinement windows (x0,y0,x1,y1) around every heat part and FET, on 1 mm aligned 0.25 mm-grid indices."""
    heat = json.loads(br.rs.HEAT_C28.read_text())["parts"]
    refs = [p["ref"] for p in heat if p.get("board_fraction") not in (None, 0)] + list(br.FET_REFS)
    rects = []
    for r in refs:
        polys = [poly for lst in brd.pads_of(r).values() for _, poly in lst]
        xs = [b for poly in polys for b in (poly.bounds[0], poly.bounds[2])]
        ys = [b for poly in polys for b in (poly.bounds[1], poly.bounds[3])]
        rects.append([min(xs) - pad_m, min(ys) - pad_m, max(xs) + pad_m, max(ys) + pad_m, {r}])
    changed = True
    while changed:
        changed = False
        for i in range(len(rects)):
            for j in range(i + 1, len(rects)):
                a, b = rects[i], rects[j]
                if a[0] < b[2] and b[0] < a[2] and a[1] < b[3] and b[1] < a[3]:
                    u = [min(a[0], b[0]), min(a[1], b[1]), max(a[2], b[2]), max(a[3], b[3])]
                    if (u[2] - u[0]) * (u[3] - u[1]) <= max_area:
                        rects[i] = u + [a[4] | b[4]]
                        rects.pop(j)
                        changed = True
                        break
            if changed:
                break
    nxg, nyg = brd.grid_n(0.25)
    out = []
    for k, (x0, y0, x1, y1, rs_) in enumerate(sorted(rects, key=lambda r: (r[0], r[1]))):
        i0 = max(int(math.floor((x0 - brd.xmin) / 0.25 / 4)) * 4, 0)
        j0 = max(int(math.floor((y0 - brd.ymin) / 0.25 / 4)) * 4, 0)
        i1 = min(int(math.ceil((x1 - brd.xmin) / 0.25 / 4)) * 4, nxg)
        j1 = min(int(math.ceil((y1 - brd.ymin) / 0.25 / 4)) * 4, nyg)
        out.append({"id": f"W{k:02d}", "win025": [i0, i1, j0, j1], "refs": sorted(rs_),
                    "x_mm": [brd.xmin + i0 * 0.25, brd.xmin + i1 * 0.25], "y_mm": [brd.ymin + j0 * 0.25, brd.ymin + j1 * 0.25]})
    return out


def window_tasks(brd, fresh):
    wins = make_windows(brd)
    (HERE / "windows.json").write_text(json.dumps(wins, indent=1) + "\n")
    tasks = []
    for op, h in VERDICT_OPS:
        g = tname(op, h, 0.25, "main")
        for w in wins:
            i0, i1, j0, j1 = w["win025"]
            tasks.append(dict(name=tname(op, h, FINE, "main", f"_{w['id']}"), op=op, h=h, pitch=FINE, config="main",
                              window=[2 * i0, 2 * i1, 2 * j0, 2 * j1], bc_from=g, fresh=fresh))
    # window-vs-global control: same 0.25 mm mesh inside the window must reproduce the global solution
    for w in wins[:3] + [x for x in wins if "R5" in x["refs"]][:1]:
        tasks.append(dict(name=tname("c28", 25, 0.25, "main", f"_{w['id']}ctl"), op="c28", h=25, pitch=0.25,
                          config="main", window=list(w["win025"]), bc_from=tname("c28", 25, 0.25, "main"), fresh=fresh))
    return tasks, wins


FINEST = 0.0625
# nested 0.0625 mm windows (pad bounding box + 7 mm) around the thermally critical parts, BC from the 0.125 mm parent
FINE_GROUPS = [("R5", ["R5"], "W00"), ("U41", ["U41"], "W01"), ("U42", ["U42"], "W01"), ("U26", ["U26", "U37"], "W04"),
               ("R39", ["R39"], "W05"), ("PS2", ["PS2"], "W07"), ("PS1", ["PS1"], "W09"), ("R58", ["R58"], "W00"),
               ("FETROW", ["Q2", "Q3"], "W00")]
FINE_OPS = [("c28", 25), ("der14", 10)]


def fine_tasks(brd, fresh):
    wins = {w["id"]: w for w in json.loads((HERE / "windows.json").read_text())}
    nested, tasks, parents = [], [], set()
    for gid, refs, pid in FINE_GROUPS:
        polys = [poly for r_ in refs for lst in brd.pads_of(r_).values() for _, poly in lst]
        x0 = min(p.bounds[0] for p in polys) - 7.0
        x1 = max(p.bounds[2] for p in polys) + 7.0
        y0 = min(p.bounds[1] for p in polys) - 7.0
        y1 = max(p.bounds[3] for p in polys) + 7.0
        px, py = wins[pid]["x_mm"], wins[pid]["y_mm"]
        x0, x1 = max(x0, px[0] + 2.5), min(x1, px[1] - 2.5)
        y0, y1 = max(y0, py[0] + 2.5), min(y1, py[1] - 2.5)
        i0, i1 = int(math.floor((x0 - brd.xmin) / FINEST)), int(math.ceil((x1 - brd.xmin) / FINEST))
        j0, j1 = int(math.floor((y0 - brd.ymin) / FINEST)), int(math.ceil((y1 - brd.ymin) / FINEST))
        nested.append({"id": f"F_{gid}", "parent": pid, "refs": refs, "win": [i0, i1, j0, j1], "x_mm": [x0, x1], "y_mm": [y0, y1]})
        parents.add(pid)
    (HERE / "windows_fine.json").write_text(json.dumps(nested, indent=1) + "\n")
    for op, h in FINE_OPS:
        for pid in sorted(parents):
            w = wins[pid]
            i0, i1, j0, j1 = w["win025"]
            tasks.append(dict(name=tname(op, h, FINE, "main", f"_{pid}").replace("p0p0625", "p0p125"), op=op, h=h, pitch=0.125,
                              config="main", window=[2 * i0, 2 * i1, 2 * j0, 2 * j1], bc_from=tname(op, h, 0.25, "main"),
                              save_rise=True, fresh=True))
    return nested, tasks


def fine_stage2(nested, fresh):
    tasks = []
    for op, h in FINE_OPS:
        for n in nested:
            tasks.append(dict(name=tname(op, h, FINEST, "main", f"_{n['id']}"), op=op, h=h, pitch=FINEST, config="main",
                              window=n["win"], bc_from=tname(op, h, 0.125, "main", f"_{n['parent']}"), fresh=fresh))
    return tasks


def run_pool(tasks, workers):
    t0 = time.time()
    # largest (finest) first so the pool stays busy
    tasks = sorted(tasks, key=lambda t: -(1.0 / t["pitch"]) ** 2 * (0.15 if t.get("window") else 1.0))
    with ProcessPoolExecutor(max_workers=workers) as ex:
        for name, dt in ex.map(do_task, tasks):
            if dt:
                print(f"[{time.time() - t0:6.0f}s] {name}: {dt:.0f} s", flush=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", default="all", choices=("controls", "global", "windows", "fine", "all"))
    ap.add_argument("--workers", type=int, default=3)
    ap.add_argument("--fresh", action="store_true")
    a = ap.parse_args()
    assert a.workers <= 4
    RUNS.mkdir(exist_ok=True)
    CACHE.mkdir(exist_ok=True)
    brd = board()
    if a.stage in ("global", "all"):
        run_pool(global_tasks(a.fresh), a.workers)
    if a.stage in ("fine", "all"):
        nested, parent_tasks = fine_tasks(brd, a.fresh)
        print(f"re-saving {len(parent_tasks)} parent 0.125 mm windows, then {len(nested) * len(FINE_OPS)} nested 0.0625 mm solves", flush=True)
        run_pool(parent_tasks, a.workers)
        run_pool(fine_stage2(nested, a.fresh), a.workers)
    if a.stage in ("windows", "all"):
        tasks, wins = window_tasks(brd, a.fresh)
        print(f"{len(wins)} refinement windows, {len(tasks)} window solves", flush=True)
        run_pool(tasks, a.workers)


if __name__ == "__main__":
    main()
