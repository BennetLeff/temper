#!/usr/bin/env python3
"""C1: detection latency, comparator to BIAS_GOOD, for V0 / V1 / V2.     python3 -I scripts/timing.py -> results/timing.{json,md}

Neither comparator has a maximum propagation delay in its data sheet, and the TI functional-safety documents carry no
timing.  Typicals (sources.json): LM339B 1.0 us (5 mV overdrive, SLCS006Z 6.13 p.12); TPS3701 tpd(HL) 9.9 us (an input
falling: UV assert) and tpd(LH) 28.1 us (an input rising: OV assert), +-10 mV overdrive, VDD 24 V (SBVS240C 6.6 p.6);
Figures 12-13 (p.8, +-200 mV step, -40..125 C, VDD 1.8 / 36 V) read <= 9.6 us (HL) and <= 2.5 us (LH).
Downstream heartbeat (c24): <= 89.4 us hand sizing, <= 90.3 us SPICE (M1b, 96 corners), <= 122.9 us with one pump cap
shorted.  Tap filter: tau = (Rt || Rb) x 1 nF.  'Guard x3' is an assumption (no maximum exists), labelled as such.
Rail excursion beyond the threshold during the comparator delay = slew x delay, for illustrative slews (assumption).
"""
import json, os, sys
sys.dont_write_bytecode = True
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "results")
TAPS = {
    "V0": {"neg UV": (4.42e3, 10e3), "neg OV": (7.68e3, 10e3), "span UV": (120e3, 10e3), "span OV": (133e3, 10e3)},
    "V1": {"neg UV": (750.0, 10e3), "neg OV": (2940.0, 10e3), "span UV": (90900.0, 11e3), "span OV": (104000.0, 11e3)},
    "V2": {"neg UV": (15.8e3, 4.42e3), "neg OV": (28.4e3, 6.2e3), "span UV": (240e3, 6.2e3), "span OV": (86.6e3, 2.0e3)},
}
CHAIN = {"hand": 89.4, "spice_M1b": 90.3, "pump_cap_shorted": 122.9}
TPD = {"LM339B": {"UV": 1.0, "OV": 1.0}, "TPS3701_10mV": {"UV": 9.9, "OV": 28.1}, "TPS3701_200mV_fig": {"UV": 9.6, "OV": 2.5}}


def main():
    out = {}
    for var, taps in TAPS.items():
        row = {}
        for n, (rt, rb) in taps.items():
            tau = rt * rb / (rt + rb) * 1e-9 * 1e6
            kind = "UV" if "UV" in n else "OV"
            if var == "V2":
                tpd_small, tpd_large = TPD["TPS3701_10mV"][kind], TPD["TPS3701_200mV_fig"][kind]
            else:
                tpd_small = tpd_large = TPD["LM339B"][kind]
            row[n] = {"tap_tau_us": round(tau, 2), "tpd_typ_small_overdrive_us": tpd_small, "tpd_typ_large_step_us": tpd_large,
                      "total_typ_small_overdrive_us": round(tau + tpd_small + CHAIN["spice_M1b"], 1),
                      "total_guard3_small_overdrive_us": round(tau + 3 * tpd_small + CHAIN["pump_cap_shorted"], 1),
                      "rail_excursion_mV_during_tpd": {f"{s:g} V/ms": round(s * tpd_small, 2) for s in (0.1, 1.0, 10.0)}}
        out[var] = row
    os.makedirs(OUT, exist_ok=True)
    json.dump({"chain_us": CHAIN, "tpd_typ_us": TPD, "variants": out}, open(os.path.join(OUT, "timing.json"), "w"), indent=1, sort_keys=True)
    L = ["# C1 detection latency (generated by scripts/timing.py)", "",
         f"Chain (c24): {CHAIN} us. Comparator typicals: {TPD} us. No maximum exists for either part.", "",
         "| variant | threshold | tap tau us | tpd typ, small overdrive us | tpd typ, 200 mV step us | total typ (tau + tpd + 90.3) us | "
         "guard x3 + pump-cap short us (assumption) | rail excursion during tpd at 0.1 / 1 / 10 V/ms (mV) |", "|---|---|---:|---:|---:|---:|---:|---|"]
    for var, row in out.items():
        for n, r in row.items():
            ex = r["rail_excursion_mV_during_tpd"]
            L.append(f"| {var} | {n} | {r['tap_tau_us']} | {r['tpd_typ_small_overdrive_us']} | {r['tpd_typ_large_step_us']} | "
                     f"{r['total_typ_small_overdrive_us']} | {r['total_guard3_small_overdrive_us']} | {' / '.join(str(v) for v in ex.values())} |")
    open(os.path.join(OUT, "timing.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
