#!/usr/bin/env python3
"""Stage 45 parts-cost delta per BOM line, on the card's basis and on one like-for-like JLC basis.

    python3 -I scripts/cost45.py   -> results/cost-s44-s45.json, results/cost-s44-s45.md

BOMs: sourcing/study-2026-10-15/snapshot/s44/bom-jlcpcb.s44.csv and snapshot/s45/bom-jlcpcb.s45.csv.
* card basis: what scorecard.py sums (STOCK-2026-10-13*.csv, later addenda override; unit_usd_at_500boards x qty). The
  lines this stage removes carry the 2026-10-13 class-default ESTIMATE (TL431AIDBZR $0.40, 0603 thin film $0.008), the
  lines it adds carry fetched JLC prices (addendum-s45), so the card delta mixes two price bases.
* JLC basis: every line on the JLC 2026-10-15 ladders (study-2026-10-15/snapshot/jlc-2026-10-15.json plus the cached
  detail records), each at its own 500-board quantity. This is the S16 study's line_delta basis (+$0.167).
"""
import sys as _s; _s.dont_write_bytecode = True
import csv, glob, json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PS = HERE.parents[3]
SRC = PS / "validation-results/08-manufacturing-package/native-21/sourcing"
STUDY = SRC / "study-2026-10-15"
sys.path.insert(0, str(STUDY / "scripts"))
import jlc_snapshot as S  # noqa: E402  (reads scripts/jlc-raw only on a cache hit; every code below is cached)

NEW = {"TL431BIDBZR": "C41283", "RT0603BRD07750RL": "C861551", "RT0603BRD072K94L": "C705761",
       "RT0603BRD0790K9L": "C728600", "RT0603BRD07104KL": "C861070"}


def bom(p):
    out = {}
    for r in csv.DictReader(open(p)):
        out[r["Manufacturer Part Number"].strip()] = len([d for d in r["Designator"].split(",") if d.strip()])
    return out


def main():
    a, b = bom(STUDY / "snapshot/s44/bom-jlcpcb.s44.csv"), bom(STUDY / "snapshot/s45/bom-jlcpcb.s45.csv")
    st = {}
    for p in sorted(glob.glob(str(SRC / "STOCK-2026-10-13*.csv"))):
        for r in csv.DictReader(open(p)):
            if r["board"].startswith("power"):
                st[r["mpn"].strip()] = r
    lad = {r["mpn"]: r.get("jlc_ladder") for r in json.load(open(STUDY / "snapshot/jlc-2026-10-15.json"))["bom"]}
    for mpn, code in NEW.items():
        lad[mpn] = S.rec_from_detail(code)["jlc_ladder"]
    rows, tot = [], {"card": 0.0, "jlc": 0.0}
    for mpn in sorted(set(a) | set(b)):
        qa, qb = a.get(mpn, 0), b.get(mpn, 0)
        if qa == qb:
            continue
        cu = float(st[mpn]["unit_usd_at_500boards"])
        ja = S.unit_at(lad[mpn], 500 * qa) if qa else 0.0
        jb = S.unit_at(lad[mpn], 500 * qb) if qb else 0.0
        row = {"mpn": mpn, "qty_s44": qa, "qty_s45": qb, "card_unit_500": cu, "card_basis": st[mpn]["price_source"],
               "card_delta": round(cu * (qb - qa), 4), "jlc_unit_500_s44": ja, "jlc_unit_500_s45": jb,
               "jlc_delta": round(jb * qb - ja * qa, 4)}
        tot["card"] += row["card_delta"]
        tot["jlc"] += row["jlc_delta"]
        rows.append(row)
    out = {"rows": rows, "card_delta_usd_per_board": round(tot["card"], 4), "jlc_delta_usd_per_board": round(tot["jlc"], 4)}
    (HERE.parent / "results/cost-s44-s45.json").write_text(json.dumps(out, indent=1) + "\n")
    L = ["# Stage 45 parts cost at 500 boards, per changed line (generated by scripts/cost45.py)\n",
         "| MPN | qty s44 -> s45 | card $/unit (basis) | card delta | JLC $/unit s44 / s45 | JLC delta |",
         "|---|---|---|---:|---|---:|"]
    for r in rows:
        L.append(f"| {r['mpn']} | {r['qty_s44']} -> {r['qty_s45']} | {r['card_unit_500']} ({r['card_basis'][:38]}) | "
                 f"{r['card_delta']:+.4f} | {r['jlc_unit_500_s44']} / {r['jlc_unit_500_s45']} | {r['jlc_delta']:+.4f} |")
    L.append(f"| **total** | | | **{out['card_delta_usd_per_board']:+.4f}** | | **{out['jlc_delta_usd_per_board']:+.4f}** |")
    (HERE.parent / "results/cost-s44-s45.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


main()
