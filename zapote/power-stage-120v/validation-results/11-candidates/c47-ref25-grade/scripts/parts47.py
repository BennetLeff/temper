#!/usr/bin/env python3
"""Stage 47 part record from the cached JLC public records (scripts/jlc-raw, read 2026-10-15 by scripts/jlc.py; untrusted,
named fields only). Offline.

    python3 -I scripts/parts47.py   -> results/parts-s47.md

Need: 1 per board x 500 boards = 500 for U5 (550 with ~10 % attrition for the owner pre-order).
The JLC 'Operating Temperature' attribute is quoted to show the listing error: TI SNOS455H 5.3 p.5 and the orderable
addendum p.25 give -40..125 C for every LM4050AEM3 (E = extended range).
"""
import sys as _s; _s.dont_write_bytecode = True
import sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.argv = [sys.argv[0], "--offline"]
sys.path.insert(0, str(HERE))
import jlc  # noqa: E402

ROWS = [  # role, need, MPN, LCSC
    ("REF25 as built (s46)", 500, "LM4040A25IDBZR", "C9421"),
    ("REF25 stage 47 (chosen)", 500, "LM4050AEM3-2.5/NOPB", "C2156518"),
    ("REF25 same die, AEC-Q100 Q1 (alternate)", 500, "LM4050QAEM3-2.5/NOPB", "C2157745"),
    ("REF25 same die, Q1, large reel (alternate)", 500, "LM4050QAEM3X2.5/NOPB", "C2157326"),
    ("REF25 TL4050A25Q (electrically equal, alternate)", 500, "TL4050A25QDBZR", "C2156942"),
]


def attr(det, name):
    return next((a.get("attribute_value_name") for a in det.get("attributes") or [] if a.get("attribute_name_en") == name), "-")


def main():
    L = ["# Stage 47 U5 parts at JLC (generated by scripts/parts47.py from scripts/jlc-raw; do not edit)\n",
         "| Role | Need | MPN | LCSC | JLC MPN / brand | Library | Stock | Stock >= need | $ at need | JLC 'Operating Temperature' | Fetched (UTC) |",
         "|---|---:|---|---|---|---|---:|---|---:|---|---|"]
    tot = 0
    for role, need, mpn, code in ROWS:
        det = jlc.detail(code)
        stock = det.get("stockCount") or 0
        if mpn.startswith("LM4050"):
            tot += stock
        L.append(f"| {role} | {need:,} | {mpn} | {code} | {det.get('componentModelEn', '-')} / {det.get('componentBrandEn', '-')} | "
                 f"{det.get('componentLibraryType', '-')} | {stock:,} | {'yes' if stock >= need else '**no**'} | "
                 f"{jlc.price_at(det, need)} | {attr(det, 'Operating Temperature')} | {jlc.fetched(code) or '-'} |")
    L.append(f"\nLM4050(Q)AEM3-2.5 at JLC in total: {tot:,} against 500 (550 with attrition): the lot is an owner pre-order, "
             "consigned. TI SNOS455H 5.3 p.5 and addendum p.25: LM4050AEM3-2.5/NOPB -40 to 125 C; the JLC attribute above "
             "for C2156518 is a listing error.")
    out = HERE.parent / "results/parts-s47.md"
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
