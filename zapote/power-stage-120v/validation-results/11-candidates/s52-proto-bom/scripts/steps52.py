#!/usr/bin/env python3
"""Stage 52: the commissioning-ladder steps of the fitted TDK B32643H8104J000 bank on this board's own pads.

    python3 -I validation-results/11-candidates/s52-proto-bom/scripts/steps52.py BUILD/b3-bank-air
        -> s52-proto-bom/results/steps-s52.json, steps-s52.md

The chain's producer (bank28-air/scripts/bank_air_metric.py, stage-52 B32643H rows: the p.19 curve and the vendor's own
F_T(T_A) self-heating rule) is imported and re-run with the tank current set to each ladder step, on the s52 jetmix pads
(BUILD/b3-bank-air, the same runs the chain's bank_air value uses). Per step: the vendor ratio at 85 C (I_part / I35,
rule <= 0.85, DECISIONS 37) and the strict bank_air gate (<= 1.00, and T_op <= Top,max). The highest step that passes both
is the bank's strict ladder cap. Same method as c51-bank-source/scripts/b32643h.py's `steps` (that one on the s49 pads,
with a gap-credit column this producer does not have). Control: the 28 A step must equal the chain's
bank_air_metric.json value for B32643H8104J000.
"""
import sys as _s; _s.dont_write_bytecode = True
import importlib.util
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
PS = HERE.parents[3]
OUT = HERE.parent / "results"
MPN = "B32643H8104J000"
STEPS = (18.0, 20.0, 22.0, 24.0, 26.0, 28.0)
spec = importlib.util.spec_from_file_location("bam", PS / "validation-results/11-candidates/bank28-air/scripts/bank_air_metric.py")
bam = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bam)


def main():
    runs = Path(_s.argv[1])
    rows = []
    for i in STEPS:
        bam.I_TANK = i
        r = bam.metric(PS, runs, MPN)
        rows.append({"I_tank_A": i, "vendor_85C": r["ratio_35k_vendor_curve"], "vendor_40k": r["ratio_40k_vendor_curve"],
                     "gate_strict": r["bank_air_ratio_28A_35k"], "T_op_max_C": r["T_op_max_C"],
                     "worst": {k: r["worst"][k] for k in ("point", "position", "g_board_bound", "T_A_C", "dT_col_K", "dT_allowed_K")},
                     "strict_ok": r["bank_air_ratio_28A_35k"] <= 1.0 and r["ratio_35k_vendor_curve"] <= 0.85
                                  and r["T_op_max_C"] <= r["Top_max_C"],
                     "board_sha256_of_pad_runs": r["board_sha256_of_pad_runs"]})
    bam.I_TANK = 28.0
    chain = json.loads((PS / "validation-results/11-candidates/bank28-air/results/bank_air_metric.json").read_text())["by_mpn"][MPN]
    fails = []
    if abs(chain["bank_air_ratio_28A_35k"] - rows[-1]["gate_strict"]) > 1e-9:
        fails.append(f"28 A step {rows[-1]['gate_strict']} vs chain {chain['bank_air_ratio_28A_35k']}")
    if chain["board_sha256_of_pad_runs"] != rows[-1]["board_sha256_of_pad_runs"]:
        fails.append("pad runs are not the chain's board")
    i85 = round(0.85 * bam.part_data(PS, MPN)[1]["I35"] / bam.share(5, 0.05), 2)
    out = {"mpn": MPN, "board_sha256_of_pad_runs": rows[-1]["board_sha256_of_pad_runs"], "steps": rows,
           "highest_step_strict_A": max([x["I_tank_A"] for x in rows if x["strict_ok"]], default=None),
           "tank_A_at_vendor_0.85": i85, "control_failed": fails}
    OUT.mkdir(exist_ok=True)
    (OUT / "steps-s52.json").write_text(json.dumps(out, indent=1) + "\n")
    L = [f"# Ladder steps, stage 52 (generated by s52-proto-bom/scripts/steps52.py; do not edit)\n",
         f"{MPN} on board {out['board_sha256_of_pad_runs'][:8]} (jetmix pads). Vendor ratio <= 0.85 at 85 C reached at "
         f"{i85} A of tank current.\n", "| Tank A | Vendor 35 kHz | Vendor 40 kHz | Gate strict | T_op max (C) | Strict OK |",
         "|---:|---:|---:|---:|---:|---|"]
    for x in rows:
        L.append(f"| {x['I_tank_A']:g} | {x['vendor_85C']} | {x['vendor_40k']} | {x['gate_strict']} | {x['T_op_max_C']} | "
                 f"{'yes' if x['strict_ok'] else 'no'} |")
    L += ["", f"Highest strict step: {out['highest_step_strict_A']} A. Controls: {fails or 'pass'}"]
    (OUT / "steps-s52.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))
    _s.exit(1 if fails else 0)


if __name__ == "__main__":
    main()
