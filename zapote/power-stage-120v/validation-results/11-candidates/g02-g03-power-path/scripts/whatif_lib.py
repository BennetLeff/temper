#!/usr/bin/env python3
"""What-if engine on the stage-19c copper dump: edit primitives, re-pour a plane window under the
board's own clearance rules, and re-run the F1 fusing-neck calculator on the edited copper.

Clearance rules are read from native-21/section.kicad_dru (rule 1: 3.2 mm between differing HOT potential
groups; 0.2 mm inside a group, which clearances.py confirms against the dump) and the 8.0 mm SELV/PE barrier
(rules 4-5) is applied to any net not on the HOT list.  The neck calculator is the *unmodified*
02-protection-timing/shoot-through-f1/f1_containment.py::copper_necks, imported by path.
"""
import gzip
import importlib.util
import json
import os
import re
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from shapely.geometry import LineString, MultiPolygon, Point, Polygon, box
from shapely.ops import unary_union

from pp_common import F1C, PS, fix, geom, load_copper

DRU = PS / "native-21/section.kicad_dru"


def _parse_groups():
    t = DRU.read_text()
    rule = re.split(r"\n(?=\(rule )", t)[1]
    c = re.search(r'\(condition "([^"]*)"', rule).group(1)
    first = c[:c.find(") && (")]
    hot = set(re.findall(r"A\.NetName == '([^']+)'", first))
    clauses = re.findall(r"\(\((A\.NetName[^&]*?)\) && \((B\.NetName.*?)\)\)(?= \|\| \(\(|\)$|$)", c)
    group = {}
    for gi, (a, _b) in enumerate(clauses):
        for n in re.findall(r"A\.NetName == '([^']+)'", a):
            group[n] = gi
    return hot, group


HOT, GROUP = _parse_groups()


def clr(a, b):
    """Required copper-to-copper clearance (mm) between nets a and b."""
    if a == b:
        return 0.0
    ha, hb = a in HOT, b in HOT
    if ha and hb:
        return 0.2 if GROUP.get(a, -1) == GROUP.get(b, -2) and a in GROUP else 3.2
    if ha != hb and (a or b):
        # one side not on the HOT list: SELV/PE barrier 8 mm, but unnamed/NC nets are treated as 0.2
        other = b if ha else a
        return 8.0 if other else 0.2
    return 0.2


def polys(g):
    if g.is_empty:
        return []
    return [g] if isinstance(g, Polygon) else [x for x in g.geoms if isinstance(x, Polygon) and not x.is_empty]


def zone_prim(net, layer, poly):
    return {"kind": "zone", "net": net, "layer": layer,
            "shell": [list(p) for p in poly.exterior.coords[:-1]],
            "holes": [[list(p) for p in r.coords[:-1]] for r in poly.interiors]}


def clone(prims):
    return [dict(p) for p in prims]


def repour(prims, net, layer, window, outline=None, min_area=0.5, edge_clear=0.5, ignore_nets=()):
    """Replace net's zone copper on `layer` inside `window` (x0,y0,x1,y1) with a fresh pour:
    window minus every other-net primitive on that layer buffered by its clearance. Same-net primitives
    (pads/vias/tracks) are kept. Returns a new primitive list."""
    W = box(*window)
    out = []
    for p in prims:
        if p["kind"] == "zone" and p["net"] == net and p["layer"] == layer:
            g = fix(Polygon(p["shell"], p.get("holes") or []))
            rest = g.difference(W)
            for q in polys(rest):
                if q.area >= min_area:
                    out.append(zone_prim(net, layer, q))
        else:
            out.append(p)
    cut = []
    for p in prims:
        if p["layer"] != layer or p["net"] == net or p["net"] in ignore_nets:
            continue
        if p["kind"] == "zone":
            # other zones are regenerated by the real pour; treat their *footprint* only as a clearance
            # obstacle when it is not itself a plane being replaced (kept simple: include)
            pass
        g = geom(p, via_ring=False) if p["kind"] != "zone" else fix(Polygon(p["shell"], p.get("holes") or []))
        if not g.intersects(W.buffer(8.5)):
            continue
        cut.append(g.buffer(clr(net, p["net"]) + 1e-3))
    fill = W.difference(unary_union(cut)) if cut else W
    if outline is not None:
        fill = fill.intersection(outline.buffer(-edge_clear))
    # drill clearance: other nets' holes (vias/PTH) are drilled through every layer
    for q in polys(fill.buffer(0)):
        if q.area >= min_area:
            out.append(zone_prim(net, layer, q))
    return out


def outline_poly(d):
    o = d["outline"]
    return Polygon(o["shell"], o.get("holes") or [])


def rename_net(prims, old, new):
    return [dict(p, net=new) if p["net"] == old else p for p in prims]


def drop(prims, pred):
    return [p for p in prims if not pred(p)]


_F1C = None


def f1c():
    global _F1C
    if _F1C is None:
        spec = importlib.util.spec_from_file_location("f1_containment", str(F1C))
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
        _F1C = m
    return _F1C


def necks(d, prims, segments):
    """Run the unmodified F1 neck calculator on an edited copper list. segments: [(net, termA, termB, label)]."""
    m = f1c()
    d2 = dict(d)
    d2["primitives"] = prims
    with tempfile.TemporaryDirectory() as td:
        path = os.path.join(td, "edited.json.gz")
        with gzip.open(path, "wt") as fh:
            json.dump(d2, fh)
        save = m.SEGMENTS
        m.SEGMENTS = segments
        try:
            sha, out = m.copper_necks("edited", path, None)
        finally:
            m.SEGMENTS = save
    return out


# ------------------------------------------------------------------ editing helpers (added)
def clip_zone(prims, net, layer, window):
    """Remove net's zone copper inside window (no refill)."""
    W = box(*window)
    out = []
    for p in prims:
        if p["kind"] == "zone" and p["net"] == net and p["layer"] == layer:
            g = fix(Polygon(p["shell"], p.get("holes") or [])).difference(W)
            for q in polys(g):
                if q.area >= 0.05:
                    out.append(zone_prim(net, layer, q))
        else:
            out.append(p)
    return out


def make_via(net, xy, dia=0.6, drill=0.3):
    return [{"kind": "via", "net": net, "layer": L, "centre": list(xy), "diameter_mm": dia, "drill_mm": drill}
            for L in ("F.Cu", "In1.Cu", "In2.Cu", "B.Cu")]


def make_track(net, layer, pts, width):
    return [{"kind": "track", "net": net, "layer": layer, "start": list(a), "end": list(b), "width_mm": width}
            for a, b in zip(pts[:-1], pts[1:])]


def check_clear(prims, new_items, tol=0.005, zones=True):
    """DRC-style check of new tracks/vias against all other-net copper on each layer.
    Returns list of (layer, new_net, other_net, gap_mm, required_mm) violations."""
    bad = []
    by_layer = {}
    for p in prims:
        by_layer.setdefault(p["layer"], []).append(p)
    for n in new_items:
        gn = geom(n, via_ring=False)
        for q in by_layer.get(n["layer"], []):
            if q["net"] == n["net"] or (q["kind"] == "zone" and not zones):
                continue
            gq = geom(q, via_ring=False) if q["kind"] != "zone" else fix(Polygon(q["shell"], q.get("holes") or []))
            if gq.distance(gn) + tol < clr(n["net"], q["net"]):
                bad.append((n["layer"], n["net"], q["net"], round(gq.distance(gn), 3), clr(n["net"], q["net"])))
    return bad


class ClearIndex:
    """Spatial index of copper per layer for fast via-site checks."""

    def __init__(self, prims, window=None, zones=True):
        from shapely.strtree import STRtree
        self.by = {}
        for L in ("F.Cu", "In1.Cu", "In2.Cu", "B.Cu"):
            items = []
            for p in prims:
                if p["layer"] != L or (p["kind"] == "zone" and not zones):
                    continue
                g = geom(p, via_ring=False) if p["kind"] != "zone" else fix(Polygon(p["shell"], p.get("holes") or []))
                if window is not None and not g.intersects(box(*window)):
                    continue
                items.append((p["net"], g))
            self.by[L] = (items, STRtree([g for _, g in items]) if items else None)

    def via_ok(self, net, xy, dia=0.6, tol=0.005, extra_geoms=()):
        c = Point(xy).buffer(dia / 2)
        for L, (items, tree) in self.by.items():
            if tree is None:
                continue
            for i in tree.query(c.buffer(8.5)):
                n, g = items[int(i)]
                if n == net:
                    continue
                if g.distance(c) + tol < clr(net, n):
                    return False
        return True
