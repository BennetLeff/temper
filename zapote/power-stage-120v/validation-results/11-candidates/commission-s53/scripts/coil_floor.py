#!/usr/bin/env python3
"""The coil study's R1 design against both versions of the tank-coil spec's acceptance rows.

Reads only committed model output of output/temper-coil-r1 (pans.json: loaded L per layout, pan, µ and
diameter at 40 kHz; trim_heating.json: free-air and cast-iron / 430 loaded L for each tune state). It
re-solves nothing. The spec limits are constants below, each cited to the version it comes from:

* COMMITTED: docs/hardware/TANK_COIL_SPECIFICATION.md as committed (852e9fa8d .. 3ae26dfef):
  row 1 88 µH ±10 %, row 3 L_loaded >= 53.43 µH, row 3b L_loaded >= 0.60 x L_unloaded. Its floor is
  derived from a 300 nF ±10 % tank and PLL_MIN_FREQ_HZ 44 kHz (the spec's own derivation, §2).
* WORKING_TREE: the main checkout's uncommitted version (sha256 637a7603...; the version the coil study
  designed to): alternate B 80 µH ±10 %, row 3 L_loaded >= 41.5 µH on the reference pan, row 3b
  0.47-0.77 for alternate B.

The spec's row 3 is judged on its §2 reference pan (a ferromagnetic pan, the coil study takes cast iron
as the reference class). Every other pan class is reported for information: it is not what row 3 binds.

Run: python3 -I scripts/coil_floor.py  -> results/coil-floor.json and results/coil-floor.md
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
REPO = HERE.parents[4]
COIL = REPO / "output/temper-coil-r1/model/results"

SPECS = {
    "committed (88 µH, 53.43 µH floor)": {"l_free": (79.2, 96.8), "floor": 53.43, "ratio": (0.60, None)},
    "working tree (alt B 80 µH, 41.5 µH floor)": {"l_free": (72.0, 88.0), "floor": 41.5, "ratio": (0.47, 0.77)},
}
REF_PAN = ("cast_iron", "nom")


def main() -> int:
    pans = json.loads((COIL / "pans.json").read_text())["rows"]
    trim = json.loads((COIL / "trim_heating.json").read_text())["rows"]
    l_free = {r["state"]: r["L_free_uH"] for r in trim}
    r1 = [r for r in pans if r["layout"] == "R1" and r["f_kHz"] == 40.0 and r["pan"] != "aluminium"]
    out = {"source": {p: str((COIL / p).relative_to(REPO)) for p in ("pans.json", "trim_heating.json")},
           "R1_L_free_uH": l_free["R1"], "specs": {}}
    md = ["# R1 against the two spec versions (generated by scripts/coil_floor.py; do not edit)", ""]
    for name, s in SPECS.items():
        lo, hi = s["ratio"]
        rows = []
        for r in r1:
            L = r["L_uH"]
            ratio = L / l_free["R1"]
            rows.append({"pan": r["pan"], "mu": r["mu_tag"], "d_mm": r["pan_d_mm"], "L_loaded_uH": round(L, 2),
                         "row3_pass": L >= s["floor"], "ratio": round(ratio, 3),
                         "row3b_pass": ratio >= lo and (hi is None or ratio <= hi),
                         "reference": (r["pan"], r["mu_tag"]) == REF_PAN})
        states = []
        for t in trim:
            if t["pan"] == "cast_iron":
                states.append({"state": t["state"], "L_free_uH": round(t["L_free_uH"], 2),
                               "row1_pass": s["l_free"][0] <= t["L_free_uH"] <= s["l_free"][1],
                               "L_cast_iron_uH": round(t["L_loaded_uH"], 2),
                               "row3_pass": t["L_loaded_uH"] >= s["floor"]})
        out["specs"][name] = {"limits": s, "R1_pans_40kHz": rows, "tune_states_cast_iron_240": states}
        md += [f"## {name}", "",
               f"Row 1 window {s['l_free'][0]}–{s['l_free'][1]} µH; row 3 floor {s['floor']} µH; row 3b ratio "
               f"{lo}{'–' + str(hi) if hi else ' minimum'} (L_loaded / R1 free-air {l_free['R1']:.2f} µH).", "",
               "| Pan | µ | Ø mm | L loaded µH | row 3 | ratio | row 3b |", "|---|---|---|---|---|---|---|"]
        for x in rows:
            tag = " (reference)" if x["reference"] else ""
            md.append(f"| {x['pan']}{tag} | {x['mu']} | {x['d_mm']:.0f} | {x['L_loaded_uH']:.2f} | "
                      f"{'pass' if x['row3_pass'] else 'FAIL'} | {x['ratio']:.3f} | {'pass' if x['row3b_pass'] else 'FAIL'} |")
        npass = sum(x["row3_pass"] for x in rows)
        md += ["", f"Row 3 passes on {npass} of {len(rows)} ferrous pan cases.", "",
               "| Tune state | L free µH | row 1 | cast iron Ø240 µ nom, L loaded µH | row 3 |", "|---|---|---|---|---|"]
        for x in states:
            md.append(f"| {x['state']} | {x['L_free_uH']:.2f} | {'pass' if x['row1_pass'] else 'FAIL'} | "
                      f"{x['L_cast_iron_uH']:.2f} | {'pass' if x['row3_pass'] else 'FAIL'} |")
        md.append("")
    (HERE / "results").mkdir(exist_ok=True)
    (HERE / "results/coil-floor.json").write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n")
    (HERE / "results/coil-floor.md").write_text("\n".join(md))
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    sys.exit(main())
