#!/usr/bin/env python3
"""Stage 49: the bank's fault voltages against the B32643B8104J000 rating, with the s49 OCP band.

    python3 -I scripts/bank_voltage49.py   -> results/bank-voltage-s49.json, results/bank-voltage-s49.md

Run after scripts/bands49.py (results/bands-s49.json, this board's solve). Inputs:
  * TDK B3264*B data sheet (June 2026, sha256 ab9fdca0...4a58ab77; PDF page = footer page): VR 2000 V DC, VRMS 500 V AC
    (p.11 ordering table header, B32643B8104+***); category voltage VC = VR (Top <= 85 C), VR x (165 - Top) / 80
    (85 < Top <= 125 C), test voltage terminal to terminal 1.6 VR for 2 s (p.12); dV/dt 3800 V/us at 22.5 mm,
    2000 V / 500 V AC (p.13); Top,max 125 C case (p.2, p.12).
  * F3, the CT-failed third-fault case (DECISIONS 13 / 37): 1,683 V with the J bank (DECISIONS.md:853), the
    bank-ov-double-fault study's quasi-steady governing case ("just under the upper band edge, no f floor") at the
    shunt band top it was run at, 118.74 A (02-protection-timing/bank-ov-double-fault/results.json: 1,702.4 V with the
    K bank; the J bank's C_min lowers it to 1,683 V). That case is I_top x X_C at the worst drive frequency, linear in
    I_top, so the s49 value is 1,683 V x top / 118.74 A at each band reading.
  * The CT-failed double-fault bank rule of stage15-28A/fault_check.py (as s23_bands.py): Z0,max x OCP top, Z0,max =
    sqrt(L_max / C_min) = 12.75 ohm, against the 1,600 V of the fitted bank (the old rule) and the new 2,000 V.
  * dV/dt: the study's clamp sizing at the largest turn-off current (results.json clamp_sizing, 345.4 V/us).
Acceptance (DECISIONS 37 derating rule): normal peak <= 0.8 VR; F3 <= 0.85 VR at every reading (audit.rs S49_BANK_VR);
Z0,max x top <= VR; dV/dt <= the p.13 limit.
"""
import sys as _s; _s.dont_write_bytecode = True
import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
PS = HERE.parents[3]
VR_DIR = PS / "validation-results"
OUT = HERE.parent / "results"
VR, VRMS, DVDT, TOP_MAX = 2000.0, 500.0, 3800.0, 125.0
VR_OLD = 1600.0
F3_J, F3_TOP = 1683.0, 118.74
L_MAX, C_MIN = 66.5e-6 * 1.1, 0.50e-6 * 0.9
Z0_MAX = math.sqrt(L_MAX / C_MIN)


def vc(top):
    return VR if top <= 85.0 else VR * (165.0 - top) / 80.0


def main():
    bands = json.loads((HERE.parent / "results/bands-s49.json").read_text())
    df = json.loads((VR_DIR / "02-protection-timing/bank-ov-double-fault/results.json").read_text())
    assert df["controls"]["shunt_band_R34_12k6_A"] == [66.3, F3_TOP] and df["governing_Vc_pk_V"] == 1702.4, df["controls"]
    assert abs(df["controls"]["z0_max_ohm"] - round(Z0_MAX, 2)) < 0.01, (df["controls"]["z0_max_ohm"], Z0_MAX)
    rows = []
    for r in bands["tlv3201_readings"]:
        top = r["ocp_top_A"]
        f3 = F3_J * top / F3_TOP
        z = Z0_MAX * top
        rows.append({"network": r["network"], "reading": r["reading"], "hot5": r["hot5"], "ocp_top_A": top,
                     "F3_V": round(f3, 1), "F3_over_VR": round(f3 / VR, 4), "Z0max_x_top_V": round(z, 1),
                     "Z0max_margin_vs_1600_V": round(VR_OLD - z, 1), "Z0max_margin_vs_2000_V": round(VR - z, 1)})
    # R4 (spec-literal 5.4 mV) is the S23 record's unguaranteed reading; the gate reading is R0, R1 the review's
    gated = [x for x in rows if x["reading"] in ("R0", "R1")]
    worst = max(gated, key=lambda x: x["ocp_top_A"])
    worst_all = max(rows, key=lambda x: x["ocp_top_A"])
    dvdt = df["clamp_sizing"]["dVdt_at_I_off_V_per_us"]
    out = {"board_sha256": bands["board_sha256"], "rating": {"VR_V": VR, "VRMS_V": VRMS, "dVdt_V_per_us": DVDT,
           "Top_max_C": TOP_MAX, "VC_at_110C_V": vc(110.0), "VC_at_125C_V": vc(125.0), "proof_1p6VR_2s_V": 1.6 * VR,
           "source": "TDK B3264*B June 2026: p.11 (VR, VRMS), p.12 (VC derating, 1.6 VR test, Top,max), p.13 (dV/dt 22.5 mm)"},
           "z0_max_ohm": round(Z0_MAX, 3), "F3_basis": {"F3_J_V": F3_J, "at_top_A": F3_TOP, "V_per_A": round(F3_J / F3_TOP, 3)},
           "rows": rows, "worst_R0_R1": worst, "worst_any_reading": worst_all,
           "F3_ratio_at_committed_1683_V": round(F3_J / VR, 4),
           "dVdt": {"V_per_us": dvdt, "limit": DVDT, "ratio": round(dvdt / DVDT, 4)},
           "pass": {"F3 <= 0.85 VR (R0/R1)": worst["F3_V"] <= 0.85 * VR, "F3 <= VR (any reading)": worst_all["F3_V"] <= VR,
                    "Z0max x top <= VR (any reading)": worst_all["Z0max_x_top_V"] <= VR,
                    "dV/dt": dvdt <= DVDT}}
    OUT.mkdir(exist_ok=True)
    (OUT / "bank-voltage-s49.json").write_text(json.dumps(out, indent=1) + "\n")
    L = ["# Bank fault voltages, stage 49 (generated by scripts/bank_voltage49.py; do not edit)\n",
         f"Board {bands['board_sha256'][:8]}. B32643B8104J000: VR {VR:g} V, VC {vc(110.0):g} V at 110 C / {vc(125.0):g} V at "
         f"125 C, dV/dt {DVDT:g} V/us. F3 = {F3_J:g} V x top / {F3_TOP} A; Z0,max {Z0_MAX:.3f} ohm.\n",
         "| Network | Reading | HOT5 | OCP top (A) | F3 (V) | F3 / VR | Z0max x top (V) | vs 1600 V | vs 2000 V |",
         "|---|---|---|---:|---:|---:|---:|---:|---:|"]
    for x in rows:
        L.append(f"| {x['network']} | {x['reading']} | {x['hot5']} | {x['ocp_top_A']} | {x['F3_V']} | {x['F3_over_VR']} | "
                 f"{x['Z0max_x_top_V']} | {x['Z0max_margin_vs_1600_V']:+.1f} | {x['Z0max_margin_vs_2000_V']:+.1f} |")
    L += ["", f"Worst R0/R1: {worst['network']} {worst['reading']} {worst['hot5']}: F3 {worst['F3_V']} V "
              f"({worst['F3_over_VR']} of VR). dV/dt {dvdt} V/us = {out['dVdt']['ratio']} of {DVDT:g}. Pass: {out['pass']}"]
    (OUT / "bank-voltage-s49.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))
    _s.exit(0 if all(out["pass"].values()) else 1)


if __name__ == "__main__":
    main()
