#!/usr/bin/env python3
"""Build complete-envelope tables; numerical failures cannot become qualified margins."""

import itertools
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESERVE_DB = 1.0  # Planning reserve, not a mathematical truncation-error bound.


def load(name):
    return json.loads((HERE / name).read_text())


def qualified(comparisons, label):
    """Require both comparisons and every expected scenario/terminal in each."""
    scenarios = set(load("filter-scenarios.json"))
    expected = {(scenario, terminal) for scenario in scenarios for terminal in ("l_pe", "n_pe")}
    for suffix in ("-step", "-cycle"):
        rows = [r for r in comparisons if r["comparison"] == label + suffix]
        if {(r["scenario"], r["terminal"]) for r in rows} != expected:
            return False
        if len(rows) != len(expected) or not all(r["passes_0p2dB_target"] for r in rows):
            return False
    return True


def complete_receiver_coverage(rows):
    """A missing scenario/mode must not hide the worst receiver margin."""
    expected = {(scenario, mode) for scenario in load("filter-scenarios.json") for mode in ("L", "N", "terminal", "DM", "CM")}
    return len(rows) == len(expected) and {(r["scenario"], r["mode"]) for r in rows} == expected


def write_attempts():
    """Account for every scheduled point, including failures without spectra."""
    text = [
        "# Simulation attempts", "",
        "Generated by `summarize.py`. Complete means the endpoint and cycle-RMS check passed, not timestep qualification. Indeterminate attempts supply no margin. Elapsed times and timeout limits use the runner’s monotonic clock; they need not match calendar elapsed time across host suspension.", "",
        "| Campaign | Case | Outcome | Runner seconds | Timeout limit | Detail |",
        "| --- | --- | --- | ---: | ---: | --- |",
    ]
    rows = []
    for campaign in ("envelope-0.5", "envelope-0.25", "envelope-0.125", "anchor-0.0625", "targeted-refinement", "additional-refinement", "fine-refinement", "recovery-refinement", "weak-refinement", "retry-refinement", "last-refinement", "closing-refinement", "terminal-refinement", "final-light-refinement", "diagnostic", "tight-diagnostic", "trap-diagnostic", "klu-diagnostic", "bypass-diagnostic"):
        for item in load(campaign + ".json"):
            label = item["label"]
            path = HERE / "periodic-runs" / label / "result.json"
            result = json.loads(path.read_text()) if path.exists() else {}
            status = result.get("status", "pending")
            if result.get("timeout"):
                detail = "runner timeout; indeterminate"
            elif status == "indeterminate":
                detail = result.get("analysis_error", "simulator abort/failure; see run.log")
                log = path.with_name("run.log")
                if log.exists():
                    diagnostic = re.search(r"doAnalyses:[^\r\n]+", log.read_text(errors="replace"))
                    if diagnostic:
                        detail = diagnostic.group(0).replace("|", "/")
            else:
                detail = ""
            row = {"campaign": campaign, "case": label, "outcome": status, "elapsed_seconds": result.get("elapsed_seconds"), "timeout_seconds": item["config"].get("timeout", 1800), "detail": detail}
            rows.append(row)
            seconds = "—" if row["elapsed_seconds"] is None else f"{row['elapsed_seconds']:.1f}"
            text.append(f"| {campaign} | `{label}` | {status} | {seconds} | {row['timeout_seconds']} | {detail} |")
    (HERE / "attempts.json").write_text(json.dumps(rows, indent=2) + "\n")
    (HERE / "ATTEMPTS.md").write_text("\n".join(text) + "\n")


def main():
    write_attempts()
    pending = any(row["outcome"] == "pending" for row in load("attempts.json"))
    margins = load("qualified-margin-results.json")
    comparisons = load("convergence-summary.json")
    captures = [
        load(str(p.relative_to(HERE)))
        for p in sorted((HERE / "periodic-runs").glob("envelope-*/result.json"))
    ]
    rows = []
    for bus, freq, resistance, esl in itertools.product(
        (170, 198), (35000, 60000), (2, 100), (1.06, 10)
    ):
        candidates = [
            r
            for r in captures
            if all(
                r["identity"]["config"][key] == value
                for key, value in {
                    "bus": bus,
                    "freq": freq,
                    "resistance": resistance,
                    "esl": esl,
                }.items()
            )
        ]
        completed = [r for r in candidates if r["status"] == "complete"]
        row = {
            "bus_V": bus,
            "frequency_Hz": freq,
            "R_ohm": resistance,
            "ESL_nH": esl,
            "qualified": False,
        }
        if not completed:
            row["status"] = "indeterminate"
            rows.append(row)
            continue
        finest = min(completed, key=lambda r: (r["identity"]["config"]["step"], -r["identity"]["config"]["cycles"]))
        label = finest["label"]
        selected = [r for r in margins if r["case"] == label]
        if not selected or not complete_receiver_coverage(selected):
            row["status"] = (
                "complete; receiver analysis pending" if not selected
                else "complete; receiver coverage incomplete"
            )
            rows.append(row)
            continue
        row.update(
            case=label,
            step_ns=finest["identity"]["config"]["step"],
            cycles=finest["identity"]["config"]["cycles"],
            input_power_estimate_W=finest["input_power_estimate_W"],
            qualified=qualified(comparisons, label),
        )
        row["status"] = (
            "numerically qualified" if row["qualified"] else (
                "complete; refinement pending/failed" if pending else "complete; numerical checks failed"
            )
        )
        reasons = []
        for kind in ("step", "cycle"):
            checked = [r for r in comparisons if r["comparison"] == label + "-" + kind]
            if not checked:
                reasons.append(kind + " comparison missing")
                continue
            if not all(r["passes_significant_line_target"] for r in checked):
                reasons.append(kind + " significant lines")
            if not all(r["passes_weak_line_target"] for r in checked):
                reasons.append(kind + " weak lines")
        if not row["qualified"] and not reasons:
            reasons.append("comparison coverage incomplete")
        row["failed_checks"] = reasons
        for design in ("original", "proposed"):
            subset = [
                r
                for r in selected
                if r["scenario"].startswith("original") == (design == "original")
            ]
            row[design] = {
                mode: min((r for r in subset if r["mode"] == mode), key=lambda r: r["AV_dB"])
                for mode in ("terminal", "DM", "CM")
            }
        row["proposed_margin_after_reserve_dB"] = row["proposed"]["terminal"]["AV_dB"] - RESERVE_DB
        row["meets_6dB"] = row["qualified"] and row["proposed_margin_after_reserve_dB"] >= 6
        steps = [r for r in comparisons if r["comparison"] == label + "-step"]
        row["maximum_step_change_dB"] = max(
            (r["maximum_significant_line_change_dB"] for r in steps), default=None
        )
        rows.append(row)
    accepted = [r for r in rows if r["qualified"]]
    accepted_minimum = min((r["proposed"]["terminal"]["AV_dB"] for r in accepted), default=None)
    summary = {
        "numerical_reserve_dB": RESERVE_DB,
        "expected_cases": 16,
        "attempts_pending": pending,
        "qualified_minimum_proposed_AV_dB": accepted_minimum,
        "qualified_minimum_after_reserve_dB": accepted_minimum - RESERVE_DB if accepted_minimum is not None else None,
        "all_qualified_cases_meet_6dB": bool(accepted) and all(r["meets_6dB"] for r in accepted),
        "numerically_qualified_cases": sum(r["qualified"] for r in rows),
        "all_cases_meet_6dB": all(r.get("meets_6dB", False) for r in rows),
        "cases": rows,
    }
    (HERE / "envelope-summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    text = [
        "# Complete-envelope evidence",
        "",
        "Generated by `summarize.py`. Margins below are provisional unless the numerical status passes. QP/AV are CW-equivalent estimates; negative margin exceeds the limit. Original columns take the worse of nominal/combined sensitivity. Proposed columns take the worse of all declared added-stage sensitivities. Different mode minima may occur at different frequencies.",
        "",
    ]
    for design in ("original", "proposed"):
        text += [
            f"## {design.capitalize()} receiver",
            "",
            "| Bus V | kHz | R Ω | ESL nH | Step ns | Terminal AV / QP dB | DM AV / QP dB | CM AV / QP dB | Worst terminal MHz |",
            "| ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
        ]
        for row in rows:
            prefix = f"| {row['bus_V']} | {row['frequency_Hz'] / 1000:g} | {row['R_ohm']} | {row['ESL_nH']} |"
            if design not in row:
                text.append(prefix + " — | indeterminate | — | — | — |")
                continue
            modes = row[design]
            cells = " | ".join(
                f"{modes[mode]['AV_dB']:.2f} / {modes[mode]['QP_dB']:.2f}"
                for mode in ("terminal", "DM", "CM")
            )
            text.append(
                prefix + f" {row['step_ns']} | {cells} | {modes['terminal']['Hz'] / 1e6:g} |"
            )
        text += [""]
    text += [
        "## Numerical acceptance",
        "",
        "Significant-line checks use the 0.2 dB target. Weak-line checks require the absolute complex difference to be no more than `10**(0.2/20)-1` times the AV-minus-40-dB floor. Step and cycle checks are separate; passing the significant-line column alone does not qualify a case.",
        "",
        "| Bus V | kHz | R Ω | ESL nH | Cycles | Finest step ns | Largest significant-line step change dB | Failed checks | Status |",
        "| ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- | --- |",
    ]
    for row in rows:
        delta = row.get("maximum_step_change_dB")
        delta_text = "—" if delta is None else f"{delta:.4f}"
        text.append(
            f"| {row['bus_V']} | {row['frequency_Hz'] / 1000:g} | {row['R_ohm']} | {row['ESL_nH']} | {row.get('cycles', '—')} | {row.get('step_ns', '—')} | {delta_text} | {'; '.join(row.get('failed_checks', [])) or '—'} | {row['status']} |"
        )
    text += [
        "",
        f"Qualified {summary['numerically_qualified_cases']}/16; all cases meet ≥6 dB after the explicit {RESERVE_DB:g} dB planning reserve: **{summary['all_cases_meet_6dB']}**.",
        "",
    ]
    if accepted_minimum is not None:
        text += [f"Within the qualified subset, the minimum proposed AV margin is **{accepted_minimum:.4f} dB**, or **{accepted_minimum - RESERVE_DB:.4f} dB** after the planning reserve. Unqualified cases do not enter that acceptance claim.", ""]
    (HERE / "TABLES.md").write_text("\n".join(text))
    readme = HERE / "README.md"
    if readme.exists():
        start = "<!-- BEGIN GENERATED TABLES -->"
        stop = "<!-- END GENERATED TABLES -->"
        before, rest = readme.read_text().split(start, 1)
        _, after = rest.split(stop, 1)
        readme.write_text(before + start + "\n" + "\n".join(text[2:]) + "\n" + stop + after)
    print(
        summary["numerically_qualified_cases"],
        "/16 qualified; all meet 6 dB:",
        summary["all_cases_meet_6dB"],
    )


if __name__ == "__main__":
    main()
