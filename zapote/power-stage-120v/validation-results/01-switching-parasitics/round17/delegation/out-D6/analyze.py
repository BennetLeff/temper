#!/usr/bin/env python3
"""Build D6 report tables and fail closed on missing case coverage."""
from __future__ import annotations
import json
from pathlib import Path
import run
HERE=Path(__file__).resolve().parent
variants=list(run.VARIANTS)+['off1_c1','off1_c1_neg2','c1_neg2','c1_neg4']
rows=[json.loads(f.read_text()) for f in (HERE/'raw').glob('*/result.json')]
main=[r for r in rows if r['step_ns']==.2 and r['matrix'] in ('lin','quad')]
assert len(main)==32*len(variants),(len(main),32*len(variants))
assert {(r['matrix'],r['variant'],(r['case'],r['vbus'],r['il'],r['dir'],r['dt'])) for r in main}=={(m,v,c) for m in ('lin','quad') for v in variants for c in run.CASES}
base=[r for r in rows if r['matrix']=='v2' and r['variant']=='baseline' and r['step_ns']==.2]
assert len(base)==16
comparisons=[]
for r in base:
    tag=f'{r["case"]}_v{r["vbus"]}_i{r["il"]}_d{r["dir"]}_dt{r["dt"]}_esl10'
    old=json.loads((run.D2/'results/grid-h0-lin12-v2/cases'/f'{tag}.json').read_text())
    comparisons.append({'case':tag,'off_delta_V':r['off_V']-old['vgs_off_max'],'vds_delta_V':r['vds_V']-old['vds_pk'],
                        'zvs_agrees':r['zvs']==old['zvs']})
assert all(abs(c['off_delta_V'])<=2e-6 and abs(c['vds_delta_V'])<=2e-4 and c['zvs_agrees'] for c in comparisons)
(HERE/'baseline-comparison.json').write_text(json.dumps(comparisons,indent=2)+'\n')
summary=[]
for name in variants:
    rs=[r for r in main if r['variant']==name]
    good=[r for r in rs if not r['aborted']]
    s1=[r for r in good if r['case']=='S1' and r['dt']==348]
    paired=[]
    for r in good:
        b=next(b for b in main if b['variant']=='baseline' and all(b[k]==r[k] for k in ('matrix','case','vbus','il','dir','dt')))
        paired.append(100*(r['total_uJ']/b['total_uJ']-1))
    summary.append({'variant':name,'completed':len(good),'aborted':len(rs)-len(good),
                    'worst_off_V':max(r['off_V'] for r in good),'worst_vds_V':max(r['vds_V'] for r in good),
                    'gate_under_1p9':sum(r['off_V']<1.9 for r in good),'gate_under_3':sum(r['off_V']<3 for r in good),
                    'max_abs_gate_V':max(abs(r['meas'][k]) for r in good for k in ('vgs_ls_die_max','vgs_ls_die_min','vgs_hs_die_max','vgs_hs_die_min')),
                    'vds_pass':sum(r['vds_V']<=(585 if r['case']=='S2' else 520) for r in good),
                    'zvs_nominal':sum(r['zvs'] for r in s1),'zvs_nominal_total':len(s1),
                    'energy_delta_min_percent':min(paired),'energy_delta_max_percent':max(paired)})
(HERE/'summary.json').write_text(json.dumps(summary,indent=2)+'\n')
out=['# Per-remedy decision tables','',
     'Generated by `analyze.py`. Each entry is linear / curved matrix; each number is the worst of both directions, independently. Energies are positive die-terminal VDS·ID integrals, µJ; Eoff is the outgoing device before partner command, Eon the incoming device after it, EΣ both devices over the full event. These include capacitive/diode energy and conduction tails; they are loss proxies, not calorimetric switching loss. `abort` means no numerical verdict. ZVS counts both directions at 348 ns (two per matrix).','']
for name in variants:
    out += [f'## {name}','','| Case, bus / current, DT | Off-gate V | Die VDS V | Eoff µJ | Eon µJ | EΣ µJ | ZVS count |',
            '|---|---:|---:|---:|---:|---:|---:|']
    for s,v,il,dt in dict.fromkeys((s,v,il,dt) for s,v,il,d,dt in run.CASES):
        groups=[[r for r in main if r['variant']==name and r['matrix']==m and (r['case'],r['vbus'],r['il'],r['dt'])==(s,v,il,dt)] for m in ('lin','quad')]
        cells=[]
        for k,precision in [('off_V',3),('vds_V',2),('off_uJ',2),('on_uJ',2),('total_uJ',2)]:
            cells.append(' / '.join('abort' if any(r['aborted'] for r in g) else f'{max(r[k] for r in g):.{precision}f}' for g in groups))
        z=' / '.join('abort' if any(r['aborted'] for r in g) else f'{sum(r["zvs"] for r in g)}/2' for g in groups)
        out.append(f'| {s}, {v} V / {il} A, {dt} ns | '+' | '.join(cells)+f' | {z} |')
    out += ['']
(HERE/'TABLES.md').write_text('\n'.join(out).rstrip()+'\n')
print(json.dumps(summary,indent=2))

# Derived component costs and refinement comparison are evidence, not prose arithmetic.
cost={'discharge_branch_ohm':{str(r):1/(1/r-1/3.9) for r in (1,2)},
      'cgs_15V':[{"C_nF":c,"Q_nC":c*15,"energy_full_cycle_uJ":c*15**2/1000} for c in (1,2.2,4.7)],
      'candidate_cgs_at_17V':{'C_nF':1,'Q_nC':17,'energy_full_cycle_uJ':17**2/1000},
      'candidate_margin_gate_V':1.9-next(r['worst_off_V'] for r in summary if r['variant']=='off1_c1_neg2'),
      'candidate_margin_vds_V':520-next(r['worst_vds_V'] for r in summary if r['variant']=='off1_c1_neg2')}
(HERE/'derived-costs.json').write_text(json.dumps(cost,indent=2)+'\n')
refined=[r for r in rows if r['step_ns']==.1]
assert len(refined)==32,len(refined)
ref=[]
for r in refined:
    if r['aborted']:
        ref.append({k:r[k] for k in ('matrix','variant','case','vbus','il','dir','dt')} | {'aborted':True})
        continue
    b=next(b for b in main if all(b[k]==r[k] for k in ('matrix','variant','case','vbus','il','dir','dt')))
    ref.append({k:r[k] for k in ('matrix','variant','case','vbus','il','dir','dt')} |
               {'off_delta_V':r['off_V']-b['off_V'],'vds_delta_V':r['vds_V']-b['vds_V'],
                'energy_delta_percent':100*(r['total_uJ']/b['total_uJ']-1),
                'same_screen_verdict':(r['off_V']<1.9)==(b['off_V']<1.9) and (r['vds_V'] <= (585 if r['case']=='S2' else 520))==(b['vds_V'] <= (585 if r['case']=='S2' else 520)),
                'zvs_agrees':r['zvs']==b['zvs']})
assert all(r['same_screen_verdict'] and r['zvs_agrees'] for r in ref if not r.get('aborted'))
(HERE/'refinement-comparison.json').write_text(json.dumps(ref,indent=2)+'\n')
print('refinement maxima', {k:max(abs(r[k]) for r in ref if not r.get('aborted')) for k in ('off_delta_V','vds_delta_V','energy_delta_percent')})
