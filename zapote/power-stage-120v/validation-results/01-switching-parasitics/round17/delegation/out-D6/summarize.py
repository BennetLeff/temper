#!/usr/bin/env python3
"""Read committed ngspice measurements and reproduce D6 evidence tables."""
from __future__ import annotations
import json
from pathlib import Path
from run_study import D2, HERE, cases
from run_combinations import VARIANTS

def load(group: str) -> list[dict]:
    return [json.loads(p.read_text()) for p in sorted((HERE/'results'/group).glob('*/result.json'))]

def key(r: dict) -> tuple:
    return r['case'], r['vbus'], r['il'], r['dir'], r['dt_ns']

def energy(r: dict, window: str, kind: str = 'positive') -> float:
    return 1e6*sum(r['meas'][f'e_{dev}_{window}_{kind}'] for dev in ('l','h'))

def main() -> None:
    original, rows = load('original'), load('corrected')
    assert len(original) == 16
    assert len(rows) == len(VARIANTS)*16
    assert {(r['variant'],*key(r)) for r in rows} == {(v,*c) for v in VARIANTS for c in cases()}
    baseline = {key(r):r for r in rows if r['variant']=='baseline'}
    old_deltas=[]
    for r in original:
        tag=f"{r['case']}_v{r['vbus']}_i{r['il']}_d{r['dir']}_dt{r['dt_ns']}_esl10"
        old=json.loads((D2/'results/grid-h0-lin12-v2/cases'/f'{tag}.json').read_text())
        delta={k:r[k]-old[k] for k in ('vds_pk','vgs_off_max','vds_incoming_at_on')}
        assert all(abs(v)<=0.00011 for v in delta.values()), (tag,delta)
        corrected=baseline[key(r)]
        old_deltas.append({'case':tag,'original_grid_delta':delta,
                           'corrected_minus_original':{k:corrected[k]-r[k] for k in delta}})
    summary={}
    tables=['# D6 per-case measurements','',
            'Generated by `python3 summarize.py`. All corrected-matrix rows: capacitor ESL 10 nH, max step 0.2 ns, model TEMP=27°C. DIR0 turns LS off first; DIR1 HS.',
            'Eoff and Eon are sums over both die ports of positive VDS×ID overlap in [T1,T1+DT] and [T1+DT,T1+DT+750ns], in µJ. They are comparison proxies, not dissipated channel heat; signed values and each device are in raw result JSON.','']
    for variant in VARIANTS:
        selected=[r for r in rows if r['variant']==variant]
        valid=[r for r in selected if not r['aborted']]
        summary[variant]={
            'cases':len(selected),'aborted':sum(r['aborted'] for r in selected),
            'offgate_max_V':max(r['vgs_off_max'] for r in valid),
            'offgate_lt3_count':sum(r['vgs_off_max']<3 for r in valid),
            'offgate_le0_screen_count':sum(r['vgs_off_max']<=0 for r in valid),
            'vds_max_V':max(r['vds_pk'] for r in valid),
            'vds_fail_count':sum(r['vds_pk']>(585 if r['case']=='S2' else 520) for r in valid),
            'S1_348_zvs_count':sum(r['vds_incoming_at_on']<=0.05*r['vbus'] for r in valid if r['case']=='S1' and r['dt_ns']==348),
            'Eoff_ratio_range':[min(energy(r,'off')/energy(baseline[key(r)],'off') for r in valid),max(energy(r,'off')/energy(baseline[key(r)],'off') for r in valid)],
            'Eon_ratio_range':[min(energy(r,'on')/energy(baseline[key(r)],'on') for r in valid),max(energy(r,'on')/energy(baseline[key(r)],'on') for r in valid)],
            'vgs_min_V':min(min(r['meas']['vgs_ls_die_min'],r['meas']['vgs_hs_die_min']) for r in valid),
            'vgs_max_V':max(max(r['meas']['vgs_ls_die_max'],r['meas']['vgs_hs_die_max']) for r in valid)}
        tables += [f'## {variant}','', '| Case | Vbus | DIR | DT ns | Off VGS peak V | Die VDS peak V | Incoming VDS at on V | Eoff µJ | Eon µJ |',
                   '|---|---:|---:|---:|---:|---:|---:|---:|---:|']
        for r in sorted(selected,key=key):
            if r['aborted']:
                tables.append(f"| {r['case']} | {r['vbus']} | {r['dir']} | {r['dt_ns']} | ABORT | — | — | — | — |")
                continue
            tables.append(f"| {r['case']} | {r['vbus']} | {r['dir']} | {r['dt_ns']} | {r['vgs_off_max']:.4f} | {r['vds_pk']:.3f} | {r['vds_incoming_at_on']:.3f} | {energy(r,'off'):.3f} | {energy(r,'on'):.3f} |")
        tables.append('')
    (HERE/'tables.md').write_text('\n'.join(tables)+'\n')
    (HERE/'summary.json').write_text(json.dumps({'original_replay':old_deltas,'remedies':summary},indent=2)+'\n')
    print(json.dumps(summary,indent=2))

if __name__=='__main__':
    main()
