#!/usr/bin/env python3
"""Generate j4-interface.svg: the controller J4 (15 V input from PS1 / native-21 harness) interface drawing.

Every number below is quoted from a committed project document or the committed KiCad footprint; nothing is
read from the network.  The Molex sales drawing for 43045-1600 has NOT been read (molex.com unreachable), so
the connector body envelope is not drawn from it; the pad grid comes from the project's KiCad footprint.
usage: j4_drawing.py [out.svg]
"""
import html, pathlib, re, sys

HERE = pathlib.Path(__file__).resolve().parent
CTRL = HERE.parents[2]
FOOT = CTRL / "pcb/libs/Connector_Molex.pretty/Molex_Micro-Fit_3.0_43045-1600_2x08_P3.00mm_Horizontal.kicad_mod"

# pin -> (net, direction at controller, electrical note)   (README.md pin obligations, DECISIONS C17)
PINS = {
    1: ("v15_selv", "IN", "+15 V +/-2.5 % from PS1 IRM-20-15; ~0.32 A (4.83 W logic load); feeds the 3.3 V buck only"),
    2: ("selv_gnd", "RTN", "15 V return, shares 0.85 A peak with pins 4 and 15"),
    3: ("v3v3", "OUT", "3.3 V from the controller buck; native-21 sees 3.237-3.389 V; <= 49.4 mA"),
    4: ("selv_gnd", "RTN", "return"),
    5: ("pwm_ha", "OUT", "3.3 V logic, GPIO-driven, 10 kOhm pull-down at J4"),
    6: ("pwm_la", "OUT", "3.3 V logic, 10 kOhm pull-down"),
    7: ("pwm_hb", "OUT", "3.3 V logic, 10 kOhm pull-down"),
    8: ("pwm_lb", "OUT", "3.3 V logic, 10 kOhm pull-down"),
    9: ("permit", "OUT", "PERMIT = latch Q AND RUN_EN (U37); 10 kOhm pull-down R103"),
    10: ("bus_fault", "IN", "native-21 OR of OCP/OVP/HOT5/CT; 10 kOhm pull-up, open wire reads fault"),
    11: ("vbus_p", "IN", "D-11 bus sense +, receiver U5; <= 400 pF to ground, <= 200 pF between pair"),
    12: ("vbus_n", "IN", "D-11 bus sense -, tight pair with pin 11"),
    13: ("ct_zc", "IN", "CT zero-cross to GPIO38, 1 kOhm series"),
    14: ("ct_mon", "IN", "CT monitor, U6 buffer >= 10 MOhm DC, 0 V when unplugged"),
    15: ("selv_gnd", "RTN", "return"),
    16: ("line_zc", "IN", "line zero-cross to GPIO39, 1 kOhm series"),
}
COL = {"IN": "#1a5fb4", "OUT": "#c64600", "RTN": "#333333"}


def pad_grid():
    t = open(FOOT).read()
    pads = {}
    for m in re.finditer(r'\(pad "(\d+)" thru_hole \w+\s*\(at ([-\d.]+) ([-\d.]+)\)', t):
        pads[int(m.group(1))] = (float(m.group(2)), float(m.group(3)))
    assert len(pads) == 16, len(pads)
    return pads


def main():
    out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "j4-interface.svg"
    pads = pad_grid()
    W, H = 1180, 900
    s = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" '
         f'font-family="Helvetica, Arial, sans-serif" font-size="12">',
         f'<rect width="{W}" height="{H}" fill="#ffffff"/>',
         '<text x="20" y="30" font-size="20" font-weight="bold">J4 interface: controller 15 V input / native-21 harness</text>',
         '<text x="20" y="50" fill="#444">Controller J4 = Molex Micro-Fit 3.0 43045-1600 (LCSC C277731), 2x8, right-angle THT, mating -X (left board edge). '
         'Generated by j4_drawing.py from the committed KiCad footprint and README/DECISIONS C17.</text>']
    # ---- header pad view (top view, KiCad footprint orientation), scale 40 px/mm
    k, ox, oy = 40, 60, 130
    s.append('<text x="20" y="80" font-size="14" font-weight="bold">Header pad grid, top view (footprint frame, mm)</text>')
    x0, y0 = ox - 30, oy - 40
    s.append(f'<rect x="{x0}" y="{y0}" width="{21*k+60}" height="{3*k+80}" fill="#f4f4f0" stroke="#999" stroke-dasharray="4 3"/>')
    s.append(f'<text x="{x0+4}" y="{y0+12}" fill="#666">courtyard not drawn: Molex envelope drawing unread (UNVERIFIED)</text>')
    for n, (px, py) in sorted(pads.items()):
        cx, cy = ox + px * k, oy + py * k + 20
        net, d, _ = PINS[n]
        shape = (f'<rect x="{cx-9}" y="{cy-9}" width="18" height="18" fill="{COL[d]}"/>' if n == 1 else
                 f'<circle cx="{cx}" cy="{cy}" r="9" fill="{COL[d]}"/>')
        s.append(shape)
        s.append(f'<text x="{cx}" y="{cy+4}" fill="#fff" font-size="10" text-anchor="middle">{n}</text>')
        ty = cy - 16 if py == 0 else cy + 24
        s.append(f'<text x="{cx}" y="{ty}" text-anchor="middle" font-size="10" fill="{COL[d]}">{net}</text>')
    s.append(f'<polygon points="{ox-26},{oy+20-8} {ox-26},{oy+20+8} {ox-14},{oy+20}" fill="#d00000"/>')
    s.append(f'<text x="{ox-52}" y="{oy+54}" fill="#d00000" font-weight="bold">PIN 1</text>')
    s.append(f'<text x="{ox}" y="{oy+3*k+68}" fill="#444">Row A = pins 1-8 (left to right), row B = pins 9-16 below it; pin 3.00 mm pitch, row spacing 3.00 mm. '
             f'Pin 1 square pad.</text>')
    s.append(f'<text x="{ox}" y="{oy+3*k+84}" fill="#444">Two 3.0 mm non-plated peg holes at x = 2.16 and 18.86, y = -4.32 (footprint frame). '
             f'Plated drill 1.02 mm, pad 1.5 mm.</text>')
    s.append('<text x="975" y="95" font-size="14" font-weight="bold">Legend</text>')
    for i, (lab, d) in enumerate([("controller input", "IN"), ("controller output", "OUT"), ("return / selv_gnd", "RTN")]):
        s.append(f'<circle cx="985" cy="{112+i*20}" r="7" fill="{COL[d]}"/><text x="998" y="{116+i*20}">{lab}</text>')
    # ---- harness block
    hy = 375
    s.append(f'<text x="20" y="{hy}" font-size="14" font-weight="bold">Harness SELV_J4_to_controller (1:1, pin 1 to pin 1)</text>')
    s.append(f'<rect x="20" y="{hy+14}" width="150" height="60" fill="#eef3ff" stroke="#1a5fb4"/>'
             f'<text x="95" y="{hy+38}" text-anchor="middle" font-weight="bold">controller J4</text>'
             f'<text x="95" y="{hy+56}" text-anchor="middle">43045-1600 R/A header</text>')
    s.append(f'<rect x="1010" y="{hy+14}" width="150" height="60" fill="#eef3ff" stroke="#1a5fb4"/>'
             f'<text x="1085" y="{hy+38}" text-anchor="middle" font-weight="bold">native-21 J4</text>'
             f'<text x="1085" y="{hy+56}" text-anchor="middle">43045-1612 vertical</text>')
    s.append(f'<line x1="170" y1="{hy+44}" x2="1010" y2="{hy+44}" stroke="#333" stroke-width="4"/>')
    s.append(f'<rect x="170" y="{hy+26}" width="110" height="36" fill="#fff" stroke="#333"/>'
             f'<text x="225" y="{hy+41}" text-anchor="middle">43025-1600</text><text x="225" y="{hy+55}" text-anchor="middle">housing, 16 pos</text>')
    s.append(f'<rect x="900" y="{hy+26}" width="110" height="36" fill="#fff" stroke="#333"/>'
             f'<text x="955" y="{hy+41}" text-anchor="middle">43025-1600</text><text x="955" y="{hy+55}" text-anchor="middle">housing, 16 pos</text>')
    s.append(f'<text x="590" y="{hy+34}" text-anchor="middle">16 x AWG22, length &lt;= 1 m (allocation; harness length not yet specified in ENCLOSURE-HANDOFF)</text>')
    s.append(f'<text x="590" y="{hy+60}" text-anchor="middle" fill="#444">crimp: 43030-0001 (20-24 AWG, tin) x 32; gold alt 43030-0008; crimp tool / die not selected here</text>')
    s.append(f'<text x="590" y="{hy+78}" text-anchor="middle" fill="#444">vbus_p/vbus_n (11/12) twisted pair; D-11 harness: &lt;= 400 pF to ground, &lt;= 200 pF between conductors</text>')
    s.append(f'<text x="20" y="{hy+100}" fill="#444">Contact rating 8.5 A (LCSC C277731), 600 V; used at 0.32 A on pin 1, 0.85 A peak shared by pins 2/4/15 (DECISIONS C17), '
             f'so the contacts run at about 10 % of rating or less.</text>')
    s.append(f'<text x="20" y="{hy+116}" fill="#444">Polarity: the 43025/43045 shells are keyed (shell shape and latch polarise the mating, no reverse fit); '
             f'pin 1 triangle on the housing at the pin 1 end; wire colours not assigned.</text>')
    # ---- pin table
    ty = 535
    s.append(f'<text x="20" y="{ty}" font-size="14" font-weight="bold">Pin map</text>')
    s.append(f'<text x="20" y="{ty+20}" font-weight="bold">Pin</text><text x="60" y="{ty+20}" font-weight="bold">Net</text>'
             f'<text x="160" y="{ty+20}" font-weight="bold">Dir</text><text x="215" y="{ty+20}" font-weight="bold">Level / current / note</text>')
    for i, (n, (net, d, note)) in enumerate(sorted(PINS.items())):
        y = ty + 40 + i * 19
        s.append(f'<rect x="14" y="{y-13}" width="{W-28}" height="19" fill="{"#f6f6f6" if i % 2 else "#ffffff"}"/>')
        s.append(f'<text x="20" y="{y}">{n}</text><text x="60" y="{y}" fill="{COL[d]}">{net}</text>'
                 f'<text x="160" y="{y}">{d}</text><text x="215" y="{y}">{html.escape(note)}</text>')
    s.append(f'<text x="20" y="{H-14}" fill="#a00000">Open item: Molex sales drawing 430451600_sd not read (molex.com unreachable); '
             f'envelope, mated height 10.29 mm (series figure, 43045-2001) and plug overhang remain [UNVERIFIED].</text>')
    s.append('</svg>')
    out.write_text("\n".join(s) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
