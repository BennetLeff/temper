def board_of_record() -> dict:
    text = read(FAB_NOTE)
    m = re.search(r"Board: native-21 stage (\d+)[a-z]?, the board of record", text)
    h = re.search(r"SHA-256\s*`([0-9a-f]{64})`", text)
    k = re.search(r"copper key ([0-9a-f]{12})", text)
    if not (m and h and k):
        raise GateError(f"{rel(FAB_NOTE)}: cannot read the board-of-record stage / SHA-256 / copper key")
    stage, board, copper = m.group(1), h.group(1), k.group(1)
    if stage not in STAGE_FACTS:
        raise GateError(f"board of record is stage {stage} but STAGE_FACTS has {sorted(STAGE_FACTS)}: re-base "
                        "COMMISSIONING.md on it (read its DECISIONS entry, add STAGE_FACTS[stage], re-render)")
    card = VR / f"10-benchmark/scorecard-native21s{stage}.json"
    if json.loads(read(card))["board_sha256"] != board:
        raise GateError(f"{rel(card)} board_sha256 differs from FAB-NOTE's {board[:12]}")
    return {"stage": stage, "tag": f"native21s{stage}", "board": board, "copper": copper, "card": card}


def render() -> tuple[str, list[str]]:
    """(markdown block, findings): findings are firmware / board disagreements the block reports."""
    rec = board_of_record()
    facts = STAGE_FACTS[rec["stage"]]
    bom, nets = load_board()
    ohm = {d: mpn_ohms(p) for d, p in bom.items()}
    findings: list[str] = []

    # --- threshold engine (CT band, nominal OCP / OVP), with the board's parts
    thr = load_module("thr_cbt", THRESHOLDS)
    for f in ("default.csv", "default.net"):   # the engine's validate_inputs reads the unit-level frozen copy
        if _sha(PS / "frozen" / f) != _sha(FROZEN / f):
            raise GateError(f"zapote/power-stage-120v/frozen/{f} differs from native-21/frozen/{f}")
    over = {r: bom[r] for r in ("R5", "R32", "R33", "R34", "R35", "R39", "R43", "R44", "R45", "R46")}
    thr.validate_inputs(overrides=over)
    rt = (0.001, 25e-6)
    for r in ("R30", "R32", "R33", "R34", "R35", "R36", "R37", "R40", "R41", "R43", "R44", "R45", "R46"):
        if not bom[r].startswith("RT0603BRD07"):
            raise GateError(f"{r} {bom[r]} is not an RT0603BRD 0.1 % / 25 ppm part (the band model assumes it)")
        thr.PARTS[r] = (ohm[r], *rt)
    for r in ("R26", "R27", "R28", "R29"):
        thr.PARTS[r] = (ohm[r], *thr.PARTS[r][1:])
    if bom["R5"] != "CSS2H-2512R-1L00F":
        raise GateError(f"R5 is {bom['R5']}; the band record models CSS2H-2512R-1L00F")
    thr.PARTS["R5"] = thr.SHUNT_CSS2H
    ratio = facts["ct_ratio"].get(bom["T1"])
    if ratio is None:
        raise GateError(f"T1 {bom['T1']}: turns ratio unknown (STAGE_FACTS ct_ratio)")
    # the engine's CT gain is R39 / 100 (a 1:100 CT); scale the burden to this CT's ratio
    thr.PARTS["R39"] = (ohm["R39"] * 100.0 / ratio, *thr.PARTS["R39"][1:])
    v_per_a = ohm["R39"] / ratio
    p0 = {k: v[0] for k, v in thr.PARTS.items()}
    ocp_nom, ct_nom, _, ovp_nom = thr.thresholds(p0, 2.5, 0.0)
    vcm = 2.5 * p0["R35"] / (p0["R34"] + p0["R35"])
    ct = {t: thr.exact_corners(t, 50.0) for t in (-10.0, 85.0)}
    ct_band = {k: (floor2(min(ct[t][k]["min"] for t in ct)), ceil2(max(ct[t][k]["max"] for t in ct)))
               for k in ("ct_pos_a", "ct_neg_a")}

    # --- Kelvin budget and band record for this stage
    kb = load_module("kb_cbt", KELVIN / "kelvin_budget.py")
    tag = rec["tag"]
    if tag not in kb.BAND_BEFORE or tag not in kb.FLOOR:
        raise GateError(f"kelvin_budget.py has no BAND_BEFORE / FLOOR for {tag}")
    band_before, floor_a = tuple(kb.BAND_BEFORE[tag]), kb.FLOOR[tag]
    budget = json.loads(read(KELVIN / f"budget-{tag}.json"))
    if tuple(budget["band_before_A"]) != band_before:
        raise GateError(f"budget-{tag}.json band_before_A {budget['band_before_A']} != BAND_BEFORE {band_before}: "
                        f"re-run kelvin_budget.py {tag}")
    shift_c, shift_b = budget["trip_shift_A"], budget["bound_all_at_max_transfer"]["trip_shift_A"]
    bandrec = json.loads(read(VR / facts["band_record"]))
    basis = bandrec[facts["band_basis_key"]]
    if tuple(basis["ocp_band_before_kelvin_A"]) != band_before:
        raise GateError(f"{facts['band_record']} basis {basis['ocp_band_before_kelvin_A']} != BAND_BEFORE {band_before}")
    if bandrec["divider"] != {r: ohm[r] for r in ("R32", "R33", "R34", "R35")}:
        raise GateError(f"{facts['band_record']} divider {bandrec['divider']} is not the frozen BOM's")
    solved = {r["network"]: r for r in bandrec["rows"] if r["network"].startswith("solved ")}
    hottest = [r for r in bandrec["rows"] if r["network"].startswith("hottest ")]
    ovp_bound = (min(r["ovp_band_V"][0] for r in hottest), max(r["ovp_band_V"][1] for r in hottest))
    rel_row = next(r for n, r in solved.items() if n.startswith("solved c17.5"))
    c28_row = next(r for n, r in solved.items() if n.startswith("solved c28"))
    tlv = {(r["network"].split("@")[0], r["reading"], r["hot5"]): r for r in bandrec["tlv3201_readings"]}
    r0_c28 = tlv[("c28_h10", "R0", "Q1")]["ocp_before_A"]
    r1_rel = tlv[("c17.5_h10", "R1", "Q1")]["ocp_before_A"]

    # --- B3 temperature of the CT network: R39 always; R40-R46 once B3 gates them (stage 54, "tank-CT band basis" rows)
    mg = json.loads(read(MARGINS))
    if set(mg["board_sha256"].values()) != {rec["board"]}:
        raise GateError(f"{rel(MARGINS)} is not solved on board {rec['board'][:12]}")
    r39_t = max(r["est_c"] for rows_ in mg["cases"].values() for r in rows_ if r["item"].startswith("R39:"))
    ct_refs = [r for rows_ in mg["cases"].values() for r in rows_
               if r["item"].split(":")[0] in ("R40", "R41", "R43", "R44", "R45", "R46") and "tank-CT band basis" in r["item"]]
    ct_ref = max(ct_refs, key=lambda r: r["est_c"]) if ct_refs else None

    # --- D3 / D17 stand-off (datasheet ledger)
    led = json.loads(read(LEDGER))
    tvs = led["entries"].get(bom["D3"])
    if tvs is None:
        raise GateError(f"datasheet ledger has no entry for D3 {bom['D3']}")
    standoff = next(r["datasheet_limit"] for r in tvs["ratings"] if r["parameter"] == "Standoff string")
    lim_v = facts["ovp_supply_limit_v"]
