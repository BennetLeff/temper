class GateError(Exception):
    """An input is missing, unparseable, or the board of record has no STAGE_FACTS entry."""


def load_module(name: str, path: Path):
    if not path.exists():
        raise GateError(f"missing {path.relative_to(REPO)}")
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def read(path: Path) -> str:
    if not path.exists():
        raise GateError(f"missing {path.relative_to(REPO)}")
    return path.read_text()


def rel(path: Path) -> str:
    return str(path.relative_to(REPO))


# ---------------------------------------------------------------------------------------------- parts

_CODE = re.compile(r"(\d+)([KRM])(\d*)")
_MULT = {"R": 1.0, "K": 1e3, "M": 1e6}


def _code(s: str) -> float:
    m = _CODE.fullmatch(s)
    if not m:
        raise ValueError(s)
    return float(f"{m.group(1)}.{m.group(3) or '0'}") * _MULT[m.group(2)]


def mpn_ohms(mpn: str) -> float | None:
    """Nominal resistance of the resistor families on the board, from the MPN; None if not a known family."""
    for pat, fn in (
        (r"RT0603BRD07(\w+)L", lambda g: _code(g[0])),                 # Yageo RT 0.1 %
        (r"RC(?:0402|0603|0805|1206|2512)FR-07(\w+)L", lambda g: _code(g[0])),  # Yageo RC 1 %
        (r"(?:0603WAF|0402WGF|1206W4F|0805W8F)(\d{3})(\d)T5E", lambda g: int(g[0]) * 10 ** int(g[1])),
        (r"25121WF(\d{2})(\d)JT4E", lambda g: int(g[0]) * 10 ** int(g[1])),
        (r"PS122WF(\d{2})(\d)JT4E", lambda g: int(g[0]) * 10 ** int(g[1])),       # UniRoyal PS12 2 W (stage 54 R_on)
        (r"ERJ-PA3F(\d{3})(\d)V", lambda g: int(g[0]) * 10 ** int(g[1])),          # Panasonic ERJ-PA3 1 % (stage 54)
        (r"TNPW0603(\w+)BEEA", lambda g: _code(g[0])),
        (r"CSS2H-2512R-(\d)L(\d{2})F", lambda g: float(f"{g[0]}.{g[1]}") * 1e-3),
    ):
        m = re.fullmatch(pat, mpn)
        if m:
            return float(fn(m.groups()))
    return None


def load_board():
    bom = {}
    with (FROZEN / "default.csv").open(newline="") as fh:
        for row in csv.DictReader(fh):
            for d in row["Designator"].split(","):
                bom[d.strip()] = row["Comment"]
    res = json.loads(read(FROZEN / "resolved-components.json"))
    roles = {}
    for it in res["components"]:
        role = it["address"].split("::", 1)[1]
        roles[role] = it["attributes"]["designator"]
    for role, want in ROLES.items():
        if roles.get(role) != want:
            raise GateError(f"designator moved: {role} is {roles.get(role)}, the procedure assumes {want}")
    net = read(FROZEN / "default.net")
    blocks = re.findall(r'\(net \(code "\d+"\) \(name "([^"]+)"\)(.*?)(?=\n    \(net |\n  \)\n\))', net, re.S)
    nets = {n: re.findall(r'\(node \(ref "([^"]+)"\) \(pin "([^"]+)"\)', body) for n, body in blocks}
    return bom, nets


def fmt_ohm(v: float) -> str:
    if v < 1:
        return f"{v * 1e3:g} mΩ"
    if v < 1e3:
        return f"{v:g} Ω"
    if v < 1e6:
        return f"{v / 1e3:g} k"
    return f"{v / 1e6:g} M"


def floor2(x: float) -> float:
    return math.floor(x * 100 + 1e-9) / 100


def ceil2(x: float) -> float:
    return math.ceil(x * 100 - 1e-9) / 100


def c_define(path: Path, name: str) -> float:
    m = re.search(rf"#define\s+{name}\s+\(?([-0-9.]+)f?", read(path))
    if not m:
        raise GateError(f"{name} not defined in {rel(path)}")
    return float(m.group(1))


def kconfig() -> dict[str, str]:
    out, cur = {}, None
    for line in read(KCONFIG).splitlines():
        m = re.match(r"config\s+(\w+)", line)
        if m:
            cur = m.group(1)
            out.setdefault(cur, "")
            continue
        m = re.match(r"\s+default\s+(\S+)", line)
        if m and cur and not out[cur]:
            out[cur] = m.group(1)
        m = re.match(r"\s+range\s+(\S+)\s+(\S+)", line)
        if m and cur:
            out[cur + ".range"] = f"{m.group(1)} {m.group(2)}"
    return out


