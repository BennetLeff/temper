STAGE_CLAIM = re.compile(r"\b(?:stage[- ]?|s)(\d+)[a-z]?\**\s+board\b|\bstage[- ]?(\d+)[a-z]?\**:\s*R\d", re.I)
DESIG_VAL = re.compile(r"(?<![\w.])(?<!controller )(R\d+(?:\s*/\s*R\d+)*)\s*(?:=\s*)?(\d+(?:\.\d+)?)\s?"
                       r"(mΩ|kΩ|MΩ|Ω|k(?![A-Za-z0-9])|M(?![A-Za-z0-9]))")
_UNIT = {"mΩ": 1e-3, "Ω": 1.0, "kΩ": 1e3, "k": 1e3, "MΩ": 1e6, "M": 1e6}


def split_doc(text: str) -> tuple[str, str, str]:
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        raise GateError("COMMISSIONING.md must hold the board-table markers exactly once")
    head, rest = text.split(BEGIN, 1)
    block, tail = rest.split(END, 1)
    return head, BEGIN + block + END + "\n", tail.lstrip("\n")


def check_text(text: str, rendered: str, stage: str, bom: dict, kc: dict, fw_text: str) -> list[str]:
    errs = []
    head, block, tail = split_doc(text)
    if block != rendered:
        errs.append("board table differs from the rendered one: run commissioning_board_table.py --write and review")
    prose = head + tail
    intro = head.split("\n## ", 1)[0]
    if not re.search(rf"\bstage {stage}\b", intro):
        errs.append(f"the introduction does not name the board of record (stage {stage})")
    lines, inside = [], False                       # (file line number, text) outside the block
    for n, line in enumerate(text.splitlines(), 1):
        if line == BEGIN:
            inside = True
        if not inside:
            lines.append((n, line))
        if line == END:
            inside = False
    errs += _prose_checks(lines, prose, stage, bom, kc, fw_text)
    return errs


def _prose_checks(lines: list[tuple[int, str]], prose: str, stage: str, bom: dict, kc: dict, fw_text: str) -> list[str]:
    errs = []
    for n, line in lines:
        for m in STAGE_CLAIM.finditer(line):
            st = m.group(1) or m.group(2)
            if st != stage:
                errs.append(f"line {n}: claims a stage-{st} board ('{m.group(0)}'); the board of record is stage {stage}")
        for m in DESIG_VAL.finditer(line):
            want = float(m.group(2)) * _UNIT[m.group(3)]
            for d in re.split(r"\s*/\s*", m.group(1)):
                have = mpn_ohms(bom.get(d, "")) if d in bom else None
                if d not in bom:
                    errs.append(f"line {n}: {d} is not on the stage-{stage} board ('{m.group(0)}')")
                elif have is None:
                    errs.append(f"line {n}: {d} {bom[d]}: value not parseable, cannot check '{m.group(0)}'")
                elif abs(have - want) > 1e-6 * max(have, 1e-3):
                    errs.append(f"line {n}: '{m.group(0)}' but the frozen BOM has {d} = {bom[d]} ({fmt_ohm(have)})")
    for sym in sorted(set(re.findall(r"\b(?:CONFIG_)?(TEMPER_POWER_[A-Z0-9_]+)", prose))):
        if sym not in kc:
            errs.append(f"Kconfig has no {sym}")
    for line in prose.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != 5 or "`" not in cells[1]:
            continue
        names = [t for t in re.findall(r"`([A-Z0-9_]+)`", cells[1]) if not cells[1].lstrip().startswith("(")]
        if not names or not all(f"TEMPER_POWER_{t}" in kc for t in names):
            continue
        vals = [v.strip().split(" ")[0] for v in re.split(r",\s*(?![^()]*\))", cells[2])]
        for t, v in zip(names, vals):
            if v != kc[f"TEMPER_POWER_{t}"]:
                errs.append(f"record row '{cells[0]}': {t} provisional {v} != Kconfig default {kc['TEMPER_POWER_' + t]}")
    for sym in sorted(set(re.findall(r"`([A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+)`", prose))):
        if sym.startswith("TEMPER_POWER_") or f"TEMPER_POWER_{sym}" in kc:
            continue
        if sym not in fw_text:
            errs.append(f"`{sym}` is not mentioned anywhere in the firmware sources")
    return errs


STEP_HEAD = re.compile(r"^## Step (\d+[a-z]?):", re.M)
_TOK = r"\d+[a-z]?"
STEP_REF = re.compile(rf"\bsteps?\s+({_TOK}(?:\s*(?:,|–|-|and|or)\s*{_TOK})*)"
                      rf"(?:\s+items?\s+({_TOK}(?:\s*(?:,|–|-|and|or)\s*{_TOK})*))?", re.I)


def procedure_steps(proc_text: str) -> dict[str, set[str]]:
    """Step id -> the top-level item numbers of that step, from COMMISSIONING.md's '## Step N:' sections."""
    heads = list(STEP_HEAD.finditer(proc_text))
    steps = {}
    for i, h in enumerate(heads):
        end = proc_text.find("\n## ", h.end())
        body = proc_text[h.end(): end if end >= 0 else len(proc_text)]
        steps[h.group(1)] = set(re.findall(r"^(\d+)\. ", body, re.M))
    return steps


def check_companion(text: str, proc_text: str, stage: str, bom: dict, kc: dict, fw_text: str) -> list[str]:
    """BRING-UP.md: the prose rules, the board of record in the introduction, and step / item refs that exist."""
    errs = []
    intro = text.split("\n## ", 1)[0]
    if not re.search(rf"\bstage {stage}\b", intro):
        errs.append(f"BRING-UP.md: the introduction does not name the board of record (stage {stage})")
    lines = list(enumerate(text.splitlines(), 1))
    errs += [f"BRING-UP.md {e}" for e in _prose_checks(lines, text, stage, bom, kc, fw_text)]
    steps = procedure_steps(proc_text)
    for n, line in lines:
        for m in STEP_REF.finditer(line):
            ids = re.findall(_TOK, m.group(1))
            for sid in ids:
                if sid not in steps:
                    errs.append(f"BRING-UP.md line {n}: '{m.group(0)}' but COMMISSIONING.md has no step {sid}")
            if m.group(2) and len(ids) == 1 and ids[0] in steps:
                for it in re.findall(r"\d+", m.group(2)):
                    if it not in steps[ids[0]]:
                        errs.append(f"BRING-UP.md line {n}: '{m.group(0)}' but COMMISSIONING.md step {ids[0]} "
                                    f"has no item {it}")
    return errs


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    ap.add_argument("--doc", type=Path, default=None, help="check / write this file instead of COMMISSIONING.md")
    a = ap.parse_args(argv)
    doc = a.doc or DOC
    try:
        rendered, findings = render()
        if a.write:
            head, _, tail = split_doc(doc.read_text())
            doc.write_text(head + rendered + "\n" + tail)
            print(f"wrote {doc}")
        elif a.check:
            stage = board_of_record()["stage"]
            bom, _ = load_board()
            fw = "\n".join(p.read_text(errors="replace") for p in FW_SOURCES if p.exists())
            errs = check_text(doc.read_text(), rendered, stage, bom, kconfig(), fw)
            for e in errs:
                print(f"FAIL: {e}")
            if errs:
                return EXIT_VIOLATION
            print(f"PASS: COMMISSIONING.md matches the stage-{stage} board table")
            if not BRINGUP.exists():
                raise GateError(f"{BRINGUP} is missing (the home-lab overview the gate also checks)")
            errs = check_companion(BRINGUP.read_text(), doc.read_text(), stage, bom, kconfig(), fw)
            for e in errs:
                print(f"FAIL: {e}")
            if errs:
                return EXIT_VIOLATION
            print("PASS: BRING-UP.md points only to COMMISSIONING steps that exist and agrees with the board")
        else:
            sys.stdout.write(rendered)
        for f in findings:
            print(f"FINDING (firmware / board, for the owner): {f}", file=sys.stderr)
    except GateError as e:
        print(f"GATE ERROR: {e}", file=sys.stderr)
        return EXIT_GATE_ERROR
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
