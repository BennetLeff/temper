#!/usr/bin/env python3
"""Render the board-specific tables of firmware/components/power/COMMISSIONING.md from the native-21
board of record, and check the procedure against them.

Board-specific numbers in a bench procedure drifting from the board is a recurring error class here
(COMMISSIONING.md carried the stage-15 OCP divider and band into stage 53). This tool makes the
procedure's board numbers a generated artifact:

* The board of record is whatever ``fab/FAB-NOTE.md`` names (stage, board SHA-256, copper key). Its
  scorecard must carry the same board hash.
* Every value in the block is re-derived from a committed source on each run: the frozen BOM, netlist
  and resolved export; the round-3 threshold engine (CT band, nominal trips); the Kelvin budget and the
  band record the budget names for this stage; the B3 margins; the 2EDR8259X dead-time estimator; the
  controller's D-11 receiver calc; BRINGUP-PROBES.md; firmware headers and Kconfig.
* The few facts no light tool reproduces (SPICE timing, bank ladder stops) live in ``STAGE_FACTS``,
  keyed by stage with their DECISIONS / OPEN-ITEMS citation. A new board of record has no entry, so the
  tool refuses (exit 5) until someone re-bases the procedure on it.

``--check`` also fails when the procedure, outside the generated block:
* claims a stage other than the board of record for the board ("stage-15 board", "stage 15: R34 ..."),
* gives a power-board resistor a value the frozen BOM does not have ("R34 12.6 kΩ"),
* names a TEMPER_POWER_* Kconfig symbol that does not exist, or a commissioning-record provisional
  value that differs from the Kconfig default,
* names a backticked firmware symbol (UPPER_SNAKE) that no firmware source mentions.

``--check`` also checks the home-lab overview ``BRING-UP.md`` (native-21 manufacturing package), which has no
generated block and must point to COMMISSIONING's steps instead of repeating them. It gets the same prose rules,
its introduction must name the board of record, and every "step N" / "step N item M" it names must exist in
COMMISSIONING.md (a renumbered or deleted step fails here instead of leaving a dangling pointer).

Usage:
  python3 firmware/tools/commissioning_board_table.py            # print the rendered block
  python3 firmware/tools/commissioning_board_table.py --write    # replace the block in COMMISSIONING.md
  python3 firmware/tools/commissioning_board_table.py --check    # 0 ok, 3 drift, 5 gate error

Needs numpy (the round-3 engine imports it).
"""

