"""Rev F phase 1: turn the floorplan's capacitance and inductance FORECAST into a stability-harness board.

python3 validation/rev-f-floorplan/forecast_harness.py     (after floorplan.py; < 1 s)

Writes ../stability-full-chain/revf_est_extracted.rs with two board sets for loop_matrix.rs:
  REVF_EST_*   every node-to-ground term from the forecast, mutual terms as extracted on Rev E,
               RF-loop inductance from the forecast (Rev E free-space value x planned path / Rev E path)
  REVF_PESS_*  the same ground terms, every mutual term doubled (a denser board couples more) and the
               Rev E RF-loop inductances kept (no credit for the shorter loops)
Both start from the Rev E as-built extraction strings (extracted_reve_bnc.json, board 80d44838), so
every node, term and range is the one `kelvincng100` ran. This is a forecast for the go/no-go
decision only; phase 3 replaces it with an FD extraction of the routed Rev F board.
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
FP = json.loads((HERE / 'floorplan.json').read_text())
EXT = json.loads((HERE.parent / 'layout-parasitics/extracted_reve_bnc.json').read_text())
NETS = FP['net_ground_capacitance_forecast_pf']
RANGES = ['r100', 'r5k', 'r100k']
RF = ['RF100', 'RF5K', 'RF100K']
RG = ['RG100', 'RG5K', 'RG100K']
FIXED = {'sum': ['TIA_SUM'], 'low': ['DUT_LO'], 'hi': ['DUT_HI'], 'lowbuf': ['LOW_BUF'], 'highbuf': ['HIGH_BUF'],
         'srcdrv': ['SRC_DRV'], 'hpot': ['HPOT'], 'lpot': ['LPOT'], 'refa': ['REF_A']}


def nets_of(node, k):
    if node == 'tia':
        return ['TIA_OUT', RF[k]]
    if node == 'source':
        return ['SOURCE_BUF', RG[k]]
    m = re.fullmatch(r'(ru|rgu)(\d)', node)
    if m:
        return [(RF if m.group(1) == 'ru' else RG)[int(m.group(2))]]
    return FIXED[node]


def board(corner, k, mutual_factor):
    lines = []
    for line in EXT['spice'][corner][RANGES[k]].splitlines():
        name, a, b, val = line.split()
        v = float(val.rstrip('p'))
        if b == '0':
            nets = nets_of(a, k)
            e = sum(NETS[n][f'rev_e_{corner}'] for n in nets)
            assert abs(e - v) < 2e-3 * max(1.0, v), (corner, k, a, e, v)
            v = sum(NETS[n][f'rev_f_{corner}'] for n in nets)
        else:
            v *= mutual_factor
        lines.append(f'{name} {a} {b} {v:.4f}p')
    return '\n'.join(lines) + '\n'


def main():
    rf = FP['rf_loop_forecast']
    est_l = [rf[n]['rev_f_L_forecast_nH'] for n in RF]
    e_l = [EXT['inductance_nh'][r]['high'] for r in RANGES]
    cap = EXT['inductance_nh']['c104']['high']
    out = ['// GENERATED by ../rev-f-floorplan/forecast_harness.py from floorplan.json -- do not edit.',
           '// Rev F (100 x 100 mm) FORECAST board, not an extraction: Rev E 80d44838 strings with every',
           '// ground term replaced by the floorplan forecast. EST: Rev E mutuals, forecast RF-loop L.',
           '// PESS: mutuals x2, Rev E RF-loop L.']
    for tag, mf, lead in (('EST', 1.0, est_l), ('PESS', 2.0, e_l)):
        out.append(f'const REVF_{tag}_LEAD: [f64; 3] = {json.dumps(lead)};')
        out.append(f'const REVF_{tag}_CAPLEAD: f64 = {cap};')
        for corner, cname in (('nom', 'NOM'), ('high', 'HIGH')):
            out.append(f'const REVF_{tag}_BOARD_{cname}: [&str; 3] = [')
            out += ['    ' + json.dumps(board(corner, k, mf)) + ',' for k in range(3)]
            out.append('];')
    dest = HERE.parent / 'stability-full-chain/revf_est_extracted.rs'
    dest.write_text('\n'.join(out) + '\n')
    print(f'wrote {dest}; EST RF L {est_l} nH, PESS {e_l} nH')


if __name__ == '__main__':
    main()
