"""Summarise the fixture/lead envelope matrices into fixture-envelope-tables.md.

Reads matrix-final_{fixedfixture,fixedleads,fixedriso,fixedrisoleads,fixedrisogrid,fixedrisocorners}.md
written by `loop_matrix final_<mode>` and reports, per case group, the minimum downward-crossing
angle from -1 and the minimum return difference |1+T|. Run: python3 fixture_envelope.py
"""

import re
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODES = ["fixedfixture", "fixedleads", "fixedriso", "fixedrisoleads", "fixedrisogrid", "fixedrisocorners", "fixedextracted"]


def rows(mode):
    for line in (HERE / f"matrix-final_{mode}.md").read_text().splitlines():
        if not line.startswith("| final"):
            continue
        cells = line.split("|")
        down = [float(a) for a in re.findall(r"/ (-?[\d.]+)° \(down\)", cells[2])]
        yield cells[1].strip(), min(down), float(cells[3].split()[0])


def main():
    out = ["# Fixture envelope tables (generated by fixture_envelope.py)", ""]
    # Lumped stray, no isolation resistor, TIA loop.
    out += ["## Lumped stray per DUT terminal, TIA loop, no isolation", "",
            "| Range | DUT | 0 pF | 100 pF | 220 pF | 470 pF | 1000 pF |", "|---|---|---:|---:|---:|---:|---:|"]
    table = defaultdict(dict)
    for name, angle, _ in rows("fixedfixture"):
        m = re.match(r"final_fixture_(\w+?)_(\w+?)_stray([\d.]+)_.*_tia$", name)
        if m:
            table[(m[1], m[2])][float(m[3])] = angle
    for (rng, dut), v in table.items():
        out.append(f"| {rng} | {dut} | " + " | ".join(f"{v[s]:.1f}°" for s in [0, 100, 220, 470, 1000]) + " |")
    out += ["", "## Isolation resistor between J3 LO and the summing node, 100 Ω range, TIA loop", "",
            "| R_iso | DUT | 0 pF | 100 pF | 220 pF | 470 pF | 1000 pF |", "|---|---|---:|---:|---:|---:|---:|"]
    table = defaultdict(dict)
    for name, angle, _ in rows("fixedriso"):
        m = re.match(r"final_riso_r100_(\w+?)_stray([\d.]+)_risolo([\d.]+)_.*_tia$", name)
        if m:
            table[(float(m[3]), m[1])][float(m[2])] = angle
    for (ri, dut), v in sorted(table.items()):
        out.append(f"| {ri:g} Ω | {dut} | " + " | ".join(f"{v[s]:.1f}°" for s in [0, 100, 220, 470, 1000]) + " |")
    out += ["", "## Group minima (all loops in each matrix)", "",
            "| Matrix | Cases | Min downward angle | Case | Min abs(1+T) |", "|---|---:|---:|---|---:|"]
    for mode in MODES:
        r = list(rows(mode))
        worst = min(r, key=lambda x: x[1])
        out.append(f"| {mode} | {len(r)} | {worst[1]:.2f}° | `{worst[0].removeprefix('final_')}` | {min(x[2] for x in r):.3f} |")
        for rng in ["r100", "r5k", "r100k"]:
            sub = [x for x in r if f"_{rng}_" in x[0]]
            if sub:
                w = min(sub, key=lambda x: x[1])
                out.append(f"| ↳ {rng} | {len(sub)} | {w[1]:.2f}° | | {min(x[2] for x in sub):.3f} |")
    out += ["", "## Extracted board parasitics plus cable capacitance (TIA loop, worst DUT and C104 lead)", "",
            "| Variant | Range | 0 pF | 100 pF | 220 pF | 470 pF | 1000 pF |", "|---|---|---:|---:|---:|---:|---:|"]
    table = defaultdict(lambda: defaultdict(list))
    for name, angle, _ in rows("fixedextracted"):
        m = re.match(r"final_extracted_(\w+?)_\w+?_stray([\d.]+)(_risolo22)?_caplead", name)
        table[("22 Ω R_iso" if m[3] else "Rev C", m[1])][float(m[2])].append(angle)
    for (variant, rng), v in sorted(table.items(), key=lambda kv: (kv[0][0], ["r100", "r5k", "r100k"].index(kv[0][1]))):
        out.append(f"| {variant} | {rng} | " + " | ".join(f"{min(v[s]):.1f}°" if s in v else "—" for s in [0, 100, 220, 470, 1000]) + " |")
    (HERE / "fixture-envelope-tables.md").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
