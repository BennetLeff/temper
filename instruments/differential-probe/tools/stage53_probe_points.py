#!/usr/bin/env python3
"""Stage-53 probe attachment points: distance from each tip contact to the nearest copper of another net.

Run from the probe directory:
  python3 tools/stage53_probe_points.py            # uses the committed copper window
  python3 tools/stage53_probe_points.py --extract PATH/copper-dump.json   # refresh the window first
  python3 tools/stage53_probe_points.py --extract-earth PATH/copper-dump.json   # refresh the earthed-copper file

The earthed-copper file validation/leads/stage53-earth.txt lists stage 53's earth-referenced copper (PE, and
the SELV planes, which R38, a 0 ohm jumper, ties to PE) as simplified outlines for tools/leads.rs, which reads
it for the per-tip capacitance and setback calculations.

The window file validation/leads/stage53-copper-window.json is a cut of the stage-53 board-of-record
copper dump (board sha256 82af7bd9..., runs-native21/s53/c53int). Only geometry inside WINDOW is kept.
Read-only with respect to stage 53: nothing in the power-stage tree is written.
"""
import hashlib, json, math, sys

WINDOW = (110.0, 30.0, 220.0, 135.0)  # x0, y0, x1, y1 in stage-53 board mm
WIN_FILE = "validation/leads/stage53-copper-window.json"
EARTH_FILE = "validation/leads/stage53-earth.txt"
EARTH_NETS = ("pe", "selv_gnd", "v3v3")  # v3v3 is SELV and decoupled to selv_gnd; R38 (0 ohm) joins selv_gnd to pe
OUT_FILE = "validation/leads/stage53-probe-points.txt"
BOARD_SHA = "82af7bd93e62d1f2e6c7c2c2b971a4830bf6e09078bae3f269d8bead9a31fd27"
OUTER = ("F.Cu", "B.Cu")

# (name, net, x, y, contact radius mm, attachment). The contact radius is the
# envelope of exposed tip metal: M4 ring lugs under a screw head with washer
# (Ø9 mm), or a soldered lead end in a plated hole (fillet envelope Ø5 mm).
# Option B (2026-10-20): J5 carries both probes' TIP+ rings, J2 probe 2's TIP-,
# C22's free hole probe 1's soldered TIP-. The other free holes are listed for
# reference only.
POINTS = [
    ("J5 M4 terminal", "res_a", 132.0, 70.5, 4.5, "probe 1 and probe 2 TIP+ rings stacked, screw-on"),
    ("J2 M4 terminal", "coil_feed", 132.0, 85.5, 4.5, "probe 2 TIP- ring, screw-on"),
    ("C22 free P27.5 hole", "sw_b", 190.5, 68.2, 2.5, "probe 1 TIP- lead soldered into the unused plated hole"),
] + [
    (f"{c} free P27.5 hole", "sw_b", 190.5, y, 2.5, "unused alternative (not used by option B)")
    for c, y in (("C21", 53.2), ("C23", 83.2), ("C151", 98.2), ("C152", 113.2))
]


def inwin(pts, m=0.0):
    x0, y0, x1, y1 = WINDOW
    return any(x0 - m <= x <= x1 + m and y0 - m <= y <= y1 + m for x, y in pts)


def rnd(item):
    """Round outline coordinates to 1 um to keep the committed window small."""
    out = dict(item)
    out["pts"] = [[round(x, 3), round(y, 3)] for x, y in item["pts"]]
    if "holes" in item:
        out["holes"] = [[[round(x, 3), round(y, 3)] for x, y in h] for h in item["holes"]]
    return out


def extract(dump_path):
    raw = open(dump_path, "rb").read()
    d = json.loads(raw)
    keep = {
        "source": dump_path.split("/runs-native21/")[-1],
        "source_sha256": hashlib.sha256(raw).hexdigest(),
        "board_sha256": BOARD_SHA,
        "window_mm": WINDOW,
        "zones": [rnd(z) for z in d["zones"] if z["layer"] in OUTER and z["net"] and inwin(z["pts"])],
        "pads": [
            rnd(dict(p, layers=[l for l in p["layers"] if l in OUTER]))
            for p in d["pads"]
            if p["net"] and inwin(p["pts"]) and any(l in OUTER for l in p["layers"])
        ],
        "tracks": [t for t in d["tracks"] if t["layer"] in OUTER and t["net"] and inwin([t["a"], t["b"]], 1.0)],
        "vias": [v for v in d["vias"] if v["net"] and inwin([v["at"]], 1.0)],
    }
    with open(WIN_FILE, "w") as f:
        json.dump(keep, f, separators=(",", ":"))


def simplify(pts, tol=0.1):
    """Douglas-Peucker on a closed outline (tolerance mm); keeps the outline within tol of the original."""
    if len(pts) < 4:
        return pts

    def dp(seq):
        a, b = seq[0], seq[-1]
        best, idx = -1.0, 0
        for i in range(1, len(seq) - 1):
            d = seg_dist(seq[i], a, b)
            if d > best:
                best, idx = d, i
        if best <= tol:
            return [a, b]
        return dp(seq[: idx + 1])[:-1] + dp(seq[idx:])

    far = max(range(len(pts)), key=lambda i: math.dist(pts[0], pts[i]))
    return dp(pts[: far + 1])[:-1] + dp(pts[far:] + [pts[0]])[:-1]


def extract_earth(dump_path):
    raw = open(dump_path, "rb").read()
    d = json.loads(raw)
    lines = [
        "# Stage-53 earth-referenced copper (generated by tools/stage53_probe_points.py --extract-earth; do not edit).",
        f"# source {dump_path.split('/runs-native21/')[-1]} sha256 {hashlib.sha256(raw).hexdigest()}; board sha256 {BOARD_SHA}",
        "# nets: " + ", ".join(EARTH_NETS) + "; outlines simplified to 0.1 mm; frame KiCad x, y (down); mm.",
        "# zone NET LAYER x y x y ...   |   track NET LAYER width ax ay bx by   |   pad NET REF x y x y ...   |   via NET d x y",
    ]
    r = lambda v: f"{v:.2f}"
    for z in d["zones"]:
        if z["net"] in EARTH_NETS:
            pts = simplify([tuple(p) for p in z["pts"]])
            lines.append(f"zone {z['net']} {z['layer']} " + " ".join(r(c) for p in pts for c in p))
    for t in d["tracks"]:
        if t["net"] in EARTH_NETS:
            lines.append(f"track {t['net']} {t['layer']} {r(t['w'])} " + " ".join(r(c) for c in (*t["a"], *t["b"])))
    for q in d["pads"]:
        if q["net"] in EARTH_NETS:
            pts = simplify([tuple(p) for p in q["pts"]])
            lines.append(f"pad {q['net']} {q['ref']} " + " ".join(r(c) for p in pts for c in p))
    for v in d["vias"]:
        if v["net"] in EARTH_NETS:
            lines.append(f"via {v['net']} {r(v['d'])} {r(v['at'][0])} {r(v['at'][1])}")
    open(EARTH_FILE, "w").write("\n".join(lines) + "\n")


def seg_dist(p, a, b):
    ax, ay = a
    bx, by = b
    dx, dy = bx - ax, by - ay
    L2 = dx * dx + dy * dy
    t = 0.0 if L2 == 0 else max(0.0, min(1.0, ((p[0] - ax) * dx + (p[1] - ay) * dy) / L2))
    return math.hypot(p[0] - ax - t * dx, p[1] - ay - t * dy)


def inside(p, poly):
    x, y = p
    c = False
    n = len(poly)
    for i in range(n):
        (x1, y1), (x2, y2) = poly[i], poly[(i + 1) % n]
        if (y1 > y) != (y2 > y) and x < x1 + (y - y1) * (x2 - x1) / (y2 - y1):
            c = not c
    return c


def poly_dist(p, poly, holes=()):
    edge = min(seg_dist(p, poly[i], poly[(i + 1) % len(poly)]) for i in range(len(poly)))
    for h in holes:
        edge = min(edge, min(seg_dist(p, h[i], h[(i + 1) % len(h)]) for i in range(len(h))))
    if inside(p, poly) and not any(inside(p, h) for h in holes):
        return 0.0
    return edge


def items(w):
    for z in w["zones"]:
        yield z["net"], z["layer"], "pour", lambda p, z=z: poly_dist(p, z["pts"], z.get("holes", []))
    for q in w["pads"]:
        for layer in q["layers"]:
            yield q["net"], layer, f"pad {q['ref']}", lambda p, q=q: poly_dist(p, q["pts"])
    for t in w["tracks"]:
        yield t["net"], t["layer"], "track", lambda p, t=t: max(0.0, seg_dist(p, t["a"], t["b"]) - t["w"] / 2)
    for v in w["vias"]:
        yield v["net"], "F.Cu", "via", lambda p, v=v: max(0.0, math.dist(p, v["at"]) - v["d"] / 2)
        yield v["net"], "B.Cu", "via", lambda p, v=v: max(0.0, math.dist(p, v["at"]) - v["d"] / 2)


def main():
    if len(sys.argv) == 3 and sys.argv[1] == "--extract":
        extract(sys.argv[2])
    if len(sys.argv) == 3 and sys.argv[1] == "--extract-earth":
        extract_earth(sys.argv[2])
        return
    w = json.load(open(WIN_FILE))
    lines = [
        "Stage-53 probe attachment points (generated by tools/stage53_probe_points.py; do not edit).",
        f"Board of record sha256 {w['board_sha256']}; copper dump {w['source']} sha256 {w['source_sha256']}.",
        "Distances are plan-view edge-to-edge, from the tip-metal envelope (circle of the stated radius) to the",
        "nearest copper of another net on F.Cu / B.Cu (pads are exposed; pours and tracks are under solder mask,",
        "which is not credited as insulation). Component bodies are not in the copper dump.",
        "",
    ]
    for name, net, x, y, rc, how in POINTS:
        p = (x, y)
        own = sorted({lay for n, lay, kind, f in items(w) if n == net and f(p) <= rc})
        best = {}
        for n, lay, kind, f in items(w):
            if n == net or not n or lay not in OUTER:
                continue
            d = f(p)
            key = (n, lay)
            if key not in best or d < best[key][0]:
                best[key] = (d, kind)
        near = sorted(best.items(), key=lambda kv: kv[1][0])[:4]
        lines.append(f"{name} ({net}) at ({x}, {y}); {how}; tip envelope radius {rc} mm")
        lines.append(f"  own-net ({net}) copper within the envelope on: {', '.join(own) if own else 'NONE'}")
        for (n, lay), (d, kind) in near:
            lines.append(f"  nearest {n:14s} {lay}: centre {d:6.2f} mm, envelope edge {d - rc:6.2f} mm ({kind})")
        lines.append("")
    a, b = POINTS[0], POINTS[1]
    lines.append(
        f"J5-J2 centre spacing {math.dist(a[2:4], b[2:4]):.2f} mm; C22 free hole to J5 centre {math.dist((190.5, 68.2), a[2:4]):.2f} mm."
    )
    open(OUT_FILE, "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
