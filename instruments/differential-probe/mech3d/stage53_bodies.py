"""Stage-53 component bodies as axis-aligned boxes, for the dock and spine clearance gates.

Run from the probe directory with the mech3d environment (CadQuery reads the STEP):

    mech3d/.venv/bin/python mech3d/stage53_bodies.py PATH/TO/s53/c53int

It reads the board of record's own 3-D export (board.step, written by kicad-cli from
section.kicad_pcb) and section.kicad_pcb, and writes validation/leads/stage53-bodies.txt.
Read-only with respect to stage 53.

Frame: X = KiCad x, Y = KiCad y (down), Z = height above the board top, all mm.
Each STEP solid becomes one box; the label is the footprint whose courtyard box
contains the solid's plan centre. Solids that do not rise above the board top
(the board itself, pads) are dropped. Footprints without a 3-D model (J2/J5, the
Würth 7466004R; J3/J11, whose models were missing at export) are listed so that
tools/leads.rs can add them from datasheet dimensions.
"""
import hashlib
import math
import re
import sys
from pathlib import Path

import cadquery as cq

OUT = Path("validation/leads/stage53-bodies.txt")
BOARD_SHA = "82af7bd93e62d1f2e6c7c2c2b971a4830bf6e09078bae3f269d8bead9a31fd27"


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def footprints(pcb_text):
    """(ref, x0, y0, x1, y1, has_model) courtyard boxes in board coordinates."""
    starts = [m.start() for m in re.finditer(r"\n\t\(footprint \"", pcb_text)]
    starts.append(len(pcb_text))
    out = []
    num = r"(-?[0-9.]+)"
    for a, b in zip(starts, starts[1:]):
        blk = pcb_text[a:b]
        at = re.search(r"\(at " + num + " " + num + r"(?: " + num + r")?\)", blk)
        ref = re.search(r"\(property \"Reference\" \"([^\"]+)\"", blk)
        if not at or not ref:
            continue
        fx, fy = float(at.group(1)), float(at.group(2))
        rot = math.radians(float(at.group(3) or 0.0))
        flipped = '(layer "B.Cu")' in blk[:400]
        pts = []
        for g in re.finditer(r"\((fp_line|fp_rect|fp_circle|fp_poly)(.*?)\(layer \"([FB])\.CrtYd\"\)", blk, re.S):
            body = g.group(2)
            xy = [(float(x), float(y)) for x, y in re.findall(r"\((?:start|end|center|xy) " + num + " " + num + r"\)", body)]
            if g.group(1) == "fp_circle" and len(xy) == 2:
                (cx, cy), (ex, ey) = xy
                r = math.hypot(ex - cx, ey - cy)
                xy = [(cx - r, cy - r), (cx + r, cy + r), (cx - r, cy + r), (cx + r, cy - r)]
            pts += xy
        if not pts:
            continue
        glob = []
        for lx, ly in pts:
            # KiCad stores footprint graphics unrotated; rotation is counter-clockwise on screen (y down).
            gx = fx + lx * math.cos(rot) + ly * math.sin(rot)
            gy = fy - lx * math.sin(rot) + ly * math.cos(rot)
            glob.append((gx, gy))
        xs, ys = [p[0] for p in glob], [p[1] for p in glob]
        has_model = "(model " in blk
        out.append((ref.group(1), min(xs), min(ys), max(xs), max(ys), has_model, flipped))
    return out


def main():
    src = Path(sys.argv[1])
    pcb, step = src / "section.kicad_pcb", src / "board.step"
    assert sha(pcb) == BOARD_SHA, "section.kicad_pcb is not the board of record"
    fps = footprints(pcb.read_text())
    shape = cq.importers.importStep(str(step))
    boxes = []
    for so in shape.solids().vals():
        bb = so.BoundingBox()
        if bb.xlen > 250 and bb.ylen > 150:  # the board itself
            continue
        boxes.append(bb)
    # kicad-cli places the board's underside at z = 0; the stackup is 1.6 mm, and the
    # component models sit on z = 1.6 (plus their own standoff).
    top = 1.6
    lines = [
        "# Stage-53 component bodies (generated by mech3d/stage53_bodies.py; do not edit).",
        f"# board {pcb.name} sha256 {sha(pcb)}; step {step.name} sha256 {sha(step)}",
        "# frame: X = KiCad x, Y = KiCad y (down), Z = height above the board top; mm.",
        "# body ref x0 y0 z0 x1 y1 z1  (axis-aligned box of one STEP solid)",
    ]
    rows = []
    for bb in boxes:
        z0, z1 = bb.zmin - top, bb.zmax - top
        if z1 <= 0.05:
            continue
        x0, x1 = bb.xmin, bb.xmax
        y0, y1 = -bb.ymax, -bb.ymin
        cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
        hits = [f for f in fps if f[1] - 0.01 <= cx <= f[3] + 0.01 and f[2] - 0.01 <= cy <= f[4] + 0.01]
        hits.sort(key=lambda f: (f[3] - f[1]) * (f[4] - f[2]))
        ref = hits[0][0] if hits else "?"
        rows.append((ref, x0, y0, z0, x1, y1, z1))
    rows.sort(key=lambda r: (r[0], r[1], r[2]))
    for r in rows:
        lines.append("body {} {:.3f} {:.3f} {:.3f} {:.3f} {:.3f} {:.3f}".format(*r))
    lines.append("# footprints without a 3-D body in the STEP: ref x0 y0 x1 y1 (courtyard)")
    have = {r[0] for r in rows}
    for f in sorted(fps):
        if not f[5] or f[0] not in have:
            if f[0].startswith("H") or f[6]:
                continue  # mounting holes and bottom-side parts carry no top-side body
            lines.append("nomodel {} {:.3f} {:.3f} {:.3f} {:.3f}".format(f[0], *f[1:5]))
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(rows)} bodies written to {OUT}")


if __name__ == "__main__":
    main()
